/* 曲（GDD 15.4）。

   盤に音を添える。狙いは、覇王伝のころの音――FM音源とPSGで鳴らした、和の音階に
   よる静かな調べである。録音を持ち込むのではなく、その場で合成する（音の出自が
   同じなので、むしろ寄せやすい。何より一枚物の盤を重くしない）。

   ここは「何を鳴らすか」だけを持つ。音を出す段（gakki.js）とは切り分けてある。
   小節ごとに音符の並びを返す純粋な関数なので、音の出ない所（試験）でも検められる。

   音階について。

     都節（みやこぶし）  レ ミ♭ ソ ラ シ♭   … 半音を含む陰の調べ。政務と城攻めに
     律（りつ）          レ ミ ソ ラ シ      … 雅楽の明るい方。関白の参内に
     民謡               レ ファ ソ ラ ド     … 陽の調べ。野戦の勢いに

   音の高さは十二平均律の番号で持つ（六十＝中央のハ）。 */

// 音の名から番号へ。レ＝62（中央のハの上の二度）
export const 音名 = { レ: 62, ミb: 63, ミ: 64, ファ: 65, ソ: 67, ラ: 69, シb: 70, シ: 71, ド: 72 };

export const 音階 = {
  都節: [62, 63, 67, 69, 70],                 // レ ミ♭ ソ ラ シ♭
  律: [62, 64, 67, 69, 71],                   // レ ミ ソ ラ シ
  民謡: [62, 65, 67, 69, 72],                 // レ ファ ソ ラ ド
};

// 音階の n 番目（八度をまたいでも良い）
export const 度 = (階, n) => {
  const 長 = 階.length;
  const 八 = Math.floor(n / 長);
  return 階[((n % 長) + 長) % 長] + 八 * 12;
};

/* 曲の作り。

   それぞれ「小節番号を渡すと、その小節の音符が返る」形にしてある。
   音符は { 楽器, 音, 位, 長, 強 }。位と長は拍で数える（四分音符＝一拍）。 */

const 揺 = (i, n) => ((i * 2654435761) % n);     // 小節ごとの控えめな揺らぎ（賽は使わない）

/* 一、政務・初期「国づくり」

   守護代の家から始める頃の調べ。琴の分散和音を敷き、尺八が間を置いて歌う。
   長く聴くものだから、音数は少なく、太鼓は入れない。 */
const 政務 = {
  名: "国づくり", 拍: 66, 拍子: 4, 小節: 8, 音階: 音階.都節, 根: 0,
  音符(小) {
    const S = this.音階, o = [];
    // 琴の敷き（四分で下から上へ、小節ごとに形を変える）
    const 型 = [[0, 2, 4, 2], [0, 3, 4, 3], [-1, 2, 4, 2], [0, 2, 5, 2]][小 % 4];
    型.forEach((d, i) => o.push({ 楽器: "琴", 音: 度(S, d) - 12, 位: i, 長: 1.1, 強: i === 0 ? 0.5 : 0.34 }));
    // 尺八の歌（二小節に一度、間を置いて）
    if (小 % 2 === 0) {
      const 節 = [[4, 0, 2.2], [5, 1.5, 1.4], [3, 2.5, 1.2]];
      const 移 = 揺(小, 3) - 1;
      for (const [d, 位, 長] of 節) o.push({ 楽器: "尺八", 音: 度(S, d + 移), 位, 長, 強: 0.3 });
    }
    // 終いの小節に、低い余韻
    if (小 === this.小節 - 1) o.push({ 楽器: "琴", 音: 度(S, 0) - 24, 位: 3, 長: 2, 強: 0.4 });
    return o;
  },
};

/* 二、政務・関白「参内」

   位人臣を極めた家の調べ。笙の合竹（あいたけ）を長く伸ばし、篳篥が上をなぞる。
   雅楽であるから拍は緩く、鉦がときおり間を刻む。 */
const 関白 = {
  名: "参内", 拍: 52, 拍子: 4, 小節: 8, 音階: 音階.律, 根: 0,
  音符(小) {
    const S = this.音階, o = [];
    // 笙の合竹。三つ重ねて長く伸ばす
    const 根 = 度(S, [0, 1, 0, 3][小 % 4]);
    for (const d of [0, 4, 7]) o.push({ 楽器: "笙", 音: 根 + d, 位: 0, 長: 4, 強: 0.16 });
    // 篳篥の旋律
    if (小 % 2 === 1) {
      const 節 = [[2, 0.5, 1.6], [3, 2, 1.2], [1, 3.2, 0.8]];
      for (const [d, 位, 長] of 節) o.push({ 楽器: "篳篥", 音: 度(S, d + 揺(小, 2)), 位, 長, 強: 0.26 });
    }
    // 鉦。四小節に一度
    if (小 % 4 === 0) o.push({ 楽器: "鉦", 音: 度(S, 4) + 12, 位: 0, 長: 2.6, 強: 0.24 });
    return o;
  },
};

/* 三、政務・征夷大将軍「幕府」

   天下を差配する家の調べ。琴と笙に、ゆるやかな太鼓が加わる。
   威はあるが騒がしくはない――政務の画面は長く見るものである。 */
const 将軍 = {
  名: "幕府", 拍: 60, 拍子: 4, 小節: 8, 音階: 音階.都節, 根: 0,
  音符(小) {
    const S = this.音階, o = [];
    const 型 = [[0, 4, 2, 4], [0, 3, 2, 3]][小 % 2];
    型.forEach((d, i) => o.push({ 楽器: "琴", 音: 度(S, d) - 12, 位: i, 長: 1.05, 強: i === 0 ? 0.48 : 0.3 }));
    o.push({ 楽器: "笙", 音: 度(S, 0) - 12, 位: 0, 長: 4, 強: 0.13 });
    o.push({ 楽器: "笙", 音: 度(S, 3) - 12, 位: 0, 長: 4, 強: 0.1 });
    // 太鼓は一拍目と三拍目に軽く
    o.push({ 楽器: "太鼓", 音: 48, 位: 0, 長: 0.5, 強: 0.42 });
    if (小 % 2 === 1) o.push({ 楽器: "太鼓", 音: 50, 位: 2, 長: 0.4, 強: 0.26 });
    if (小 % 4 === 2) {
      for (const [d, 位, 長] of [[4, 1, 1.4], [2, 2.6, 1.2]]) o.push({ 楽器: "尺八", 音: 度(S, d), 位, 長, 強: 0.26 });
    }
    return o;
  },
};

/* 四、野戦「押し太鼓」

   陣太鼓が刻み、法螺が吼える。音階は陽の民謡調で、勢いを出す。
   戦の間ずっと鳴るので、四小節で回る短い作りにしてある。 */
const 野戦 = {
  名: "押し太鼓", 拍: 132, 拍子: 4, 小節: 4, 音階: 音階.民謡, 根: 0,
  音符(小) {
    const S = this.音階, o = [];
    // 陣太鼓。裏に軽い打ちを混ぜる
    for (let i = 0; i < 4; i++) o.push({ 楽器: "太鼓", 音: i % 2 === 0 ? 46 : 52, 位: i, 長: 0.4, 強: i % 2 === 0 ? 0.5 : 0.3 });
    o.push({ 楽器: "太鼓", 音: 54, 位: 2.5, 長: 0.3, 強: 0.22 });
    if (小 % 2 === 1) o.push({ 楽器: "太鼓", 音: 54, 位: 3.5, 長: 0.3, 強: 0.24 });
    // 笛の動機
    const 節 = [[[4, 0, 0.8], [3, 1, 0.6], [4, 2, 1.4]], [[5, 0, 0.7], [4, 1.5, 0.7], [2, 2.5, 1.2]]][小 % 2];
    for (const [d, 位, 長] of 節) o.push({ 楽器: "笛", 音: 度(S, d), 位, 長, 強: 0.28 });
    // 法螺は四小節に一度、頭で
    if (小 % 4 === 0) o.push({ 楽器: "法螺", 音: 度(S, 0) - 12, 位: 0, 長: 2.4, 強: 0.3 });
    return o;
  },
};

/* 五、城攻め「寄せ太鼓」

   囲みの戦は待つ戦である。重い太鼓が間を置いて鳴り、低い笛が這う。
   速さは遅く、音は暗い（都節の下の方を使う）。 */
const 城攻め = {
  名: "寄せ太鼓", 拍: 92, 拍子: 4, 小節: 8, 音階: 音階.都節, 根: 0,
  音符(小) {
    const S = this.音階, o = [];
    o.push({ 楽器: "太鼓", 音: 43, 位: 0, 長: 0.9, 強: 0.55 });
    o.push({ 楽器: "太鼓", 音: 45, 位: 2, 長: 0.6, 強: 0.3 });
    if (小 % 2 === 1) o.push({ 楽器: "太鼓", 音: 48, 位: 3.25, 長: 0.4, 強: 0.24 });
    // 低い笛。三小節に一度、長く
    if (小 % 3 === 0) {
      for (const [d, 位, 長] of [[0, 0.5, 2.2], [1, 3, 1.2]]) o.push({ 楽器: "尺八", 音: 度(S, d) - 12, 位, 長, 強: 0.3 });
    }
    // 琴は撥ねず、間を埋めるだけ
    if (小 % 2 === 0) o.push({ 楽器: "琴", 音: 度(S, 0) - 24, 位: 1, 長: 1.6, 強: 0.3 });
    return o;
  },
};

/* 六、天下分け目

   一度きりの決戦である。太鼓・法螺・琴・笙を重ね、いちばん厚く鳴らす。
   八小節のうち後半で音を増し、寄せては返す形にしてある。 */
const 分け目 = {
  名: "天下分け目", 拍: 116, 拍子: 4, 小節: 8, 音階: 音階.都節, 根: 0,
  音符(小) {
    const S = this.音階, o = [];
    const 後半 = 小 >= 4;
    for (let i = 0; i < 4; i++) {
      o.push({ 楽器: "太鼓", 音: i === 0 ? 43 : 50, 位: i, 長: 0.45, 強: i === 0 ? 0.55 : 0.3 });
      if (後半) o.push({ 楽器: "太鼓", 音: 55, 位: i + 0.5, 長: 0.25, 強: 0.2 });
    }
    const 型 = [[0, 3, 4, 3], [0, 4, 5, 4]][小 % 2];
    型.forEach((d, i) => o.push({ 楽器: "琴", 音: 度(S, d) - 12, 位: i, 長: 0.9, 強: 0.36 }));
    o.push({ 楽器: "笙", 音: 度(S, 0) - 24, 位: 0, 長: 4, 強: 後半 ? 0.16 : 0.1 });
    if (小 % 4 === 0) o.push({ 楽器: "法螺", 音: 度(S, 0) - 12, 位: 0, 長: 2.6, 強: 0.34 });
    if (後半) {
      const 節 = [[5, 0.5, 1.2], [4, 2, 1], [6, 3, 1]];
      for (const [d, 位, 長] of 節) o.push({ 楽器: "尺八", 音: 度(S, d), 位, 長, 強: 0.3 });
    }
    return o;
  },
};

export const 曲 = { 政務, 関白, 将軍, 野戦, 城攻め, 分け目 };

/* 場面から曲を選ぶ（GDD 15.4）。

   政務は位で変える――守護代の頃、関白に昇った頃、征夷大将軍に任じられた頃で
   調べが改まる。戦は野と城で分け、天下分け目だけは別に立てる。 */
export function 場面の曲(場面, { 位 } = {}) {
  if (場面 === "分け目") return "分け目";
  if (場面 === "城攻め") return "城攻め";
  if (場面 === "野戦") return "野戦";
  if (場面 === "政務") {
    if (位 === "征夷大将軍") return "将軍";
    if (位 === "関白" || 位 === "太政大臣") return "関白";
    return "政務";
  }
  return null;
}
