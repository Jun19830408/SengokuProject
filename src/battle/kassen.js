/* ==========================================================================
   合戦（筋書きのある一戦）── GDD 8.9

   キャンペーンの合戦は、盤も布陣も、そのときの家と兵から組み立てる。
   ここで扱うのはその逆で、地形も布陣も史実に定めた一戦である。
   遊ぶ側は西軍か東軍かを選び、その一戦だけを戦う。国も月も暦も無い。

   旗色は三つ。遊ぶ側が青、敵が赤、去就の定まらぬ隊が黄である。
   黄の隊は盤の上にいるが、戦には加わらない（日和見）。定められた条件が
   揃ったとき、青か赤のどちらかに決まって初めて動き出す。
   ========================================================================== */

export const 合戦一覧 = [関ヶ原];
export const 合戦を探す = (id) => 合戦一覧.find((k) => k.id === id) || null;

const 黄の色 = "#D9A62A";
const 旗の色 = { 西: "#2F5D8C", 東: "#B0483C" };

/* ------------------------------------------------------------ 盤を組み立てる */
export function 合戦を仕立てる(id, 味方旗) {
  const k = 合戦を探す(id);
  if (!k) return null;
  筋書きの野を組む(k.地形);
  const 敵旗 = 味方旗 === "西" ? "東" : "西";
  const P = [], E = [];
  for (const d of k.布陣) {
    /* 黄の隊は、名目のうえでは西軍である。決まるまではどちらの手勢としても
       数えないので、ここで置く側は「もし何も起きなければ属していた側」でよい。 */
    const 実旗 = d.旗 === "黄" ? "西" : d.旗;
    const side = 実旗 === 味方旗 ? "P" : "E";
    const 直 = Math.round(d.兵 * 0.3), 在 = d.兵 - 直;
    const gen = {
      id: d.id, name: d.名, lead: d.将.lead, valor: d.将.valor, wit: d.将.wit,
      gov: d.将.gov, unity: d.将.unity, retinue: 直, retTrain: 76,
      rost: newRoster(直, `${d.id}-直`, d.兵科),
      locRost: newRoster(在, `${d.id}-在`, d.兵科),
      lord: !!d.大将,
    };
    const c = makeCorps(side, gen, 直, 在, 76, 70, d.x, d.y, d.向き,
      d.旗 === "黄" ? 黄の色 : 旗の色[d.旗]);
    c.筋 = { 旗: d.旗, 属: d.属 || null, 主: !!d.主, 押さえ: !!d.押さえ,
      目付: !!d.目付, 続く: !!d.続く, 家康: !!d.家康, 要: !!d.要, 島津: !!d.島津,
      備: d.備 || null, 当: d.当 || null, 先鋒: !!d.先鋒 };
    /* 戦わぬと決めている隊。盤の上にはいるが、自分からは動かず攻めない。
       攻められれば戦う――そこが日和見（黄）と違うところである。 */
    if (d.不戦) { c.不戦 = true; c.order = "待機"; }
    if (d.旗 === "黄") { c.日和見 = true; c.order = "待機"; c.seen = true; }
    if (d.押さえ) c.縛り = "南宮山";
    /* 家康の旗本三万は、本陣が動くまで桃配山に控える（GDD 8.9）。
       これを初めから前へ出すと、東軍十万が一度に押し寄せ、西軍は
       小早川を待つ間もなく潰れる。史実でも旗本が動いたのは昼近くである。 */
    if (/徳川/.test(d.名) || d.二の手) c.控え = true;
    c.auto = side !== "P";                        // 遊ぶ側の隊は手ずから動かす
    placeSquads(c, true);
    (side === "P" ? P : E).push(c);
  }
  /* 寄せ手は、先に仕掛けた側――関ヶ原では東軍である。 */
  const 攻 = 敵旗 === "東" ? "E" : "P";
  const b = createBattle(P, E, 味方旗 === "東" ? "P" : "E");
  b.weather = k.天気 || "曇";
  /* 一回で遊びきる戦であるから、運びを緩める。
     損害は半ば近くまで、足は六割ほどに落とす。街道の合戦のままでは、
     布陣を見終わらぬうちに片が付いてしまう。 */
  b.損の手加減 = k.損 || 0.11;
  b.足の手加減 = k.足 || 0.5;
  b.dusk = k.刻 || 2400;
  b.attacker = 攻;
  b.phase = "deploy";
  b.筋書き = {
    id: k.id, 名: k.名, 味方旗, 敵旗,
    小早川: "未", 南宮山: "未",
    家康前進: false, 問鉄砲: false,
    問い: null, 済んだ問い: {}, 報: [],
  };
  /* 引き際の目安になる「初めの兵」から、去就の定まらぬ隊を外す（GDD 8.9）。

     createBattle は盤に載った兵をそのまま数える。黄の四万五千まで数えると、
     西軍二万八千は「初めの五分の一」を割るのがあまりに早く、半分も損ぜぬうちに
     軍を退いてしまう。戦っている兵だけを、初めの兵とする。 */
  const 数 = (side) => b.corps.filter((c) => c.side === side && !c.日和見 && !c.不戦)
    .reduce((a, c) => a + corpsMen(c), 0);
  b.initial = { P: 数("P"), E: 数("E") };
  b.進行 = 筋書きを進める;
  b.log.push({ t: 0, text: k.詞 });
  b.log.push({ t: 0, text: `遊ぶ側は${味方旗}軍。黄の隊は去就が定まっていない。` });
  return { b, 筋書き: k };
}

export function 合戦を畳む() { 筋書きを解く(); }

/* ------------------------------------------------------------ 勘定の助け */
const 生きた = (b, f) => b.corps.filter((c) => !c.dead && !c.destroyed && f(c));
const 兵数 = (list) => list.reduce((a, c) => a + corpsMen(c), 0);
const 旗の隊 = (b, 旗) => b.corps.filter((c) => c.筋 && c.筋.旗 === 旗);
const 属の隊 = (b, 属) => b.corps.filter((c) => c.筋 && c.筋.属 === 属);

/* 初めの兵に対して、いまどれだけ残っているか。

   数えるのは「いま戦列に立っている隊」だけである。控えの旗本も、南宮山の
   押さえも、まだ戦っていないのだから戦況には映らない。これを数に入れると、
   東軍十万のうち五万が手つかずのまま分母に居座り、西軍がどれだけ押しても
   「東軍は健在」と出る。松尾山から見えているのは前線だけである。 */
function 残り(b, 旗) {
  const 隊 = 旗の隊(b, 旗).filter((c) => !c.日和見 && !c.控え && !c.縛り && !c.不戦);
  const 初 = 隊.reduce((a, c) => a + c.squads.reduce((s, q) => s + q.max, 0), 0);
  return 初 > 0 ? 兵数(隊.filter((c) => !c.dead && !c.destroyed)) / 初 : 1;
}

/* 西軍の柱となる三つの備（石田・宇喜多・大谷）の様子。
   家康を前へ出すか、問鉄砲を撃つかは、この三つがどこまで削れたかで決まる。 */
const 三つの備 = {
  石田: /石田三成|島左近|蒲生郷舎|織田信高/,
  宇喜多: /宇喜多秀家|明石全登|長船吉行|本多政重/,
  大谷: /大谷吉継|大谷吉勝|木下頼継|戸田重政|平塚為広/,
};
function 備の様子(b) {
  const 出 = {};
  for (const k in 三つの備) {
    const l = b.corps.filter((c) => 三つの備[k].test(c.name));
    const 生 = l.filter((c) => !c.dead && !c.destroyed);
    const 兵 = 生.reduce((a, c) => a + corpsMen(c), 0);
    出[k] = {
      崩れ: l.some((c) => c.routed || c.destroyed || c.dead),
      気: 兵 > 0 ? 生.reduce((a, c) => a + c.morale * corpsMen(c), 0) / 兵 : 0,
      残: l.length ? 兵 / l.reduce((a, c) => a + c.squads.reduce((t, q) => t + q.max, 0), 0) : 0,
    };
  }
  return 出;
}

/* 東軍の先手のうち、崩れた（敗走・壊滅）隊の数。小早川が西へ起つ目印である。 */
const 先手の崩れ = (b) => b.corps.filter((c) => /黒田長政|細川忠興|福島正則/.test(c.name)
  && (c.routed || c.destroyed || c.dead)).length;

const 報せる = (b, text, 種 = "info") => {
  b.筋書き.報.push({ t: b.t, text, 種 });
  b.log.push({ t: b.t, text });
  b.notices = b.notices || [];
  b.notices.push({ t: b.t, kind: 種 === "凶" ? "bad" : 種 === "吉" ? "good" : "info", text });
};

/* ------------------------------------------------------ 黄の隊が旗色を決める */
function 旗を決める(b, 属, 決, 訳) {
  const s = b.筋書き;
  s.決めた刻 = b.t;
  const 味方側 = "P";
  for (const c of 属の隊(b, 属)) {
    if (!c.日和見) continue;
    c.日和見 = false;
    c.筋.旗 = 決;
    c.side = 決 === s.味方旗 ? "P" : "E";
    c.color = 旗の色[決];
    c.morale = clamp(c.morale - 6, 20, 100);      // 旗を翻すのは楽なことではない
    c.auto = c.side !== 味方側 || !!b.委ねた;
    c.order = "待機";
    placeSquads(c, true);
  }
  報せる(b, 訳, 決 === s.味方旗 ? "吉" : "凶");
}

/* --------------------------------------------------------------- 問いを出す */
function 問う(b, id, 文, 諾文, 否文) {
  const s = b.筋書き;
  if (s.済んだ問い[id] || s.問い) return false;
  s.問い = { id, 文, 諾文: 諾文 || "そうする", 否文: 否文 || "やめておく" };
  return true;
}

export function 合戦の問いに答える(b, 諾) {
  const s = b.筋書き; if (!s || !s.問い) return;
  const q = s.問い; s.問い = null; s.済んだ問い[q.id] = 諾 ? "諾" : "否";
  if (!諾) { 報せる(b, `${q.見出し || "献策"}は用いなかった。`); return; }
  if (q.id === "家康前進") 家康を進める(b);
  if (q.id === "問鉄砲") 問鉄砲を撃つ(b);
  if (q.id === "松尾山へ備える") 松尾山へ備える(b);
  if (q.id === "島津の退き口") 島津の退き口(b);
}

/* ------------------------------------------------------------------ 手立て */
function 家康を進める(b) {
  const s = b.筋書き;
  s.家康前進 = true; s.前進の刻 = b.t;
  for (const c of b.corps) if (/徳川/.test(c.name)) c.控え = false;
  for (const c of b.corps) {
    if (!c.筋 || !c.筋.家康) continue;
    /* 桃配山から陣場野へ。松尾山を睨む位置まで三千歩ほど前へ出る。 */
    issueOrder(b, c, "前進", { x: c.x - 2600, y: c.y + 300 });
    c.morale = Math.min(100, c.morale + 4);
  }
  for (const c of b.corps) if (c.筋 && c.筋.旗 === "東" && !c.日和見) c.morale = Math.min(100, c.morale + 3);
  報せる(b, "家康が桃配山を下り、陣場野へ本陣を進めた。全軍の目が本陣を見ている。", "吉");
}

function 問鉄砲を撃つ(b) {
  const s = b.筋書き;
  s.問鉄砲 = true;
  報せる(b, "松尾山の麓へ鉄砲が撃ちかけられた。小早川の去就を問うたのである。");
  小早川を決める(b, true);
}

function 松尾山へ備える(b) {
  for (const c of b.corps) {
    if (c.side !== "P" || c.日和見) continue;
    if (!c.筋 || c.筋.旗 !== "西") continue;
    if (!c.筋.要 && !/大谷|戸田|木下|平塚/.test(c.name)) continue;
    issueOrder(b, c, "前進", { x: c.x - 200, y: c.y + 1400 });   // 松尾山へ正面を向ける
  }
  報せる(b, "大谷勢が松尾山へ正面を向けた。山が動いても、受け止める構えである。", "吉");
}

/* 島津の退き口。正面の敵中を突いて東へ抜ける。 */
function 島津の退き口(b) {
  const 島 = b.corps.filter((c) => c.筋 && c.筋.島津 && !c.dead && !c.destroyed);
  for (const c of 島) {
    c.不戦 = false;
    c.order = "突撃"; c.formation = "鋒矢";
    c.auto = c.side !== "P" || !!b.委ねた;
    issueOrder(b, c, { order: "突撃", tx: Math.min(FIELD.w - 60, c.x + 4200), ty: c.y });
    c.morale = Math.min(100, c.morale + 14);
    placeSquads(c, true);
  }
  報せる(b, "島津義弘、正面の敵中へ突き入る。退くに退けぬなら、敵の中を抜けるほかない。", "吉");
}
/* -------------------------------------------------------- 小早川の去就を決める

   東へ傾くのは易く、西へ起つのは難い。
   秀秋は前の年から家康と誼を通じ、家老の稲葉正成・平岡頼勝も東に傾いていた。
   陣中には家康の目付・奥平貞治がいる。西軍として起つには、
     一、大谷勢が健在で、松尾山の正面を固めていること
     二、東軍が目に見えて押されていること
     三、目付が討たれていること
   の三つが要る。 */
function 小早川を決める(b, 問われた) {
  const s = b.筋書き;
  if (s.小早川 !== "未") return;
  const 大谷 = b.corps.filter((c) => c.筋 && c.筋.旗 === "西" && /大谷|戸田|木下|平塚/.test(c.name));
  const 大谷の残 = 大谷.length
    ? 兵数(大谷.filter((c) => !c.dead && !c.destroyed)) / 大谷.reduce((a, c) => a + c.squads.reduce((t, q) => t + q.max, 0), 0) : 0;
  const 山の麓 = b.corps.filter((c) => c.筋 && c.筋.旗 === "西" && !c.dead && !c.destroyed
    && Math.hypot(c.x - 1812, c.y - 4045) < 2400).length;          // 松尾山の頂まわり
  const 東の残 = 残り(b, "東"), 西の残 = 残り(b, "西");
  const 三成 = b.corps.find((c) => /石田三成/.test(c.name));
  const 旗頭健在 = !!(三成 && !三成.dead && !三成.destroyed && corpsMen(三成) > 0 && 三成.morale >= 50);

  /* 西軍として起つ条件（GDD 8.9）。四つとも揃って初めて山が動く。

     一、東軍の先手（黒田長政・細川忠興・福島正則）のうち二隊以上が崩れること
     二、大谷勢が健在であること（松尾山の正面が崩れていない）
     三、松尾山の麓を西軍が固めていること（二隊以上）
     四、石田三成が健在で、士気を保っていること

     一が肝である。秀秋が見ているのは戦況であって兵の数ではない。
     東軍の先手が崩れる――目の前でそれが起きて初めて、山は西へ傾く。

     ここを緩めると、山はたやすく西へ転ぶ。秀秋は前の年から家康と誼を通じ、
     家老の稲葉正成・平岡頼勝も東に傾いており、陣中には家康の目付（奥平貞治）
     までいた。西へ起つのは、そのすべてを覆すということである。 */
  const 西へ = 先手の崩れ(b) >= 2 && 大谷の残 >= 0.70 && 山の麓 >= 2 && 旗頭健在;
  if (西へ) {
    s.小早川 = "西";
    旗を決める(b, "小早川", "西",
      "松尾山が動いた。小早川秀秋、西軍として山を下る。");
    return;
  }
  if (!問われた) return;             // 問われていないなら、まだ決めない
  /* 問鉄砲を受けた。ここで決まる。

     西へ起つ条件は上で見た三つ（大谷健在・麓の備え・東軍の劣勢・目付の討死）で
     あって、それが揃っていないなら東へ傾く。秀秋は前の年から家康と誼を通じ、
     家老の稲葉正成と平岡頼勝も東に傾いていた。中立のまま山に留まるという目は、
     鉄砲を撃ちかけられた以上もう無い。 */
  s.小早川 = "東";
  旗を決める(b, "小早川", "東",
    "松尾山が動いた。小早川秀秋、旗を翻して大谷勢の側面へ雪崩れ落ちる。");
}

/* ------------------------------------------- 南宮山と、その押さえの手が離れる

   南宮山の毛利勢は西軍だが、吉川広家が道を塞いでいるあいだは動かない。
   これを押さえる東軍六隊も、山の去就が知れぬまま持ち場を離れられない。

   松尾山が動けば、戦の形が定まる。そのとき両方の手が同時に離れる。
   （もとは南宮山にも独自の分岐を置いていたが、遊ぶ側の求めにより、
     島津と同じ「小早川が動いたら動かせる」に揃えた。） */
function 南宮山の手を離す(b) {
  const s = b.筋書き;
  if (s.南宮山 !== "未" || s.小早川 === "未") return;
  if (b.t < (s.決めた刻 || 0) + 30) return;
  s.南宮山 = "解けた";
  for (const c of 属の隊(b, "南宮山")) {
    if (!c.不戦) continue;
    c.不戦 = false; c.据え置き = null;
    c.auto = c.side !== "P" || !!b.委ねた;
    c.order = "待機";
  }
  報せる(b, "松尾山が動いた。南宮山の毛利勢は、ようやく山を下りられる。",
    s.味方旗 === "西" ? "吉" : "凶");
  押さえを解く(b, "松尾山が動いた。南宮山の押さえに就いていた六隊も、手が離れる。");
}

/* ------------------------------------------------------------ 押さえを解く

   南宮山の押さえに当たる東軍の六隊は、山の去就が分からぬあいだ、その場を
   離れられない。背に一万五千の毛利勢を負ったまま野へ出るのは、采配ではなく
   自棄である。山の去就が定まって初めて、手が離れる。 */
function 押さえを解く(b, 文) {
  for (const c of b.corps) {
    if (!c.縛り) continue;
    c.縛り = null;
    c.手が離れた = true;
  }
  報せる(b, 文, "吉");
}

/* 遊ぶ側がこの隊に下知できるか。できないなら訳を返す。 */
export function 指図の縛り(b, c) {
  if (!b || !b.筋書き || !c) return null;
  if (c.日和見) return `${c.name}はまだ旗色を決めていない。下知は届かぬ。`;
  if (c.不戦) return `${c.name}は備を固めたまま動かぬ。三成の再三の催促にも応じなかった。`;
  if (!c.縛り) return null;
  if (b.筋書き.南宮山 !== "未") return null;
  return "南宮山の様子がわからぬ。ここを離れるわけにはいかぬ。";
}

/* ---------------------------------------------------------- 備ごとの差配

   関ヶ原は、隊ごとの小競り合いではなく備どうしのぶつかり合いであった。
   采配に任せきりにすると、隊はそれぞれ「いちばん近い空いた敵」を選ぶので、
   島左近のような小さな隊が単独で前へ出て潰され、石田本隊は手つかずのまま
   残る。測ると、西軍の小さな隊が三割まで削られる一方、宇喜多秀家隊は
   九割八分を保っていた。それでは備の体を成さない。

   東軍は受け持ちの備へまとまって当たり、先鋒（黒田長政・福島正則・藤堂高虎）は
   その最前線に立つ。西軍は、備の一隊が槍を合わせたら、同じ備の隊もそこへ寄る。 */
function 備の差配(b) {
  const s = b.筋書き;
  if (b.t < 3) return;
  if (b.t < (s.差配刻 || 0) + 1.2) return;
  s.差配刻 = b.t;
  const 生 = (c) => !c.dead && !c.destroyed && !c.routed && !c.withdraw
    && !c.不戦 && !c.日和見 && !c.控え && !c.縛り;
  const 委 = (c) => (c.side !== "P" || c.auto) && !c.detach && 生(c);
  const 西 = b.corps.filter((c) => c.筋 && c.筋.旗 === "西" && 生(c));
  const 東 = b.corps.filter((c) => c.筋 && c.筋.旗 === "東" && 生(c));
  const 近い = (c, l) => (l.length
    ? l.reduce((a, o) => (Math.hypot(o.x - c.x, o.y - c.y) < Math.hypot(a.x - c.x, a.y - c.y) ? o : a))
    : null);
  /* 当たる位置は横へ散らす。

     同じ備へ差し向けた隊が皆おなじ一点を目指すと、的の前で団子になって
     押し合う。測ると、ぶつかる前の後退が三.一％から九.五％へ増え、
     「味方が九隊も百五十歩の内にいる」という場面が並んだ。

     的の正面を、当たる隊の数で分け合う。隊の正面ぶん（二百六十歩）ずつ
     離れて並べば、そのまま横陣の一線になる。 */
  const 当てる = (c, 的, 番 = 0, 数 = 1) => {
    const d = Math.hypot(的.x - c.x, 的.y - c.y) || 1;
    const ux = (c.x - 的.x) / d, uy = (c.y - 的.y) / d;      // 的から自分へ向かう向き
    const 寄 = (番 - (数 - 1) / 2) * 260;                    // 正面に沿って横へずらす
    c.狙い = 的.id;
    issueOrder(b, c, { order: "接戦", target: 的.id, 狙い: 的.id,
      tx: 的.x + ux * 38 - uy * 寄, ty: 的.y + uy * 38 + ux * 寄 });
  };

  setAiIssuing(true);
  // 一、東軍は受け持ちの備へ当たる。先鋒がまず正面に立ち、あとは左右へ並ぶ
  {
    const 組 = new Map();                                  // 的 → 当たる隊ら
    for (const c of 東) {
      if (!委(c) || !c.筋.当) continue;
      if (c.squads.some((q) => q.engaged)) continue;       // 噛んでいる隊は動かさない
      const 手 = 西.filter((o) => o.筋.備 === c.筋.当);
      const 的 = 近い(c, 手.length ? 手 : 西);
      if (!的) continue;
      if (!組.has(的)) 組.set(的, []);
      組.get(的).push(c);
    }
    for (const [的, ら] of 組) {
      // 先鋒を真ん中に据える。残りはその左右へ
      ら.sort((x, y2) => (y2.筋.先鋒 ? 1 : 0) - (x.筋.先鋒 ? 1 : 0)
        || Math.hypot(x.x - 的.x, x.y - 的.y) - Math.hypot(y2.x - 的.x, y2.y - 的.y));
      const 並 = [];
      ら.forEach((c, i) => { if (i === 0) 並.splice(0, 0, c); else if (i % 2) 並.push(c); else 並.unshift(c); });
      並.forEach((c, i) => 当てる(c, 的, i, 並.length));
    }
  }
  // 二、西軍は、備の仲間が噛んだらそこへ寄る
  for (const 名 of new Set(西.map((c) => c.筋.備).filter(Boolean))) {
    const 手 = 西.filter((c) => c.筋.備 === 名);
    const 噛 = 手.find((c) => c.squads.some((q) => q.engaged));
    if (!噛) continue;
    const 敵 = 近い(噛, 東);
    if (!敵) continue;
    const 寄せ手 = 手.filter((c) => c !== 噛 && 委(c) && !c.squads.some((q) => q.engaged)
      && Math.hypot(敵.x - c.x, 敵.y - c.y) <= 1600);
    寄せ手.forEach((c, i) => 当てる(c, 敵, i + 1, 寄せ手.length + 1));
  }
  setAiIssuing(false);
}

/* -------------------------------------------------------------- 刻ごとの進み */
export function 筋書きを進める(b, dt) {
  const s = b.筋書き;
  if (!s) return;
  if (b.phase !== "fight") return;
  s.刻 = (s.刻 || 0) + dt;

  /* 采配（敵側）の手立て。遊ぶ側には問いとして出し、敵側は自ら決める。 */
  const 東は敵 = s.味方旗 === "西";
  const 交戦 = b.corps.some((c) => !c.日和見 && c.squads.some((q) => q.engaged));

  // 一、家康の前進
  const 西の残 = 残り(b, "西");
  const 備 = 備の様子(b);
  /* 家康の前進（GDD 8.9）。

     もとは「交戦して五分」だけを見ていたので、まだ何も起きていない二十七秒で
     本陣が動いていた。家康が桃配山を下りたのは、西軍の備が目に見えて
     揺らいでからである。三つとも要る。
       一、五分が経っていること
       二、西軍の前線が八割を切っていること
       三、石田・宇喜多・大谷のどれかが崩れたか、三つの士気の平均が七十を切ること */
  const 備の気 = (備.石田.気 + 備.宇喜多.気 + 備.大谷.気) / 3;
  const 備が揺らぐ = 備.石田.崩れ || 備.宇喜多.崩れ || 備.大谷.崩れ || 備の気 < 70;
  if (!s.家康前進 && 交戦 && b.t > 300 && 西の残 <= 0.80 && 備が揺らぐ) {
    if (東は敵) { 家康を進める(b); }
    else 問う(b, "家康前進",
      "松尾山の小早川はいまだ動かぬ。家康を桃配山から陣場野へ進め、小早川に催促しますか。",
      "本陣を進める", "まだ動かさぬ");
  }
  // 二、問鉄砲（家康の前進が前提）
  /* 問鉄砲。家康が前へ出たうえで、石田か宇喜多が崩れるか、前線が七割を切ってから。 */
  /* 本陣が動いてから催促までには間がある。前へ出た本陣を松尾山が見て、
     それでも動かぬのを見届けてから鉄砲を撃つ。同じ刻に続けて起こしては、
     筋書きが一息に流れてしまう（測ったら三百秒に六つの報せが並んだ）。 */
  if (s.家康前進 && !s.問鉄砲 && s.小早川 === "未" && b.t > (s.前進の刻 || 0) + 150
    && (備.石田.崩れ || 備.宇喜多.崩れ || 西の残 <= 0.70)) {
    if (東は敵) 問鉄砲を撃つ(b);
    else 問う(b, "問鉄砲",
      "本陣は前へ出た。松尾山へ鉄砲を撃ちかけ、小早川の去就をいま問い質しますか。",
      "問鉄砲を撃つ", "なお待つ");
  }
  // 三、西軍の備え（遊ぶ側が西軍のとき）
  if (s.味方旗 === "西" && s.小早川 === "未" && (b.t > 240 || 西の残 <= 0.90)) {
    問う(b, "松尾山へ備える",
      "松尾山の小早川は、いつ山を下りてくるか分からぬ。大谷勢に松尾山への備えを固めさせますか。",
      "備えを固める", "そのままでよい");
  }
  // 五、島津の退き口（西軍が崩れかけたとき）
  {
    const 島 = b.corps.filter((c) => c.筋 && c.筋.島津 && !c.dead && !c.destroyed && c.不戦);
    if (島.length && (西の残 <= 0.50 || (s.小早川 === "東" && b.t > (s.決めた刻 || 0) + 120))) {
      if (s.味方旗 === "西") {
        問う(b, "島津の退き口",
          "島津義弘は備を固めたまま動かぬ。西軍は崩れかけている。"
          + "退くに退けぬいま、正面の敵中を突いて抜けさせますか。",
          "敵中突破を命じる", "なお待つ");
      } else if (西の残 <= 0.40) 島津の退き口(b);
    }
  }

  小早川を決める(b, false);
  南宮山の手を離す(b);
  備の差配(b);
}


/* ==========================================================================
   途中の控え（GDD 8.9）

   合戦は一回で遊びきるものであって、記録は残さない。ただし、うっかり
   頁を閉じてしまったときに、それまでの一戦がまるごと消えるのは酷である。
   閉じたところから続けられるだけの控えを、ひとつだけ取っておく。
   新しい合戦を始めれば、前の控えは消える。

   控えるのは、盤を組み直せるだけの最小の中身である。
   組の居どころは陣形から組み直せるので控えない（三千五百組の座標を
   書き出せば控えだけで一MBを超える）。
   ========================================================================== */
export const 控えの鍵 = "sengoku:kassen";

export function 合戦を控える(b) {
  if (!b || !b.筋書き) return null;
  const s = b.筋書き;
  return {
    版: 1, id: s.id, 味方旗: s.味方旗, t: Math.round(b.t), 天気: b.weather,
    相: b.phase, 果: b.result || null,
    筋: { 小早川: s.小早川, 南宮山: s.南宮山, 家康前進: s.家康前進, 問鉄砲: s.問鉄砲,
      使い: !!s.使い, 済んだ問い: s.済んだ問い, 報: s.報 },
    隊: b.corps.map((c) => ({
      i: c.id, s: c.side, x: Math.round(c.x), y: Math.round(c.y),
      f: +c.facing.toFixed(3), j: +(c.陣向き == null ? c.facing : c.陣向き).toFixed(3),
      m: Math.round(c.morale), h: Math.round(c.fatigue), o: c.order, 形: c.formation,
      tx: Math.round(c.tx), ty: Math.round(c.ty),
      状: (c.dead ? 1 : 0) | (c.destroyed ? 2 : 0) | (c.routed ? 4 : 0) | (c.withdraw ? 8 : 0)
        | (c.日和見 ? 16 : 0) | (c.縛り ? 32 : 0) | (c.控え ? 64 : 0) | (c.auto ? 128 : 0),
      旗: c.筋 ? c.筋.旗 : null, detach: !!c.detach,
    })).filter((d) => !d.detach),
    /* 組は、隊ではなく組の名で控える。

       戦の途中で分遣（騎馬の側面攻撃など）が出ると、親の隊から組が抜けて
       別の隊になる。隊ごとに並び順で控えると、戻したとき親の組数が合わず、
       抜けたはずの組が満杯のまま残る（測ったら一万三千人も湧いていた）。
       組の名は初めから終わりまで変わらないので、名で引き当てる。
       分遣そのものは控えない。戻したときは親へ呼び戻されたものとする。 */
    組: b.corps.flatMap((c) => c.squads.map((q) => [q.id, Math.round(q.men), Math.round(q.cohesion)])),
    log: b.log.slice(-40),
  };
}

export function 合戦を戻す(控) {
  if (!控 || !控.id) return null;
  const r = 合戦を仕立てる(控.id, 控.味方旗);
  if (!r) return null;
  const b = r.b;
  b.t = 控.t || 0; b.weather = 控.天気 || b.weather;
  b.phase = 控.相 === "over" ? "over" : "fight";
  b.result = 控.果 || null;
  Object.assign(b.筋書き, 控.筋 || {});
  const 帳 = new Map(b.corps.map((c) => [c.id, c]));
  for (const d of 控.隊 || []) {
    const c = 帳.get(d.i); if (!c) continue;
    c.side = d.s; c.x = d.x; c.y = d.y; c.facing = d.f; c.陣向き = d.j;
    c.morale = d.m; c.fatigue = d.h; c.order = d.o; c.formation = d.形;
    c.tx = d.tx; c.ty = d.ty;
    c.dead = !!(d.状 & 1); c.destroyed = !!(d.状 & 2); c.routed = !!(d.状 & 4);
    c.withdraw = !!(d.状 & 8); c.日和見 = !!(d.状 & 16);
    c.縛り = (d.状 & 32) ? "南宮山" : null; c.控え = !!(d.状 & 64); c.auto = !!(d.状 & 128);
    if (d.旗 && c.筋) { c.筋.旗 = d.旗; c.color = d.旗 === "黄" ? 黄の色 : 旗の色[d.旗]; }
  }
  /* 組を名で引き当てて戻す。控えに無い組は、討たれたか分遣のまま消えたもの。 */
  const 組帳 = new Map((控.組 || []).map((r) => [r[0], r]));
  for (const c of b.corps) {
    for (const q of c.squads) {
      const r = 組帳.get(q.id);
      q.men = r ? r[1] : 0;
      q.cohesion = r ? r[2] : q.cohesion;
    }
    placeSquads(c, true);
  }
  b.log = (控.log || []).slice();
  b.log.push({ t: b.t, text: "閉じたところから戦を続ける。" });
  return { b, 筋書き: r.筋書き };
}


/* ==========================================================================
   筋書きの覚え（GDD 8.9）

   分岐の条件は入り組んでいる。どれが揃っていて、どれがまだなのかが
   盤の上から読めないと、遊ぶ側は何を目指せばよいのか分からない。
   いまの戦況を条件に照らし、一つずつ○×で返す。画面がこれを並べる。
   ========================================================================== */
export function 筋書きの覚え(b) {
  if (!b || !b.筋書き) return [];
  const s = b.筋書き;
  const 備 = 備の様子(b);
  const 西の残 = 残り(b, "西"), 東の残 = 残り(b, "東");
  const 備の気 = Math.round((備.石田.気 + 備.宇喜多.気 + 備.大谷.気) / 3);
  const 崩 = 先手の崩れ(b);
  const 大谷 = b.corps.filter((c) => /大谷|戸田|木下|平塚/.test(c.name));
  const 大谷の残 = 大谷.length
    ? 兵数(大谷.filter((c) => !c.dead && !c.destroyed))
      / 大谷.reduce((a, c) => a + c.squads.reduce((t, q) => t + q.max, 0), 0) : 0;
  const 山の麓 = b.corps.filter((c) => c.筋 && c.筋.旗 === "西" && !c.dead && !c.destroyed
    && Math.hypot(c.x - 1812, c.y - 4045) < 2400).length;
  const 三成 = b.corps.find((c) => /石田三成/.test(c.name));
  const 旗頭健在 = !!(三成 && !三成.dead && !三成.destroyed && corpsMen(三成) > 0 && 三成.morale >= 50);
  const 割 = (v) => `${Math.round(v * 100)}％`;
  const 分 = (t) => `${Math.floor(t / 60)}分${String(Math.round(t % 60)).padStart(2, "0")}秒`;

  return [
    { 題: "家康の前進", 済: s.家康前進, 但: "旗本三万の控えが解ける。問鉄砲の前提",
      条: [
        { 文: `開戦から五分が経つ（いま ${分(b.t)}）`, 可: b.t > 300 },
        { 文: `西軍の前線が八割を切る（いま ${割(西の残)}）`, 可: 西の残 <= 0.80 },
        { 文: `石田・宇喜多・大谷のどれかが崩れる、または三備の士気が七十を切る（いま ${備の気}）`,
          可: 備.石田.崩れ || 備.宇喜多.崩れ || 備.大谷.崩れ || 備の気 < 70 },
      ] },
    { 題: "問鉄砲", 済: s.問鉄砲, 但: "松尾山の去就をその場で決めさせる",
      条: [
        { 文: "家康が前へ出ている", 可: !!s.家康前進 },
        { 文: `前進から百五十秒が経つ`, 可: !!s.家康前進 && b.t > (s.前進の刻 || 0) + 150 },
        { 文: `石田か宇喜多が崩れる、または西軍の前線が七割を切る（いま ${割(西の残)}）`,
          可: 備.石田.崩れ || 備.宇喜多.崩れ || 西の残 <= 0.70 },
      ] },
    { 題: "小早川が西軍として起つ", 済: s.小早川 === "西",
      但: "四つとも揃えば、問鉄砲を受けても東へは転ばない",
      条: [
        { 文: `黒田・細川・福島のうち二隊以上が崩れる（いま ${崩}隊）`, 可: 崩 >= 2 },
        { 文: `大谷勢が七割以上残る（いま ${割(大谷の残)}）`, 可: 大谷の残 >= 0.70 },
        { 文: `松尾山の麓に西軍が二隊以上（いま ${山の麓}隊）`, 可: 山の麓 >= 2 },
        { 文: `石田三成が健在で士気五十以上（いま ${三成 ? Math.round(三成.morale) : 0}）`, 可: 旗頭健在 },
      ] },
    { 題: "南宮山と押さえの手が離れる", 済: s.南宮山 === "解けた",
      但: "毛利勢二万七千九百と、東軍の押さえ六隊が動けるようになる",
      条: [
        { 文: `松尾山の去就が決まる（いま ${s.小早川 === "未" ? "未だ" : s.小早川 + "へ"}）`, 可: s.小早川 !== "未" },
        { 文: "決まってから三十秒", 可: s.小早川 !== "未" && b.t > (s.決めた刻 || 0) + 30 },
      ] },
    { 題: "島津の退き口", 済: !b.corps.some((c) => c.筋 && c.筋.島津 && c.不戦),
      但: "正面の敵中を突いて抜ける。それまで島津は動かない",
      条: [
        { 文: `西軍の前線が五割を切る（いま ${割(西の残)}）、または松尾山が東へ転ぶ`,
          可: 西の残 <= 0.50 || s.小早川 === "東" },
      ] },
    { 題: "勝ち", 済: b.phase === "over" && b.result === "P",
      但: `敵の隊をひとつ残らず崩す（敵の前線はいま ${割(s.味方旗 === "西" ? 東の残 : 西の残)}）`,
      条: [] },
  ];
}
