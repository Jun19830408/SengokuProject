/* 一 峠の鞍部（難所）

   山並みが盤を横切り、街道は低い鞍部（峠）を越える。峠は丘として盛り、山ほど
   足を取られずに越えられる。峠を先に取った側が見下ろして戦える（地の高さ）。
   峠を避けて山腹を越える細道が一本ある――回り込む者は、山に足を取られる。 */
function 峠(野) {
  const { L, C, sc, rnd } = 野;
  const r = clamp(150 * sc, 170, Math.min(L * 0.15, 900));
  const a0 = L * (0.46 + rnd() * 0.08);
  const 鞍 = C * (0.34 + rnd() * 0.32);
  const 隙 = clamp(r * 0.7, 110, C * 0.08);                  // 鞍部の半ば（山の無い所）
  const 高 = 270 + rnd() * 170;
  const 相 = rnd() * Math.PI * 2, 振 = L * (0.02 + rnd() * 0.02);
  const 筋a = (c) => a0 + Math.sin((c / C) * Math.PI * 1.7 + 相) * 振;
  const 左端 = 鞍 - 隙 - r * 1.3, 右端 = 鞍 + 隙 + r * 1.3;    // 峰の切れ目（裾の分を空ける）
  const 並み = (c0, c1, 鞍は奥) => Array.from({ length: 5 }, (_, i) => {
    const t = i / 4, c = c0 + (c1 - c0) * t, 近 = 鞍は奥 ? t : 1 - t;
    return [筋a(c), c, 高 * (1 - 0.4 * 近 * 近) * (0.92 + rnd() * 0.16), r * (1 - 0.22 * 近)];
  });
  if (左端 > -C * 0.12) 野.山.push(...尾根(野, 並み(-C * 0.16, 左端, true), { 名: "峠の山" }));
  if (右端 < C * 1.12) 野.山.push(...尾根(野, 並み(右端, C * 1.16, false), { 名: "峠の山" }));
  const 丘r = r * 0.95, 丘高 = 115 + rnd() * 40;
  野.丘.push(...尾根(野, [[筋a(左端 + r * 0.5), 左端 + r * 0.5, 丘高 * 1.15, 丘r], [筋a(鞍), 鞍, 丘高, 丘r * 1.05],
    [筋a(右端 - r * 0.5), 右端 - r * 0.5, 丘高 * 1.15, 丘r]], { 名: "峠", 札: true, 裾: 0.5 }));

  const 入 = clamp(鞍 + (rnd() - 0.5) * C * 0.36, C * 0.12, C * 0.88);
  const 出 = clamp(鞍 + (rnd() - 0.5) * C * 0.36, C * 0.12, C * 0.88);
  const 芯 = [[-30, 入], [L * 0.2, 入 + (鞍 - 入) * 0.35], [筋a(鞍) - r * 1.1, 鞍], [筋a(鞍) + r * 1.1, 鞍],
    [L * 0.8, 出 + (鞍 - 出) * 0.35], [L + 30, 出]];
  野.道.push({ 名: "街道", 幅: 野.道幅, 節: 筋(野, 芯, 3, 野.道幅 * 0.7) });
  /* 山腹の細道。鞍部から離れた側の山を越える */
  const 細c = 鞍 < C / 2 ? Math.min(C * 0.92, 右端 + C * 0.16) : Math.max(C * 0.08, 左端 - C * 0.16);
  野.道.push({ 名: "山の細道", 幅: Math.max(18, Math.round(野.道幅 * 0.5)),
    節: 筋(野, [[筋a(細c) - r * 2.3, 細c], [筋a(細c) - r * 0.7, 細c + C * 0.025], [筋a(細c) + r * 0.7, 細c - C * 0.025],
      [筋a(細c) + r * 2.3, 細c]], 3, 野.道幅 * 0.5) });

  /* 峠の両の麓の宿 */
  const vr = clamp(42 * sc, 60, 210);
  for (const 向 of [-1, 1]) {
    const a = clamp(a0 + 向 * (r * 1.45 + vr * 1.3), L * 0.28, L * 0.72);
    const c = 芯の横(芯, a) + (rnd() < 0.5 ? -1 : 1) * (野.道幅 * 1.5 + vr + 14);
    const p = 点(野, a, c);
    if (空きか(野, p, vr, [...野.丘, ...野.山.filter((m) => m.高 > 120)], { 水: false })) {
      野.村.push({ ...p, r: Math.round(vr), 名: 向 < 0 ? "麓の宿" : "峠下の宿", 横: 野.村の横 });
    }
  }
  /* 山肌の森と、麓の林 */
  野.森.push(...散らす(野, Math.max(3, Math.round(C / (r * 1.3))), r * 0.45, r * 0.75,
    (a, c) => Math.abs(a - 筋a(c)) < r * 0.8 && Math.abs(c - 鞍) > 隙 + r * 1.7, [], { 道: true, 水: false }));
  野.林.push(...散らす(野, Math.max(4, Math.round(C / (r * 0.9))), r * 0.22, r * 0.42,
    (a, c, rr) => { const d = Math.abs(a - 筋a(c)); return d > r * 1.2 + rr && d < r * 2.6 && !布陣の場か(野, a, c, rr); },
    [...野.村, ...野.丘]));
  /* 脇の野にもいくらか林を置く（布陣の場の外） */
  野.林.push(...散らす(野, 3, r * 0.2, r * 0.36, (a, c, rr) => !布陣の場か(野, a, c, rr) && Math.abs(a - 筋a(c)) > r * 1.8,
    [...野.村, ...野.丘, ...野.林, ...野.山]));
}

/* 二 谷あいの川沿い（山道の半ば）

   両側に山が迫る細長い谷。川は谷の片寄りを、街道は反対の片寄りを、どちらも奥まで
   通る。大軍は横に広がれず、縦に伸びて戦う。川向こうの狭い岸には里が一つあり、
   脇道が橋で川を渡る。瀬は二つ。布陣は谷底の帯の中。 */
function 谷(野) {
  const { L, C, sc, rnd } = 野;
  const 谷幅 = C * (0.44 + rnd() * 0.06);
  const 芯c = C * (0.5 + (rnd() - 0.5) * 0.08);
  const c左 = 芯c - 谷幅 / 2, c右 = 芯c + 谷幅 / 2;
  const r = clamp(160 * sc, 180, Math.min(C * 0.19, 1000));
  const 相 = [0, 0, 0, 0].map(() => rnd() * Math.PI * 2);
  const 揺 = (a, k) => Math.sin((a / L) * Math.PI * 1.6 + 相[k]);
  /* 山は高くしすぎない。斜めの眺めでは手前の山が持ち上がって谷底を覆い隠す */
  for (const [c, k, 高0] of [[c左 - r, 0, 230], [c左 - r * 2.3, 0, 290], [c右 + r, 1, 230], [c右 + r * 2.3, 1, 290]]) {
    野.山.push(...尾根(野, 縦の並み(野, c, 高0, r, (a) => r * 0.14 * 揺(a, k)), { 名: "谷の山" }));
  }
  const 川幅 = Math.round(clamp(野.尺H * 0.032, 44, 130));
  const 川c = (a) => c左 + 谷幅 * (0.27 + 0.06 * 揺(a, 2));
  const 川 = { 名: "谷川", 幅: 川幅, 渡し: [],
    節: 筋(野, Array.from({ length: 8 }, (_, i) => { const a = L * 1.16 - (L * 1.32 * i) / 7; return [a, 川c(a)]; }), 4, 川幅 * 0.5) };
  野.川.push(川);
  const 道c = (a) => c左 + 谷幅 * (0.66 + 0.05 * 揺(a, 3));
  const 芯 = Array.from({ length: 7 }, (_, i) => { const a = -30 + ((L + 60) * i) / 6; return [a, 道c(a)]; });
  野.道.push({ 名: "街道", 幅: 野.道幅, 節: 筋(野, 芯, 3, 野.道幅 * 0.5) });
  for (const a of [L * (0.28 + rnd() * 0.06), L * (0.66 + rnd() * 0.06)]) 渡しを置く(野, 川, a, 川c(a), "浅瀬");

  /* 川向こうの里と、橋の架かる脇道 */
  const ab = L * (0.42 + rnd() * 0.16);
  const 岸外 = c左 + r * 0.32, 岸内 = 川c(ab) - 川幅 / 2 - 24;
  if (岸内 - 岸外 > 130) {
    const vr = Math.min(clamp(36 * sc, 50, 160), (岸内 - 岸外) / 2 - 8), vc = (岸外 + 岸内) / 2;
    野.道.push({ 名: "脇道", 幅: Math.max(18, Math.round(野.道幅 * 0.6)), 節: [点(野, ab, 道c(ab)), 点(野, ab, vc)] });
    渡しを置く(野, 川, ab, 川c(ab), "橋");
    野.村.push({ ...点(野, ab, vc), r: Math.round(vr), 名: "対岸の里", 横: !野.村の横 });
  }
  /* 谷底の里と小丘 */
  const vr = clamp(40 * sc, 56, 200);
  for (const a0 of [L * (0.33 + rnd() * 0.05), L * (0.6 + rnd() * 0.06)]) {
    const p = 点(野, a0, 道c(a0) + 野.道幅 * 1.2 + vr);
    if (空きか(野, p, vr, [...野.村, ...野.山])) 野.村.push({ ...p, r: Math.round(vr), 横: 野.村の横 });
  }
  野.丘.push(...散らす(野, 1 + (rnd() < 0.5 ? 1 : 0), r * 0.38, r * 0.5, (a, c, rr) => c > c右 - r * 0.9 && c < c右 - r * 0.2
    && a > L * 0.3 && a < L * 0.7, [...野.村], { 添: { 高: Math.round(70 + rnd() * 30) } }));
  /* 川べりと山の膝の林、山肌の森 */
  野.林.push(...散らす(野, Math.round(5 + L / (r * 1.6)), r * 0.2, r * 0.4, (a, c, rr) =>
    !布陣の場か(野, a, c, rr) && ((c > c左 && c < 川c(a) - 川幅) || (c > c右 - r * 0.6 && c < c右 + r * 0.2)),
  [...野.村, ...野.丘]));
  野.森.push(...散らす(野, Math.round(4 + L / (r * 1.4)), r * 0.45, r * 0.7, (a, c) => c < c左 - r * 0.5 || c > c右 + r * 0.5,
    [], { 水: false }));
  野.帯 = [c左 + r * 0.32, c右 - r * 0.32];
}

/* 三 山裾の段々（山道の残り）

   片側が山の斜面で、二段の丘（段）が野へ下りる。段は所々で切れ、その一つから浅い沢が
   野を横切って流れる（どこでも渡れるが、足は鈍る）。街道は段の裾を通る。段の上を取った側が見下ろして戦える。
   低い側は田と里の野。布陣は街道から低い側の帯の中。 */
function 段(野) {
  const { L, C, sc, rnd } = 野;
  const r = clamp(170 * sc, 190, Math.min(C * 0.2, 1000));
  const 相 = [0, 0, 0].map(() => rnd() * Math.PI * 2);
  const 揺 = (a, k) => Math.sin((a / L) * Math.PI * 1.5 + 相[k]);
  const 山c = C * 0.02;
  野.山.push(...尾根(野, 縦の並み(野, 山c, 340, r, (a) => r * 0.15 * 揺(a, 0)), { 名: "山" }),
    ...尾根(野, 縦の並み(野, 山c - r * 1.4, 400, r, (a) => r * 0.15 * 揺(a, 0)), { 名: "山" }));
  /* 段と段のあいだを空け、段を高くする。段を山の膝にくっつけて並べると、斜めの眺めでは
     山の斜面と一続きの坂に見え、段に見えなかった */
  const r1 = r * 0.62, r2 = r1 * 0.8;
  const c1 = 山c + r * 1.3 + r1, c2 = c1 + r1 * 1.9 + r2 * 0.2;
  const 切れ目 = [L * (0.27 + rnd() * 0.1), L * (0.62 + rnd() * 0.1)];
  const 沢a = 切れ目[rnd() < 0.5 ? 0 : 1];
  const 段を引く = (c, rr, 高, 名, 切ら, 札) => {
    const 区 = [-L * 0.12, ...切ら.slice().sort((p, q) => p - q).flatMap((g) => [g - L * 0.04, g + L * 0.04]), L * 1.12];
    for (let i = 0; i + 1 < 区.length; i += 2) {
      const a0 = 区[i], a1 = 区[i + 1];
      if (a1 - a0 < rr * 1.2) continue;
      const m = (a0 + a1) / 2;
      野.丘.push(...尾根(野, [[a0 + rr * 0.4, c + rr * 0.12 * 揺(a0, 1), 高, rr], [m, c + rr * 0.12 * 揺(m, 1), 高 * 1.06, rr],
        [a1 - rr * 0.4, c + rr * 0.12 * 揺(a1, 1), 高, rr]], { 名, 札: 札 && i === 2, 裾: 0.6, 裾の倍: 1.2 }));
    }
  };
  段を引く(c1, r1, 170 + rnd() * 40, "一の段", 切れ目, true);
  段を引く(c2, r2, 100 + rnd() * 30, "二の段", [沢a, L * (沢a < L / 2 ? 0.6 : 0.4) + (rnd() - 0.5) * L * 0.08], false);
  const 道c = (a) => c2 + r2 * 1.3 + 野.道幅 + C * 0.02 * 揺(a, 2);
  const 芯 = Array.from({ length: 7 }, (_, i) => { const a = -30 + ((L + 60) * i) / 6; return [a, 道c(a)]; });
  野.道.push({ 名: "街道", 幅: 野.道幅, 節: 筋(野, 芯, 3, 野.道幅 * 0.5) });
  /* 沢。山の膝から段の切れ目を下り、野を横切って盤の外へ */
  const 沢幅 = Math.round(clamp(野.尺H * 0.026, 38, 100));
  const 沢 = { 名: "沢", 幅: 沢幅, 渡し: [], 浅: true, 節: 筋(野, [[沢a, 山c + r * 0.95], [沢a + L * 0.01, c2], [沢a + L * 0.03, 道c(沢a)],
    [沢a + L * 0.05, C * 0.75], [沢a + L * 0.07, C * 1.14]], 4, 沢幅 * 0.8) };
  野.川.push(沢);
  渡しを置く(野, 沢, 沢a + L * 0.03, 道c(沢a), "橋");
  /* 低い側の田と里と林 */
  const vr = clamp(40 * sc, 56, 200);
  for (const a0 of [L * (0.32 + rnd() * 0.05), L * (0.62 + rnd() * 0.06)]) {
    const p = 点(野, a0, 道c(a0) + 野.道幅 * 1.2 + vr);
    if (空きか(野, p, vr, [...野.村, ...野.丘])) 野.村.push({ ...p, r: Math.round(vr), 横: 野.村の横 });
  }
  野.沼.push(...散らす(野, 2 + (rnd() < 0.5 ? 1 : 0), clamp(60 * sc, 80, 300) * 0.8, clamp(60 * sc, 80, 300),
    (a, c, rr) => c > 道c(a) + 野.道幅 + rr && !布陣の場か(野, a, c, rr), [...野.村], { 添: { 葦: 0.3 } }));
  野.林.push(...散らす(野, Math.round(5 + L / (r * 1.5)), r * 0.2, r * 0.4,
    (a, c, rr) => !布陣の場か(野, a, c, rr) && c > c1 - r1 * 0.5, [...野.村, ...野.沼, ...野.丘.filter((h) => h.高 > 40)]));
  野.森.push(...散らす(野, Math.round(3 + L / (r * 1.4)), r * 0.45, r * 0.7, (a, c) => c < 山c + r * 0.6, [], { 水: false }));
  野.帯 = [道c(L / 2) - 野.道幅, C * 0.96];
}

/* 四 大河の渡し（大河を渡る街道）

   幅の広い大河が盤を横切る。街道は橋で渡る。中洲のある所で川は二筋に分かれ、
   その二筋と中洲の両の端に瀬がある――中洲を経て渡れる。もう一つ、橋と中洲から
   離れた所に瀬がある。
   先に渡った側は川を背に戦う。山越えの街道なら、両脇に山が迫る。 */
function 大河(野) {
  const { L, C, sc, rnd } = 野;
  const w = Math.round(clamp(野.尺H * 0.1, 120, 360));
  const a0 = L * (0.5 + (rnd() - 0.5) * 0.08);
  const 相 = rnd() * Math.PI * 2, 振 = L * (0.025 + rnd() * 0.03);
  const 川a = (c) => a0 + Math.sin((c / C) * Math.PI * 1.3 + 相) * 振;
  const 島左 = rnd() < 0.5;
  const cd = 島左 ? C * (0.6 + rnd() * 0.14) : C * (0.26 + rnd() * 0.14);   // 橋（街道の渡る所）
  const i0 = 島左 ? C * (0.1 + rnd() * 0.08) : C * (0.62 + rnd() * 0.08);
  const i1 = i0 + C * (0.17 + rnd() * 0.05);
  const 本流 = (c0, c1) => {
    const n = Math.max(2, Math.round(Math.abs(c1 - c0) / (C / 7)));
    return Array.from({ length: n + 1 }, (_, i) => { const c = c0 + ((c1 - c0) * i) / n; return [川a(c), c]; });
  };
  const 名 = 野.名ら.川 || "大河";
  const 上 = { 名, 幅: w, 渡し: [], 節: 筋(野, 本流(-C * 0.14, i0), 4, w * 0.25) };
  const 下 = { 名, 幅: w, 渡し: [], 節: 筋(野, 本流(i1, C * 1.14), 4, w * 0.25) };
  const d = w * 1.2, Δ = i1 - i0, 枝幅 = Math.round(w * 0.58);
  /* 中洲の二筋には名を付けない（名札が四つも並ぶ） */
  const 枝 = (向) => ({ 名: "", 幅: 枝幅, 渡し: [], 節: 筋(野, [[川a(i0), i0], [川a(i0 + Δ * 0.28) + 向 * d, i0 + Δ * 0.28],
    [川a(i0 + Δ * 0.72) + 向 * d, i0 + Δ * 0.72], [川a(i1), i1]], 3, 枝幅 * 0.2) });
  const 手前 = 枝(-1), 奥 = 枝(1);
  野.川.push(上, 手前, 奥, 下);
  const 橋の川 = cd < i0 ? 上 : 下;
  渡しを置く(野, 橋の川, 川a(cd), cd, "橋");
  const im = (i0 + i1) / 2;
  渡しを置く(野, 手前, 川a(im) - d, im, "浅瀬");
  渡しを置く(野, 奥, 川a(im) + d, im, "浅瀬");
  const cf = 島左 ? C * (0.88 + rnd() * 0.05) : C * (0.07 + rnd() * 0.05);
  渡しを置く(野, 島左 ? 下 : 上, 川a(cf), cf, "浅瀬");
  /* 中洲の両の端は砂の溜まる浅瀬。二筋の分かれ目と落ち合いが淵のままだと、中洲の端へ
     出た隊が三方を淵に囲まれて立ち往生し、そこで押し渡って水の中で槍を合わせた */
  for (const [川, c] of [[上, i0], [下, i1]]) 渡しを置く(野, 川, 川a(c), c, "浅瀬");

  const 入 = clamp(cd + (rnd() - 0.5) * C * 0.3, C * 0.12, C * 0.88);
  const 出 = clamp(cd + (rnd() - 0.5) * C * 0.3, C * 0.12, C * 0.88);
  const 芯 = [[-30, 入], [川a(cd) - w * 2.2, cd], [川a(cd) + w * 2.2, cd], [L + 30, 出]];
  野.道.push({ 名: "街道", 幅: 野.道幅, 節: 筋(野, 芯, 3, 野.道幅 * 0.6) });

  /* 中洲の林 */
  for (const t of [0.38, 0.62]) {
    const c = i0 + Δ * t, rr = Math.min(Δ * 0.2, (2 * d - 枝幅) * 0.32);
    if (rr > 30) 野.林.push(円(野, 川a(c), c, rr));
  }
  /* 渡しの宿（橋の両の袂）と、橋頭の丘 */
  const vr = clamp(40 * sc, 56, 200), 側 = rnd() < 0.5 ? -1 : 1;
  for (const 向 of [-1, 1]) {
    const p = 点(野, 川a(cd) + 向 * (w / 2 + vr + 野.道幅 + 30), cd + 側 * (野.道幅 * 1.2 + vr + 10));
    if (空きか(野, p, vr, [...野.村])) 野.村.push({ ...p, r: Math.round(vr), 名: 向 < 0 ? "渡しの宿" : "対岸の宿", 札: 向 < 0, 横: 野.村の横 });
  }
  const rh = clamp(70 * sc, 90, 300), 岸向 = rnd() < 0.5 ? -1 : 1;
  const ph = 点(野, 川a(cd) + 岸向 * (w / 2 + rh * 1.2 + 50), cd - 側 * (rh + 野.道幅 * 1.5));
  if (空きか(野, ph, rh, [...野.村])) 野.丘.push({ ...ph, r: Math.round(rh), 名: "橋頭の丘", 高: Math.round(80 + rnd() * 30) });
  /* 河原の林と田 */
  野.林.push(...散らす(野, Math.round(6 + C / (w * 3)), clamp(40 * sc, 56, 220), clamp(70 * sc, 80, 340),
    (a, c, rr) => { const e = Math.abs(a - 川a(c)) - w / 2; return e > 40 + rr * 0.6 && e < L * 0.12 + rr && !布陣の場か(野, a, c, rr); },
    [...野.村, ...野.丘]));
  野.沼.push(...散らす(野, 1 + (rnd() < 0.6 ? 1 : 0), clamp(60 * sc, 80, 300) * 0.8, clamp(60 * sc, 80, 300),
    (a, c, rr) => { const e = Math.abs(a - 川a(c)) - w / 2; return e > 60 + rr && e < L * 0.16 + rr && !布陣の場か(野, a, c, rr); },
    [...野.村, ...野.丘, ...野.林], { 添: { 葦: 0.4 } }));
  /* 山越えの街道なら、両の脇に山 */
  if (野.質 === "山道" || 野.質 === "難所") {
    const rm = clamp(150 * sc, 170, Math.min(C * 0.14, 800));
    野.山.push(...尾根(野, 縦の並み(野, -C * 0.06, 320, rm), { 名: "山" }), ...尾根(野, 縦の並み(野, C * 1.06, 320, rm), { 名: "山" }));
  }
}

/* 五 湖岸の細道（湖のそばを通る街道）

   片側が湖、片側が山の細長い帯。山から湖へ突き出す鼻（山の鼻）があり、そこで帯は
   いちばん狭くなる――街道は鼻の先と湖のあいだの隘路を抜ける。山から湖へ浅い小川が
   一筋下る。布陣は湖岸と山の麓のあいだの帯の中。 */
function 湖(野) {
  const { L, C, sc, rnd } = 野;
  const 岸 = C * (0.22 + rnd() * 0.05);
  const r = clamp(170 * sc, 190, Math.min(C * 0.2, 1000));
  const 相 = [0, 0, 0].map(() => rnd() * Math.PI * 2);
  const 揺 = (a, k) => Math.sin((a / L) * Math.PI * 1.8 + 相[k]);
  広い水(野, 野.名ら.湖 || "湖", 岸, 2 + Math.floor(rnd() * 3), false);
  const 山c = C + r * 0.15;
  野.山.push(...尾根(野, 縦の並み(野, 山c, 330, r, (a) => r * 0.15 * 揺(a, 1)), { 名: "湖岸の山" }),
    ...尾根(野, 縦の並み(野, 山c + r * 1.4, 400, r, (a) => r * 0.15 * 揺(a, 1)), { 名: "湖岸の山" }));
  /* 山の鼻 */
  /* 鼻は真ん中から少し寄せ、小川は反対の側に流す。近いと、斜めの眺めで高い鼻の陰に
     小川が隠れた */
  const as = rnd() < 0.5 ? L * (0.38 + rnd() * 0.08) : L * (0.54 + rnd() * 0.08);
  const 隘 = clamp(C * 0.1, 野.道幅 * 4, C * 0.15);
  const rt = r * 0.55, 先 = 岸 + 隘 + rt * 1.28;
  野.山.push(...尾根(野, [[as, 山c, 320, r * 0.9], [as + L * 0.02, (山c + 先) / 2, 230, r * 0.72], [as, 先, 140, rt]],
    { 名: "山の鼻", 札: true }));
  if (rnd() < 0.45) {                                         // 二つ目の小さな鼻
    const as2 = as < L / 2 ? L * (0.68 + rnd() * 0.06) : L * (0.26 + rnd() * 0.06);
    const 先2 = 岸 + C * 0.32;
    野.山.push(...尾根(野, [[as2, 山c, 330, r * 0.8], [as2, 先2, 150, r * 0.5]], { 名: "湖岸の山" }));
  }
  const 中 = (a) => (岸 + (C - r * 1.15)) / 2 + C * 0.03 * 揺(a, 2);
  const 隘c = 岸 + 隘 * 0.5;
  const 芯 = [[-30, 中(0)], [as - L * 0.2, 中(as - L * 0.2)], [as - L * 0.05, 隘c + C * 0.015], [as + L * 0.05, 隘c + C * 0.015],
    [as + L * 0.2, 中(as + L * 0.2)], [L + 30, 中(L)]];
  野.道.push({ 名: "街道", 幅: 野.道幅, 節: 筋(野, 芯, 3, 野.道幅 * 0.5) });
  /* 山から湖へ下る小川 */
  const ast = as > L / 2 ? L * (0.28 + rnd() * 0.04) : L * (0.68 + rnd() * 0.04);
  const 小幅 = Math.round(clamp(野.尺H * 0.024, 36, 90));
  const 小川 = { 名: "小川", 幅: 小幅, 渡し: [], 浅: true, 節: 筋(野, [[ast + L * 0.03, C * 1.1], [ast + L * 0.01, C * 0.75], [ast, C * 0.5], [ast - L * 0.01, 岸 - C * 0.04]], 4, 小幅 * 0.8) };
  野.川.push(小川);
  渡しを置く(野, 小川, ast, 芯の横(芯, ast), "橋");
  /* 湖畔の里、岸の松、山肌の森と麓の林 */
  const vr = clamp(40 * sc, 56, 200);
  for (const a0 of [L * (0.3 + rnd() * 0.05), L * (0.68 + rnd() * 0.05)]) {
    const p = 点(野, a0, 岸 + vr + 60);
    if (空きか(野, p, vr, [...野.村, ...野.山])) 野.村.push({ ...p, r: Math.round(vr), 名: "湖畔の里", 横: 野.村の横 });
  }
  野.林.push(...散らす(野, Math.round(4 + L / (r * 1.4)), clamp(36 * sc, 50, 180), clamp(56 * sc, 70, 260),
    (a, c, rr) => c - rr > 岸 + 26 && c < 岸 + C * 0.1 && !布陣の場か(野, a, c, rr), [...野.村, ...野.山]));
  野.林.push(...散らす(野, Math.round(3 + L / (r * 1.8)), r * 0.2, r * 0.4,
    (a, c, rr) => c > C - r * 1.3 && c < C - r * 0.6 && !布陣の場か(野, a, c, rr), [...野.村, ...野.林, ...野.山.filter((m) => m.名 === "山の鼻")]));
  野.森.push(...散らす(野, Math.round(3 + L / (r * 1.4)), r * 0.45, r * 0.7, (a, c) => c > C - r * 0.3, [], { 水: false }));
  野.帯 = [岸 + C * 0.04, C - r * 1.15];
}

/* 六 浜の道（海沿いの城どうし）／磯の難所（海沿いの山越え）

   片側が海。砂浜に松原が続き、川が一筋、野を横切って海へ注ぐ。河口は広く浅い瀬、
   川上にもう一つ瀬、街道に橋。陸の側は低い丘と田。
   磯の難所では、陸の側が山で、山の鼻が海の際まで落ちる。街道は崖の下の狭い浜を
   抜ける（隘）。川は山から下る浅い沢になる。 */
function 浜(野, 磯) {
  const { L, C, sc, rnd } = 野;
  const 岸 = C * (0.2 + rnd() * 0.05);
  const r = clamp(170 * sc, 190, Math.min(C * 0.2, 1000));
  const 相 = [0, 0].map(() => rnd() * Math.PI * 2);
  const 揺 = (a, k) => Math.sin((a / L) * Math.PI * 1.6 + 相[k]);
  広い水(野, "海", 岸, 1 + Math.floor(rnd() * 2), true);
  let as = null, 隘c = null;
  const 山c = C + r * 0.15;
  if (磯) {
    野.山.push(...尾根(野, 縦の並み(野, 山c, 340, r, (a) => r * 0.15 * 揺(a, 0)), { 名: "山" }),
      ...尾根(野, 縦の並み(野, 山c + r * 1.4, 420, r, (a) => r * 0.15 * 揺(a, 0)), { 名: "山" }));
    as = L * (0.4 + rnd() * 0.2);
    const 隘 = clamp(C * 0.06, 野.道幅 * 3.5, C * 0.1);
    const rt = r * 0.6, 先 = 岸 + 隘 + rt * 1.28;
    野.山.push(...尾根(野, [[as, 山c, 400, r * 0.95], [as + L * 0.015, (山c + 先) / 2, 300, r * 0.78], [as, 先, 210, rt]],
      { 名: "磯の崖", 札: true }));
    隘c = 岸 + 隘 * 0.5;
  }
  const 陸 = 磯 ? C - r * 1.15 : C * 0.96;
  const 中 = (a) => (岸 + 陸) / 2 - C * 0.04 + C * 0.025 * 揺(a, 1);
  const 芯 = 磯
    ? [[-30, 中(0)], [as - L * 0.2, 中(as - L * 0.2)], [as - L * 0.05, 隘c + C * 0.01], [as + L * 0.05, 隘c + C * 0.01],
      [as + L * 0.2, 中(as + L * 0.2)], [L + 30, 中(L)]]
    : Array.from({ length: 6 }, (_, i) => { const a = -30 + ((L + 60) * i) / 5; return [a, 中(a)]; });
  野.道.push({ 名: "街道", 幅: 野.道幅, 節: 筋(野, 芯, 3, 野.道幅 * 0.5) });
  /* 海へ注ぐ川（磯では細い沢） */
  const ar = 磯 ? (as < L / 2 ? L * (0.66 + rnd() * 0.08) : L * (0.26 + rnd() * 0.08)) : L * (0.42 + rnd() * 0.16);
  const 河幅 = Math.round(磯 ? clamp(野.尺H * 0.03, 40, 110) : clamp(野.尺H * 0.045, 56, 170));
  const 河 = { 名: 磯 ? "沢" : "川", 幅: 河幅, 渡し: [], ...(磯 ? { 浅: true } : {}),
    節: 筋(野, [[ar + L * 0.05, C * 1.15], [ar + L * 0.02, C * 0.75], [ar, C * 0.5],
      [ar - L * 0.02, 岸 + C * 0.05], [ar - L * 0.03, 岸 - C * 0.05]], 4, 河幅 * 0.7) };
  野.川.push(河);
  渡しを置く(野, 河, ar - L * 0.004, 芯の横(芯, ar), "橋");
  if (!磯) {
    /* 河口は広く浅い（瀬を大きく取る）。川上にもう一つ瀬 */
    渡しを置く(野, 河, ar - L * 0.022, 岸 + C * 0.075, "浅瀬");
    河.渡し[河.渡し.length - 1].r = Math.round(河幅 / 2 + clamp(120 * 野.幅倍, 100, 220));
    渡しを置く(野, 河, ar + L * 0.03, C * (0.8 + rnd() * 0.08), "浅瀬");
  }
  /* 松原（岸に沿う林）。布陣の場には掛けない */
  const rp = clamp(45 * sc, 60, 220);
  for (let a = L * 0.24; a < L * 0.77; a += rp * (1.7 + rnd() * 0.8)) {
    const c = 岸 + rp + 30 + rnd() * C * 0.02;
    const p = 点(野, a, c);
    if (空きか(野, p, rp, [...野.山])) 野.林.push({ ...p, r: Math.round(rp * (0.8 + rnd() * 0.35)) });
  }
  /* 浜の漁村と、橋の袂の宿 */
  const vr = clamp(40 * sc, 56, 200);
  const 漁a = ar > L / 2 ? L * (0.32 + rnd() * 0.05) : L * (0.66 + rnd() * 0.05);
  const 漁 = 点(野, 漁a, 岸 + vr + 50);
  if (空きか(野, 漁, vr, [...野.林, ...野.山])) 野.村.push({ ...漁, r: Math.round(vr), 名: "浜の里", 札: true, 横: 野.村の横 });
  const 宿 = 点(野, ar + (rnd() < 0.5 ? -1 : 1) * (河幅 / 2 + vr + 60), 芯の横(芯, ar) + 野.道幅 * 1.3 + vr);
  if (空きか(野, 宿, vr, [...野.村, ...野.林, ...野.山])) 野.村.push({ ...宿, r: Math.round(vr), 横: 野.村の横 });
  if (磯) {
    野.森.push(...散らす(野, Math.round(3 + L / (r * 1.4)), r * 0.45, r * 0.7, (a, c) => c > C - r * 0.3, [], { 水: false }));
    野.林.push(...散らす(野, Math.round(3 + L / (r * 1.8)), r * 0.2, r * 0.38,
      (a, c, rr) => c > C - r * 1.3 && c < C - r * 0.6 && !布陣の場か(野, a, c, rr), [...野.村, ...野.林, ...野.山.filter((m) => m.名 === "磯の崖")]));
  } else {
    /* 陸の側の低い丘と田 */
    野.丘.push(...散らす(野, 2 + (rnd() < 0.5 ? 1 : 0), r * 0.4, r * 0.62, (a, c, rr) => c > C * 0.72 && a > L * 0.24 + rr && a < L * 0.76 - rr,
      [...野.村], { 添: { 高: Math.round(80 + rnd() * 40) } }));
    野.沼.push(...散らす(野, 1 + (rnd() < 0.6 ? 1 : 0), clamp(60 * sc, 80, 300) * 0.8, clamp(60 * sc, 80, 300),
      (a, c, rr) => c > 芯の横(芯, a) + 野.道幅 + rr && !布陣の場か(野, a, c, rr), [...野.村, ...野.丘], { 添: { 葦: 0.35 } }));
    野.林.push(...散らす(野, 3, r * 0.2, r * 0.36, (a, c, rr) => c > C * 0.6 && !布陣の場か(野, a, c, rr), [...野.村, ...野.丘, ...野.沼, ...野.林]));
  }
  野.帯 = [岸 + C * 0.04, 陸];
}

/* 七 城下・宿場の町（道のりの短い街道）

   盤の真ん中に町がある。街道が町の芯を貫き（本町）、その両脇に裏通り、横には
   横町が通る。通りに挟まれた町家の区（村）は通りに沿って家を並べる。町の一方の
   端を掘割が横切り、通りの所にだけ橋が架かる。脇の小高い所に寺の境内（丘と林）。
   町の中では足が鈍り、騎馬は突けない（集落）。通りは道なので速い。 */
function 町(野) {
  const { L, C, sc, rnd } = 野;
  const am = L * (0.5 + (rnd() - 0.5) * 0.06);
  const cm = C * (0.5 + (rnd() - 0.5) * 0.14);
  /* 町の大きさは盤なりに広げず、頭を設ける。家は一軒ずつ同じ大きさで立つので、大きな盤で
     町を盤なりに広げると、区が大きくなるばかりで町家がまばらに見えた */
  const 長 = Math.min(L * (0.32 + rnd() * 0.04), 700 + 240 * sc);
  const 幅 = Math.min(C * 0.38, 長 * 1.5);
  const 裏 = 幅 * 0.3;
  const 小幅 = Math.max(20, Math.round(野.道幅 * 0.7));
  const 掘の向 = rnd() < 0.5 ? -1 : 1;
  const ak = am + 掘の向 * (長 / 2 + 小幅 * 2 + 30);
  野.道.push({ 名: "街道", 幅: 野.道幅, 節: 筋(野, [[-30, cm + (rnd() - 0.5) * C * 0.2], [am - 長 * 0.85, cm], [am + 長 * 0.85, cm],
    [L + 30, cm + (rnd() - 0.5) * C * 0.2]], 3, 野.道幅 * 0.25) });
  for (const s of [-1, 1]) {
    const 端 = am + 掘の向 * (長 / 2 + 小幅 * 2 + 30 + 小幅 * 3);
    野.道.push({ 名: "裏通り", 幅: 小幅, 節: [点(野, am - 掘の向 * 長 / 2, cm + s * 裏), 点(野, 端, cm + s * 裏)] });
  }
  const 横筋 = [am - 長 * 0.5, am - 長 * 0.17, am + 長 * 0.17, am + 長 * 0.5];
  for (const a of 横筋) 野.道.push({ 名: "横町", 幅: 小幅, 節: [点(野, a, cm - 幅 / 2), 点(野, a, cm + 幅 / 2)] });
  /* 町家の区。通りに挟まれた所ごとに一つ */
  const 横帯 = [[cm - 幅 / 2, cm - 裏], [cm - 裏, cm], [cm, cm + 裏], [cm + 裏, cm + 幅 / 2]];
  const 中芯 = 1 + (rnd() < 0.5 ? 0 : 1);
  for (let j = 0; j + 1 < 横筋.length; j++) {
    横帯.forEach(([c0, c1], k) => {
      const rr = 0.46 * Math.min(c1 - c0 - 小幅, 横筋[j + 1] - 横筋[j] - 小幅);
      if (rr < 30) return;
      const 芯の区 = j === 1 && k === 中芯;
      野.村.push({ ...点(野, (横筋[j] + 横筋[j + 1]) / 2, (c0 + c1) / 2), r: Math.round(rr), 横: 野.村の横,
        ...(芯の区 ? { 名: 野.質 === "街道" ? "城下" : "宿場", 札: true } : {}) });
    });
  }
  /* 掘割 */
  const 堀幅 = Math.round(clamp(野.尺H * 0.02, 34, 80));
  const 堀 = { 名: "掘割", 幅: 堀幅, 渡し: [], 節: 筋(野, [[ak + 掘の向 * L * 0.012, cm - 幅 * 0.64], [ak, cm - 幅 * 0.2], [ak, cm + 幅 * 0.2],
    [ak - 掘の向 * L * 0.012, cm + 幅 * 0.64]], 3, 堀幅 * 0.2) };
  野.川.push(堀);
  for (const c of [cm, cm - 裏, cm + 裏]) 渡しを置く(野, 堀, ak, c, "橋");
  /* 寺の境内。脇の小高い所に、杜を負う */
  const rt = clamp(70 * sc, 90, C * 0.1), 寺側 = rnd() < 0.5 ? -1 : 1;
  const 寺 = 点(野, am - 掘の向 * 長 * 0.15, cm + 寺側 * (幅 / 2 + rt * 1.2 + 小幅));
  野.丘.push({ ...寺, r: Math.round(rt), 名: "寺の丘", 札: true, 高: Math.round(60 + rnd() * 20) });
  野.林.push({ ...寺, r: Math.round(rt * 0.62) });
  /* 町はずれの田と林 */
  const 外 = (a, c, rr) => (Math.abs(c - cm) > 幅 / 2 + rr + C * 0.04 || Math.abs(a - am) > 長 / 2 + rr + L * 0.08) && !布陣の場か(野, a, c, rr);
  野.沼.push(...散らす(野, 2 + (rnd() < 0.5 ? 1 : 0), clamp(60 * sc, 80, 300) * 0.8, clamp(60 * sc, 80, 300), 外,
    [...野.村, ...野.丘], { 添: { 葦: 0.3 } }));
  野.林.push(...散らす(野, 4, clamp(40 * sc, 56, 220), clamp(70 * sc, 80, 340), 外, [...野.村, ...野.丘, ...野.沼]));
}

/* 八 湿田の畷（残りの街道から賽で）

   盤の中ほどを、一面の深田（湿地）が横切る。深田の中を細い畷（あぜ道）が通る――
   街道と、両脇の二筋の畷、それを結ぶ横の畷。畷を外れると足は半分に落ち、騎馬は
   突けない。深田の中には島のような微高地が二つ三つあり、里や林が乗る。
   両軍の布陣の場は乾いた野。 */
function 畷(野) {
  const { L, C, sc, rnd } = 野;
  const a1 = L * (0.29 + rnd() * 0.04), a2 = L * (0.71 - rnd() * 0.04);
  const s = clamp(170 * sc, 190, Math.min(L, C) * 0.13);
  const r = s * 0.8;
  const cm = C * (0.5 + (rnd() - 0.5) * 0.2);
  const 脇 = [cm - C * (0.26 + rnd() * 0.06), cm + C * (0.26 + rnd() * 0.06)];
  const ax = (a1 + a2) / 2 + (rnd() - 0.5) * (a2 - a1) * 0.3;
  const 畷幅 = Math.max(18, Math.round(野.道幅 * 0.55));
  野.道.push({ 名: "街道", 幅: Math.max(畷幅, Math.round(野.道幅 * 0.75)), 節: 筋(野, [[-30, cm + (rnd() - 0.5) * C * 0.16], [a1 - s, cm],
    [a2 + s, cm], [L + 30, cm + (rnd() - 0.5) * C * 0.16]], 3, 野.道幅 * 0.3) });
  for (const c of 脇) {
    if (c < C * 0.06 || c > C * 0.94) continue;
    野.道.push({ 名: "畷", 幅: 畷幅, 節: 筋(野, [[a1 - s * 1.2, c], [a2 + s * 1.2, c]], 6, 畷幅 * 0.4) });
  }
  野.道.push({ 名: "畷", 幅: 畷幅, 節: 筋(野, [[ax, Math.max(C * 0.05, 脇[0] - C * 0.05)], [ax, Math.min(C * 0.95, 脇[1] + C * 0.05)]], 6, 畷幅 * 0.4) });
  /* 島（微高地）。畷から離して置く */
  const 島 = [];
  for (let i = 0; i < 40 && 島.length < 2 + (rnd() < 0.5 ? 1 : 0); i++) {
    const a = a1 + s + rnd() * (a2 - a1 - 2 * s), c = C * (0.08 + rnd() * 0.84), ri = s * (1.0 + rnd() * 0.3);
    if (Math.abs(a - ax) < ri + s * 0.3 || [cm, ...脇].some((x) => Math.abs(c - x) < ri + s * 0.3)) continue;
    if (島.some((p) => Math.hypot(p.a - a, p.c - c) < p.r + ri + s * 1.2)) continue;
    島.push({ a, c, r: ri });
  }
  /* 深田 */
  for (let a = a1 + r * 0.5; a <= a2 - r * 0.5 + 1; a += s * 0.9) {
    for (let c = -C * 0.04; c <= C * 1.04; c += s * 0.95) {
      const aa = a + (rnd() - 0.5) * s * 0.25, cc = c + (rnd() - 0.5) * s * 0.25;
      if (島.some((p) => Math.hypot(aa - p.a, cc - p.c) < p.r + r * 0.6)) continue;
      野.沼.push(円(野, aa, cc, r * (0.9 + rnd() * 0.2), { 葦: 0.3 }));
    }
  }
  島.forEach((p, i) => {
    if (i < 2) 野.村.push({ ...点(野, p.a, p.c), r: Math.round(p.r * 0.55), 横: 野.村の横, ...(i === 0 ? { 名: "島の里", 札: true } : {}) });
    else 野.林.push(円(野, p.a, p.c, p.r * 0.6));
  });
  /* 深田の縁の並木（畷の所は空ける）と、乾いた野の里 */
  for (const a of [a1 - s * 0.55, a2 + s * 0.55]) {
    for (let c = C * 0.04; c < C * 0.96; c += s * (1.4 + rnd() * 0.8)) {
      const rr = s * (0.22 + rnd() * 0.12), p = 点(野, a, c);
      if (空きか(野, p, rr, [], { 水: false })) 野.林.push({ ...p, r: Math.round(rr) });
    }
  }
  野.村.push(...散らす(野, 2, clamp(36 * sc, 50, 180), clamp(46 * sc, 60, 210),
    (a, c, rr) => !布陣の場か(野, a, c, rr) && (a < a1 - s * 1.2 || a > a2 + s * 1.2), [...野.林], { 添: { 横: 野.村の横 } }));
}

/* 九 森を抜ける道（残りの街道から賽で）

   盤の中ほどを深い森が横切り、街道が森を抜ける。森の中には開けた所が二つ三つあり、
   一つには杣の里がある。森の縁は林になってほどける。森の中は見通しが利かない。 */
function 森(野) {
  const { L, C, sc, rnd } = 野;
  const a1 = L * (0.27 + rnd() * 0.04), a2 = L * (0.73 - rnd() * 0.04);
  const s = clamp(210 * sc, 230, Math.min(L, C) * 0.16);
  const r = s * 0.74;
  const cm = C * (0.5 + (rnd() - 0.5) * 0.24), 相 = rnd() * Math.PI * 2;
  const 道c = (a) => cm + Math.sin((a / L) * Math.PI * 1.6 + 相) * C * 0.06;
  const 芯 = Array.from({ length: 7 }, (_, i) => { const a = -30 + ((L + 60) * i) / 6; return [a, 道c(a)]; });
  野.道.push({ 名: "街道", 幅: 野.道幅, 節: 筋(野, 芯, 3, 野.道幅 * 0.5) });
  /* 開けた所。一つは街道の上に */
  const 開 = [];
  const am = (a1 + a2) / 2 + (rnd() - 0.5) * (a2 - a1) * 0.3;
  開.push({ a: am, c: 道c(am), r: s * (1.1 + rnd() * 0.3) });
  for (let i = 0; i < 60 && 開.length < 3; i++) {
    const a = a1 + s + rnd() * (a2 - a1 - 2 * s), c = C * (0.1 + rnd() * 0.8), rr = s * (1.0 + rnd() * 0.5);
    if (Math.abs(c - 道c(a)) < rr + s) continue;
    if (開.some((p) => Math.hypot(p.a - a, p.c - c) < p.r + rr + s)) continue;
    開.push({ a, c, r: rr });
  }
  for (let a = a1 + r * 0.4; a <= a2 - r * 0.4 + 1; a += s * 0.92) {
    for (let c = -C * 0.04; c <= C * 1.04; c += s * 0.95) {
      const aa = a + (rnd() - 0.5) * s * 0.3, cc = c + (rnd() - 0.5) * s * 0.3;
      if (開.some((p) => Math.hypot(aa - p.a, cc - p.c) < p.r + r * 0.4)) continue;
      野.森.push(円(野, aa, cc, r * (0.9 + rnd() * 0.25)));
    }
  }
  /* 森の縁の林 */
  for (const [a, 向] of [[a1 - s * 0.15, -1], [a2 + s * 0.15, 1]]) {
    for (let c = C * 0.02; c < C * 0.98; c += s * (0.9 + rnd() * 0.6)) {
      const rr = s * (0.3 + rnd() * 0.15), p = 点(野, a + 向 * rnd() * s * 0.3, c);
      if (!布陣の場か(野, a + 向 * s * 0.3, c, rr * 0.5) && 空きか(野, p, rr, [], { 水: false })) 野.林.push({ ...p, r: Math.round(rr) });
    }
  }
  if (開[1]) 野.村.push({ ...点(野, 開[1].a, 開[1].c), r: Math.round(開[1].r * 0.45), 名: "杣の里", 札: true, 横: 野.村の横 });
}

/* 十 丘陵の入り組み（残りの街道から賽で）

   盤の中ほどに大小の丘が入り組み、そのあいだの谷に林がある。真ん中に一つ大きな丘
   （中の丘）。浅い小川が一筋、丘のあいだを縫って野を横切る。街道は丘を縫って曲がる。
   丘に上がれば見晴らしが利き、丘の陰は見えにくい。 */
function 丘陵(野) {
  const { L, C, sc, rnd } = 野;
  const cm = C * (0.5 + (rnd() - 0.5) * 0.2), 相 = rnd() * Math.PI * 2, 振 = C * (0.06 + rnd() * 0.05);
  const 道c = (a) => cm + Math.sin((a / L) * Math.PI * 2.2 + 相) * 振;
  const 芯 = Array.from({ length: 9 }, (_, i) => { const a = -30 + ((L + 60) * i) / 8; return [a, 道c(a)]; });
  野.道.push({ 名: "街道", 幅: 野.道幅, 節: 筋(野, 芯, 3, 野.道幅 * 0.5) });
  /* 小川 */
  const 川a0 = L * (0.42 + rnd() * 0.16), 相2 = rnd() * Math.PI * 2;
  const 川a = (c) => 川a0 + Math.sin((c / C) * Math.PI * 2.4 + 相2) * L * 0.06;
  const 小幅 = Math.round(clamp(野.尺H * 0.024, 36, 90));
  const 小川 = { 名: "小川", 幅: 小幅, 渡し: [], 浅: true,
    節: 筋(野, Array.from({ length: 8 }, (_, i) => { const c = -C * 0.1 + (C * 1.2 * i) / 7; return [川a(c), c]; }), 4, 小幅 * 0.6) };
  野.川.push(小川);
  /* 中の丘 */
  const R = clamp(150 * sc, 170, Math.min(L, C) * 0.14);
  const ac = L * (0.4 + rnd() * 0.2);
  const 中 = 点(野, ac, 道c(ac) + (rnd() < 0.5 ? -1 : 1) * (野.道幅 + R * 1.25));
  if (空きか(野, 中, R, [])) 野.丘.push({ ...中, r: Math.round(R), 名: "中の丘", 札: true, 高: Math.round(170 + rnd() * 40) });
  /* 大小の丘 */
  const rh = clamp(95 * sc, 110, Math.min(L, C) * 0.1);
  野.丘.push(...散らす(野, Math.round(9 + (C * L) / (rh * rh * 60)), rh * 0.6, rh * 1.25,
    (a, c, rr) => (a - rr > L * 0.24 && a + rr < L * 0.76) || ((c < C * 0.07 || c > C * 0.93) && a > L * 0.08 && a < L * 0.92),
    [...野.丘.map((h) => ({ ...h, 間: 10 }))], { 間: 8, 添: null }).map((h) => ({ ...h, 高: Math.round(95 + (h.r / rh) * 45 + rnd() * 25) })));
  /* 道と小川の交わりに橋。交わりは、川の a と道の c を交互に引いて求める
     （どちらも振れの小さい曲がりなので、数度で落ち着く） */
  let 交c = cm;
  for (let k = 0; k < 24; k++) 交c = 道c(川a(交c));
  渡しを置く(野, 小川, 川a(交c), 交c, "橋");
  /* 谷の林と森、里 */
  野.林.push(...散らす(野, Math.round(6 + (C * L) / (rh * rh * 50)), rh * 0.3, rh * 0.55,
    (a, c, rr) => !布陣の場か(野, a, c, rr), [...野.丘.map((h) => ({ ...h, 間: -h.r * 0.35 }))]));
  野.森.push(...散らす(野, 1 + (rnd() < 0.6 ? 1 : 0), rh * 0.5, rh * 0.8, (a, c, rr) => !布陣の場か(野, a, c, rr), [...野.丘, ...野.林]));
  野.村.push(...散らす(野, 1 + (rnd() < 0.5 ? 1 : 0), clamp(36 * sc, 50, 180), clamp(46 * sc, 60, 210),
    (a, c, rr) => !布陣の場か(野, a, c, rr), [...野.丘, ...野.林, ...野.森], { 添: { 横: 野.村の横 } }));
}

const 描き手 = { 峠, 谷, 段, 大河, 湖, 浜: (野) => 浜(野, false), 磯: (野) => 浜(野, true), 町, 畷, 森, 丘陵 };

/* 型の野を描く。書付 … 野の型を決める の返り。返すのは筋書きの野と同じ形の地物
   （field.js 型の野を組む が写す）。帯 … 布陣させる横の帯（盤の歩）。 */
export function 型の野(書付, { 種, W, H, 尺W, 質 }) {
  const 描く = 書付 && 描き手[書付.型];
  if (!描く) return null;
  const 野 = 野を起こす(書付.型, { 種, W, H, 尺W, 質, 向き: 書付.向き, 鏡: 書付.鏡, 名ら: 書付.名ら });
  描く(野);
  /* 木と葦の数を抑える（間引きの割を円ごとに持たせる。mori.js・sato.js が読むのと同じ式で
     数える）。一円あたりの頭打ちがあるので、割を掛けても思うほど減らぬことがある。数え直して
     頭に収まるまで割を詰める */
  const 木数 = () => 野.森.reduce((t, f) => t + Math.min(9000, Math.round((Math.PI * f.r * f.r) / 81 * (f.密 ?? 1))), 0)
    + 野.林.reduce((t, f) => t + Math.min(9000, Math.round((Math.PI * f.r * f.r) / 225 * (f.密 ?? 1))), 0);
  const 葦数 = () => 野.沼.reduce((t, m) => t + Math.min(5000, Math.round((Math.PI * m.r * m.r) / 120 * (m.葦 ?? 1))), 0);
  for (let k = 0, n = 木数(); k < 8 && n > 木の頭; k++, n = 木数()) {
    for (const f of [...野.森, ...野.林]) f.密 = Math.round((f.密 ?? 1) * (木の頭 / n) * 0.98 * 1000) / 1000;
  }
  for (let k = 0, n = 葦数(); k < 8 && n > 葦の頭; k++, n = 葦数()) {
    for (const m of 野.沼) m.葦 = Math.round((m.葦 ?? 1) * (葦の頭 / n) * 0.98 * 1000) / 1000;
  }
  let 帯 = null;
  if (野.帯) {
    const [c0, c1] = 野.帯, i = 野.縦 ? 0 : 1;
    const p0 = 野.写(野.L / 2, c0)[i], p1 = 野.写(野.L / 2, c1)[i];
    帯 = { 中: Math.round((p0 + p1) / 2), 幅: Math.round(Math.abs(p1 - p0)) };
  }
  const 表 = 型の表[野.型];
  return { 型: 野.型, 名: 表.名, 詞: 表.詞, w: 野.W, h: 野.H, 升: 10,
    山: 野.山, 丘: 野.丘, 森: 野.森, 林: 野.林, 村: 野.村, 沼: 野.沼, 川: 野.川, 道: 野.道, 帯 };
}
