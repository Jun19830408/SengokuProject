/* ==========================================================================
   戦場の型（GDD 8.1）── 街道の性格から、野の形を決める

   遊ぶ側の申し出は「天下分け目以外のキャンペーンモードの戦場を増やしたいですね。
   もう少し今の街道に沿いつつ、さらに特徴的な戦場を10くらい追加したい」であった。

   街道ごとの野（field.js genTerrain）は、街道の質で山の数が変わるほかは、川・丘・
   森・村を賽で撒くだけである。どの街道で戦っても、似たような原っぱになる。
   そこで、戦う街道の性格――難所か山道か、大河を渡るか、湖のそばか、海沿いの城
   どうしか、道のりが短いか――から野の型を決め、その型の形に野を組む。

     峠の鞍部       … 難所。山並みが野を横切り、街道は低い鞍部を越える
     谷あいの川沿い … 山道の半ば。両側に山が迫り、川が街道に沿って流れる
     山裾の段々     … 山道の残り。片側が山で、段々の丘が野へ下りる
     大河の渡し     … 大河を渡る街道。橋一つと浅瀬二つ、川中に中洲
     湖岸の細道     … 湖のそば。片側が湖、片側が山、山の鼻が湖へ突き出す
     浜の道         … 海沿いの城どうし。片側が海、松原と河口
       （磯の難所） … 海沿いでも山越えの道なら、山が海へ落ちる崖の下の浜
     城下・宿場の町 … 道のりの短い街道。町家と掘割と寺の境内
     湿田の畷       … 残りの街道から賽で。深田の中を細い畷が通る
     森を抜ける道   … 同じく賽で。深い森と、ところどころの開けた所
     丘陵の入り組み … 同じく賽で。小さな丘と谷が入り組む
   残りの街道の半ばは、これまでどおり賽で撒いた野のままにする。

   型の野は、筋書きの野（関ヶ原・天下分け目）と同じ形で地物を持つ――山と丘は円を
   連ねた尾根、川と湖と海は折れ線、渡しは川の上の円。小川と沢は浅い流れ（浅）で、
   どこでも瀬として渡れる。幅の狭い流れを淵にすると、隊が水際で待ちあぐねて押し渡り、
   水の中で槍を合わせることになった（試験 kata の八）。盤の上の理（terrainAt）は
   升目に焼いて引く（field.js 型の野を組む）。

   型はみな「寄せ手が手前から奥へ進む」形で書く。a は寄せ手の端から受け手の端への
   道のり（零から L）、c は寄せ手から見た左の端から右の端への横（零から C）である。
   攻め口の向きに回して盤へ写す（写）。街道は寄せ手の端から受け手の端へ通るので、
   地図の上で街道が東西に通っていれば、盤の上でも東西に通る。

   地物の大きさは、街道ごとの野と同じく広げる前の幅（尺の幅）で決める。隊と地物の
   釣り合いは変えない。並びと長さは盤の広さなりに伸ばす。丘の高さ（絵の起伏。m）は
   賽で撒く野の丘（半径の四割、二百mまで）と同じほどに取る。はじめ五、六十mにしたら、
   斜めの眺めで丘が平らに見えて、丘陵の野に丘が一つも無いように見えた。

   両軍の布陣の場（a が盤の二割四分より手前と、七割六分より奥）には、布陣を嫌う地物
   （森・林・村・沼・丘・水）を置かない。湖や海や山に脇を塞がれた型は、布陣させる
   横の帯（帯）を盤へ渡し、合戦の画面はその帯の中に隊を並べる（MapScreen lineup）。
   ========================================================================== */
