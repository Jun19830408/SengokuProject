/* ------------------------------------------------------------- 型を選ぶ

   性 … 街道の性格（core/senjo.js 街道の性格）。種 … 野の種（両端の城から作る）。
   一本の街道がいくつもの型に当たるときは、目立つ地形を先に取る。海沿いの山道は
   磯の難所、大河を渡る難所は峠である。賽は種から直に引く（野の賽の流れは使わない）。 */
export function 型を選ぶ(性, 種) {
  if (!性 || 性.質 === "海路") return null;
  const 賽 = ((種 >>> 0) & 1023) / 1024, 残りの賽 = ((種 >>> 20) & 1023) / 1024;
  const 山越え = 性.質 === "山道" || 性.質 === "難所";
  if (性.海 && 山越え) return "磯";
  if (性.質 === "難所") return "峠";
  if (性.大河) return "大河";
  if (性.湖) return "湖";
  if (性.海) return "浜";
  if (性.質 === "山道") return 賽 < 0.5 ? "谷" : "段";
  if (性.距 <= 12) return "町";
  if (残りの賽 < 0.5) return null;                 // 半ばはこれまでどおり賽で撒いた野
  return 残りの賽 < 0.67 ? "畷" : 残りの賽 < 0.84 ? "森" : "丘陵";
}

/* 盤へ渡す型の書き付け（layoutField の三つ目の引数）。向き … 攻め口（S・N・E・W）。
   湖と海は、地図の上で寄せ手の左右どちらにあるか（性.湖.側・性.海.側）に合わせて置く。
   型は水を左に書くので、右にあるなら鏡に写す。左右の定まらぬ型は種で決める。 */
export function 野の型を決める(性, 種, 向き) {
  const 型 = 型を選ぶ(性, 種);
  if (!型) return null;
  const 側 = 型 === "湖" ? 性.湖.側 : 型 === "浜" || 型 === "磯" ? 性.海.側 : 0;
  return {
    型, 向き: 向き || "S",
    鏡: 側 ? 側 > 0 : ((種 >>> 11) & 1) === 1,
    名ら: { 川: 性.大河 || null, 湖: 性.湖 ? 性.湖.名 : null },
  };
}

/* ------------------------------------------------------------- 野を組む道具 */

/* 型ごとに賽の流れを分ける（同じ街道で型だけ替えても、似た並びにならぬよう） */
const 型の塩 = { 峠: 0x51ed27, 谷: 0x2c1b3c, 段: 0x7a3f11, 大河: 0x19e3b7, 湖: 0x4b1d93, 浜: 0x6f2a55,
  磯: 0x6f2a56, 町: 0x0d77c5, 畷: 0x33a1e9, 森: 0x5c0fd2, 丘陵: 0x28b74e };

/* 木と葦の数の頭。木も葦も一本ずつ立てて描くので、数が多いと合戦が重くなる。
   天下分け目の野でいちばん木の多い二川の平野が、およそ四万六千本である。 */
const 木の頭 = 42000, 葦の頭 = 30000;

function 野を起こす(型, o) {
  const W = o.W, H = o.H, 向き = o.向き || "S";
  const 縦 = 向き === "S" || 向き === "N";
  const L = 縦 ? H : W, C = 縦 ? W : H;
  const 尺W = Math.max(1, Math.min(W, o.尺W || W));
  const sc = clamp(尺W / 1080, 1, 4.6);
  const 鏡 = !!o.鏡;
  /* 型の所（a, c）から盤の所（x, y）へ。S … 寄せ手が南の辺から北へ進む */
  const 写 = (a, c) => {
    const cc = 鏡 ? C - c : c;
    return 向き === "N" ? [W - cc, a] : 向き === "E" ? [W - a, H - cc] : 向き === "W" ? [a, cc] : [cc, H - a];
  };
  return {
    型, W, H, L, C, 縦, 鏡, sc, 尺W, 尺H: 尺W * (H / W),
    幅倍: clamp(Math.pow(尺W / 1080, 0.3), 1, 1.7),
    道幅: Math.round(clamp(36 * Math.sqrt(sc), 34, 86)),
    /* 村の道（家並み）を街道と同じ向きに通す。縦に進む盤なら南北の道、横なら東西 */
    村の横: !縦,
    rnd: makeRng((((o.種 >>> 0) ^ (型の塩[型] || 0x9e3779b9)) >>> 0) || 1),
    写, 名ら: o.名ら || {}, 質: o.質 || "街道",
    山: [], 丘: [], 森: [], 林: [], 村: [], 沼: [], 川: [], 道: [], 帯: null,
  };
}

const 点 = (野, a, c) => { const [x, y] = 野.写(a, c); return { x: Math.round(x), y: Math.round(y) }; };
const 円 = (野, a, c, r, 添) => ({ ...点(野, a, c), r: Math.round(r), ...(添 || {}) });

/* 折れ線（盤の所）までの隔たりと、いちばん近い所 */
function 線に寄せる(節, x, y) {
  let 最 = Infinity, 先 = { x, y };
  for (let i = 0; i + 1 < 節.length; i++) {
    const a = 節[i], b = 節[i + 1];
    const vx = b.x - a.x, vy = b.y - a.y, L2 = vx * vx + vy * vy;
    let t = L2 ? ((x - a.x) * vx + (y - a.y) * vy) / L2 : 0;
    t = t < 0 ? 0 : t > 1 ? 1 : t;
    const px = a.x + vx * t, py = a.y + vy * t, d = (px - x) ** 2 + (py - y) ** 2;
    if (d < 最) { 最 = d; 先 = { x: Math.round(px), y: Math.round(py) }; }
  }
  return 先;
}
const 線までの距 = (節, x, y) => { const p = 線に寄せる(節, x, y); return Math.hypot(p.x - x, p.y - y); };

/* 尾根（wakemeba.js の 尾根 と同じ作り）。節を結んで円を連ね、峰の外に低く広い裾を重ねる。
   節 … [[a, c, 高（m）, 半径], ...]。札 … 真ん中の峰に名札を立てる */
function 尾根(野, 節, { 名, 札 = false, 間 = 0.62, 裾 = 0.55, 裾の倍 = 1.28, 裾なし = false } = {}) {
  const 峰 = [];
  for (let i = 0; i < 節.length - 1; i++) {
    const [a1, c1, h1, r1] = 節[i], [a2, c2, h2, r2] = 節[i + 1];
    const 数 = Math.max(1, Math.round(Math.hypot(a2 - a1, c2 - c1) / (Math.min(r1, r2) * 間)));
    for (let k = 0; k < 数; k++) {
      const t = k / 数;
      峰.push(円(野, a1 + (a2 - a1) * t, c1 + (c2 - c1) * t, r1 + (r2 - r1) * t, { 名, 高: Math.round(h1 + (h2 - h1) * t) }));
    }
  }
  const [la, lc, lh, lr] = 節[節.length - 1];
  峰.push(円(野, la, lc, lr, { 名, 高: Math.round(lh) }));
  if (札) 峰[Math.floor(峰.length / 2)].札 = true;
  const 裾ら = 裾なし ? [] : 峰.filter((_, i) => i % 2 === 0)
    .map((o) => ({ 名, 高: Math.round(o.高 * 裾), x: o.x, y: o.y, r: Math.round(o.r * 裾の倍) }));
  return [...峰, ...裾ら];
}

/* 折れ線の節を細かく割り、少し蛇行させる（wakemeba.js の 筋 と同じ作り）。
   揺れは節と節の間だけに付けるので、節の所は動かない */
function 筋(野, pts, 割 = 4, 揺 = 0) {
  const 出 = [];
  for (let i = 0; i < pts.length - 1; i++) {
    const [a1, c1] = pts[i], [a2, c2] = pts[i + 1];
    const da = a2 - a1, dc = c2 - c1, 長 = Math.hypot(da, dc) || 1;
    const na = -dc / 長, nc = da / 長;
    for (let k = 0; k < 割; k++) {
      const t = k / 割, w = 揺 ? (野.rnd() - 0.5) * 2 * 揺 * Math.sin(Math.PI * t) : 0;
      出.push(点(野, a1 + da * t + na * w, c1 + dc * t + nc * w));
    }
  }
  const [la, lc] = pts[pts.length - 1];
  出.push(点(野, la, lc));
  return 出;
}

/* 布陣の場か。両軍の前の列（盤の一割四分と八割六分）から後ろ。帯があれば帯の内だけ */
function 布陣の場か(野, a, c, r = 0) {
  if (a - r > 野.L * 0.24 && a + r < 野.L * 0.76) return false;
  const [c0, c1] = 野.帯 || [野.C * 0.06, 野.C * 0.94];
  return c + r > c0 && c - r < c1;
}

/* 空いているか。避 … 避ける円（盤の所。間 を持てばその分も空ける）。
   道と水からも離す（道を避けぬ木立は、道に切られて二つに割れる） */
function 空きか(野, p, r, 避 = [], { 道 = true, 水 = true, 道の間 = 12, 水の間 = 24 } = {}) {
  for (const o of 避) if (Math.hypot(o.x - p.x, o.y - p.y) < (o.r || 0) + r + (o.間 != null ? o.間 : 24)) return false;
  if (道) for (const d of 野.道) if (線までの距(d.節, p.x, p.y) < d.幅 / 2 + r + 道の間) return false;
  if (水) for (const w of 野.川) if (線までの距(w.節, p.x, p.y) < w.幅 / 2 + r + 水の間) return false;
  return true;
}

/* 散らす。寄（a, c, r）→ 置いてよいか。互いには 間 だけ空ける */
function 散らす(野, n, rMin, rMax, 寄, 避 = [], { 間 = 30, 試み = 50, 道 = true, 水 = true, 添 = null,
  a0 = -野.L * 0.05, a1 = 野.L * 1.05, c0 = -野.C * 0.05, c1 = 野.C * 1.05 } = {}) {
  const 出 = [];
  for (let i = 0; i < n * 試み && 出.length < n; i++) {
    const a = a0 + 野.rnd() * (a1 - a0), c = c0 + 野.rnd() * (c1 - c0);
    const r = rMin + 野.rnd() * (rMax - rMin);
    if (!寄(a, c, r)) continue;
    const p = 点(野, a, c);
    if (!空きか(野, p, r, 避, { 道, 水 })) continue;
    if (出.some((o) => Math.hypot(o.x - p.x, o.y - p.y) < o.r + r + 間)) continue;
    出.push({ ...p, r: Math.round(r), ...(添 || {}) });
  }
  return 出;
}

/* 川の上の渡し。いちばん近い川筋の所に据える。橋も瀬も、その円が川幅を跨がねば
   渡れない（升目は円で塗る）。橋は隘路なので跨ぐ分だけ、瀬は広めに取る */
function 渡しを置く(野, 川, a, c, 種) {
  const p = 点(野, a, c), q = 線に寄せる(川.節, p.x, p.y);
  const r = 種 === "橋"
    ? 川.幅 / 2 + clamp(28 * 野.幅倍, 28, 48)
    : 川.幅 / 2 + clamp(72 * 野.幅倍, 60, 130);
  川.渡し.push({ x: q.x, y: q.y, r: Math.round(r), 種 });
}

/* 尾根の筋を引く（a に沿って並べる）。c芯 … 筋の横。高0 … 峰の高さの下限 */
function 縦の並み(野, c芯, 高0, r, 揺c = () => 0) {
  return Array.from({ length: 6 }, (_, i) => {
    const a = -野.L * 0.14 + (野.L * 1.28 * i) / 5;
    return [a, c芯 + 揺c(a), 高0 + 野.rnd() * 120, r * (0.9 + 野.rnd() * 0.2)];
  });
}

/* 広い水（湖・海）。岸 … 水際の横（c）。入り江 … 岸に掛ける入り江の数。
   流れの筋は引かない（湖 の印。mori.js 川の流れを描く）。

   はじめは盤の外へ大きく張り出す一本の太い筋（幅九千歩ほど）で表した。地の焼きは水の
   深さを「岸からの隔たり÷水の幅の半ば」で決めるので、岸から千四百歩ほどが浅い水として
   ぼやけ、折れ線の節の継ぎ目が岸の近くに網の目のような筋になって出た。天下分け目の湖
   （幅千から千五百歩）はきれいに描けている。そこで、幅千六百歩の真っすぐな帯（節の継ぎ目
   が無い）を、沖へ向けて重ねて並べる。岸の出入りは、岸に掛けた短い入り江（丸い端の短い
   筋）で付ける。盤の外の水は、盤の外を塗るときに同じ形で塗る（draw.js 盤の外を塗る） */
function 広い水(野, 名, 岸, 入り江, 海) {
  const { L, C, rnd } = 野;
  const 幅 = 1600, 間 = 1100, 果て = -C * 0.45;
  const 印 = { 湖: true, ...(海 ? { 海: true } : {}) };
  for (let k = 0; k < 14; k++) {
    const c = 岸 - 幅 / 2 - k * 間;
    野.川.push({ 名, 幅, 節: [点(野, -L * 0.45, c), 点(野, L * 1.45, c)], 渡し: [], ...印 });
    if (c - 幅 / 2 <= 果て) break;
  }
  for (let i = 0; i < 入り江; i++) {
    const a = L * (0.3 + rnd() * 0.4), 長 = L * (0.05 + rnd() * 0.07);
    const w = clamp(C * (0.05 + rnd() * 0.05), 220, 900), 出 = w * (0.2 + rnd() * 0.25);
    const c = 岸 + 出 - w / 2;
    野.川.push({ 名, 幅: Math.round(w), 節: [点(野, a - 長 / 2, c), 点(野, a + 長 / 2, c)], 渡し: [], ...印 });
  }
}

/* 街道の芯（型の所）。点を結んだ折れ線の上で、a のときの c を返す */
function 芯の横(pts, a) {
  for (let i = 0; i + 1 < pts.length; i++) {
    const [a1, c1] = pts[i], [a2, c2] = pts[i + 1];
    if ((a - a1) * (a - a2) <= 0 && a1 !== a2) return c1 + (c2 - c1) * (a - a1) / (a2 - a1);
  }
  return a < pts[0][0] ? pts[0][1] : pts[pts.length - 1][1];
}

