import { 同じ旗の下 } from "./state.js";

/* ==========================================================================
   城方の後詰（GDD 9.2）

   遊ぶ側の申し出は「政務フェーズで、例えばプレイヤーが2万人の兵である城を攻めた場合、敵側も
   できるだけ兵数を集めて戦うようにする。…現在は、攻められた城の兵のみが野戦に出るだけなので、
   攻め落としやすくなっています。援軍（特に自軍からの援軍）を活用するようにしてください」、
   そして「援軍がいる場合で城攻めとなったら、その援軍は城攻めにも参加し、城の外で相手を
   待ち構えるような布陣（城の前面等で布陣して城攻めを防ぐ）」であった。

   もとは、敵の軍が城に着いたときの野戦（城下の野戦）に出るのは城の兵だけで、城の下に陣を張る
   味方の軍（在陣）や、同じ月に着いた後詰は加わらなかった（遊ぶ側の城だけは「後詰の野戦」に
   なっていた）。在陣の軍は、城が囲まれた翌月に囲みを衝く後詰に立つだけで、城下の野戦にも
   城攻めの盤にも出なかった。

   城方の後詰ら は、城下の野戦と城攻めの盤で城方に立つ味方の軍を選ぶ。
     ・城に着いている（道の残りが無い）。囲みに出ている軍は除く
     ・城の家と同じ家か、同じ旗の下の家の軍
     ・寄せ手の家とその旗の下の家の軍は除く
     ・その城に陣を張っている（在陣）か、その城を救いに来た（後詰の印 relief、あるいはその城を
       的として着いた）軍
   ========================================================================== */
export function 城方の後詰ら(s, castle, 寄せ手) {
  if (!s || !castle) return [];
  const 寄id = 寄せ手 ? 寄せ手.id : null, 寄家 = 寄せ手 ? 寄せ手.faction : null;
  return (s.armies || []).filter((a) => a && a.id !== 寄id && !a.dead && (a.men || 0) > 0
    && a.at === castle.id && (!a.path || a.path.length <= 1) && !a.sieging
    && (a.faction === castle.faction || 同じ旗の下(s, a.faction, castle.faction))
    && !(寄家 && (a.faction === 寄家 || 同じ旗の下(s, a.faction, 寄家)))
    && (a.在陣 === castle.id || a.relief === castle.id || a.target === castle.id));
}

/* 城下の野戦のあと、城方に立った後詰の軍の身の振り（GDD 9.2）。
     城方が勝った（寄せ手が退いた）… 城の下に陣を張ったまま残る（次の寄せにも立つ）
     城方が敗れて城が囲まれた     … 兵が三百を超え、発ったときの三割を保っていれば、城の下に
                                     踏みとどまる（城攻めの盤では城の前に構え、翌月には囲みを
                                     衝く後詰に立つ）。そうでなければ退く
   返すのは "留まる" か "退く" */
export function 野戦の後の後詰(勝った, 兵, 発った兵) {
  if (勝った) return "留まる";
  return 兵 >= 300 && 兵 >= (発った兵 || 兵) * 0.3 ? "留まる" : "退く";
}
