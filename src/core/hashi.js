/* ==========================================================================
   落とした橋（GDD 9.3）

   遊ぶ側の申し出は「橋が壊れているのも、防御度を回復しておかないと直らず、
   防御度を一定程度上げたら橋が付く設定にするといい」であった。

   城攻めの盤で城方が橋を落とすと（battle/field.js 橋を落とす）、その橋は戦のあとも
   落ちたままである。寄せ手が夜に架けた仮橋は、その戦かぎりのものとして数えない。
   以後この城を攻める盤では、始めから橋が無い（寄せ手も、討って出る城方も浅瀬へ回る）。

     架け直し … 城の防備を、橋を落としてからいちばん下がった所より 橋を架け直す幅 だけ
                上げ直せば、橋が架かる。築城の下知は一度に三から五上がるので、二、三度ぶん
                である（govern/commands.js 築城）。采配の城の普請は一度に二上がる
     下がる時 … 落ちたままのあいだに防備が下がれば（城攻めの傷み・囲みの月の目減り）、
                上げ直す起点もそこまで下がる
     城が替わる時 … 橋は城に付く。城の主が替わっても落ちたままである

   盤の川は寄せ手の来た道しだいで有ったり無かったりする（野の種は来た城と囲む城で
   決まる）。そこで、落ちたままの印は、盤の上で実際に橋を落とした戦のあとに付ける
   （ui/MapScreen.jsx 城攻めの後始末）。

   持つ形は城の上に置く。
     castle.落橋 … { 基: 橋を落としてからいちばん下がった防備 }。架かっていれば null
   ========================================================================== */
export const 橋を架け直す幅 = 8;

const 防備 = (c) => Math.round((c && c.def) || 0);

/* 盤の上で橋を落とした戦のあとに呼ぶ。すでに落ちたままなら、起点を下げるだけ */
export function 橋を落としたままにする(castle) {
  if (!castle) return;
  const d = 防備(castle);
  castle.落橋 = { 基: castle.落橋 ? Math.min(castle.落橋.基, d) : d };
}

/* 架け直すまでに、あと幾つ防備を上げればよいか（落ちていなければ〇） */
export function 橋の残り(castle) {
  if (!castle || !castle.落橋) return 0;
  return Math.max(0, castle.落橋.基 + 橋を架け直す幅 - 防備(castle));
}

/* 防備を見て、起点を下げるか、架け直す。架け直したら真を返す（月送りと築城の下知が呼ぶ） */
export function 橋の普請を見る(castle) {
  if (!castle || !castle.落橋) return false;
  const d = 防備(castle);
  if (d < castle.落橋.基) castle.落橋.基 = d;
  if (d >= castle.落橋.基 + 橋を架け直す幅) { castle.落橋 = null; return true; }
  return false;
}
