/* ============================================================ 差配を預ける（GDD 6.4）

   寄騎を与えるとは、その者の差配を寄親へ預けることである。

   もとは寄騎に効き目が一つしかなかった――出陣のとき寄親に従う、それだけ。
   何のために付けるのかが定まっていなかった。

   預けたものは「毎月の政務」である。大名がいちいち下知せずとも、寄親の差配で
   開墾・治水・徴募・訓練が進む。城が二十を超えれば、毎月の内政は作業になる。
   委任はそこに効く。これが大名（遊ぶ側）にとっての利である。

   委ねる範囲は寄親の役で決まる。下知ごとに選ばせはしない――選ばせれば画面も
   判じも膨らむ。「寄騎に取る／解く」の一つの操作だけで済ませる。

     国主の寄騎 … 内政（開墾・治水・商業・築城・訓練・徴募）
     旗頭の寄騎 … 内政 ＋ 守り（第三段）

   委ねないもの … 外交・調略・姫・知行・人事・他家への出陣。
   外交と人事は大名の専権であり、他家への出陣は陣触れと攻めの許しで扱う。

   縦の鎖は 城主 → 国主 → 旗頭 の一本道である。寄親は一人までなので、
   枝分かれはしない。 */
import { castellanOf } from "./rank.js";

/* その城の差配は預けられているか。預けられていれば寄親を返す。

   城主に寄親がいれば、その城は寄親の差配下にある。寄親自身の城は、その寄親が
   さらに誰かの寄騎でないかぎり、大名が直に見る。 */
export function 城の寄親(s, c) {
  if (!c) return null;
  const 主 = castellanOf(s, c);
  if (!主 || !主.寄親) return null;
  const 親 = (s.generals || []).find((x) => x.id === 主.寄親 && !x.captive);
  if (!親 || 親.faction !== c.faction) return null;
  if (親.役 !== "国主" && 親.役 !== "旗頭") return null;   // 役を離れた者に差配は預けられない
  return 親;
}

export const 差配を預けた城 = (s, fid) =>
  (s.castles || []).filter((c) => c.faction === fid && 城の寄親(s, c));

export const 大名が直に見る城 = (s, fid) =>
  (s.castles || []).filter((c) => c.faction === fid && !城の寄親(s, c));

/* 預けの目盛り（GDD 6.4）。

   家全体で一つ。委ねた城が生んだ実入りを、そのまま寄親に預けるのを「並」とする。
   会社の支社が自らの収支で回すのと同じで、少なめにすれば余りが本家の蔵へ残り、
   多めにすれば本家が足してやることになる。

   金そのものは動かさない。財布は家に一つのままで、これは「その月に使ってよい
   額の上限」である。予算とは承認であって、口座を分けることではない。 */
export const 預けの段 = [
  { 名: "少なめ", 率: 0.6, 説: "実入りの六分だけ預ける。余りは本家の蔵に残る" },
  { 名: "並", 率: 1.0, 説: "委ねた城の実入りを、そのまま預ける" },
  { 名: "多め", 率: 1.4, 説: "実入りより厚く預ける。本家の蔵から足してやる" },
];
/* 目盛りは 0（少なめ）・1（並）・2（多め）。零を偽と見て並に化けさせぬこと。 */
export const 預けの率 = (f) => {
  const i = f && f.預け != null ? f.預け : 1;
  return (預けの段[i] || 預けの段[1]).率;
};

/* 城が月に生む金。月送りの数え方と同じ式である（GDD 4.2）。
   ここを月送りと食い違わせると、預け高が実入りと合わなくなる。 */
export const 城の実入り = (c) => (c.comm || 0) * 4 + (c.koku || 0) * 0.003;

/* 寄親ごとの預け高。その寄親が差配する城の実入りに、目盛りを掛ける。 */
export function 預け高(s, fid) {
  const f = (s.factions || {})[fid] || {};
  const 率 = 預けの率(f);
  const 帳 = new Map();
  for (const c of 差配を預けた城(s, fid)) {
    const 親 = 城の寄親(s, c);
    if (!親) continue;
    const 前 = 帳.get(親.id) || { 親, 城: [], 実入り: 0 };
    前.城.push(c);
    前.実入り += 城の実入り(c);
    帳.set(親.id, 前);
  }
  for (const v of 帳.values()) v.預け = Math.round(v.実入り * 率);
  return [...帳.values()];
}

/* ============================================================ 旗頭に戦を任せる（GDD 6.4）

   旗頭は方面を預かる。柴田の北国、明智の丹波、秀吉の中国――信長が方面軍を
   置いたのは、そこまで一々下知していられなかったからである。内政だけでなく、
   戦と調略も任せねば、方面を預ける意味が薄い。

   ただし戦は大名の許しを要る。臣従した大名と同じ形である（core/yurushi.js）。
   臣従は他家であるからその家の外交が破れるのを恐れて縛るのだが、旗頭は家臣で
   あるから、縛る理由は違う――どこへ攻め入るかは家の運を決める。方面を預けた
   からといって、天下の絵図まで預けたわけではない。

   許しは城ごとに一度。落とすまで有効である。 */

export const 旗頭の許し控え = (s) => (s.旗頭の許し = s.旗頭の許し || []);

export const 旗頭は許されているか = (s, 旗頭id, castleId) =>
  旗頭の許し控え(s).some((x) => x.旗頭 === 旗頭id && x.castleId === castleId);

export function 旗頭に許す(s, 旗頭id, castleId) {
  if (旗頭は許されているか(s, 旗頭id, castleId)) return s;
  旗頭の許し控え(s).push({ 旗頭: 旗頭id, castleId, y: s.year, m: s.month });
  return s;
}

/* 済んだ許しを片づける。落とした城、旗頭でなくなった者。 */
export function 旗頭の済んだ許しを片づける(s) {
  s.旗頭の許し = 旗頭の許し控え(s).filter((x) => {
    const c = (s.castles || []).find((y) => y.id === x.castleId);
    const g = (s.generals || []).find((y) => y.id === x.旗頭);
    if (!c || !g || g.captive) return false;
    if (c.faction === g.faction) return false;            // 落とした（あるいは味方になった）
    if (g.役 !== "旗頭") return false;
    return true;
  });
  return s;
}

/* 旗頭が攻めたい城を見立てる。

   方面の国々にある自領の城と隣り合う、他家の城のうち、いちばん手近で
   兵の薄いものを選ぶ。旗の下（自家・臣従）の城は攻めない。 */
export function 旗頭の狙い(s, 旗, { 道: 道を引く, 旗の下 } = {}) {
  const 方面 = Array.isArray(旗.方面) ? 旗.方面 : [];
  if (!方面.length) return null;
  const 己方 = (s.castles || []).filter((c) => c.faction === 旗.faction && 方面.includes(c.kuni));
  if (!己方.length) return null;
  /* 狙うのは、預かる方面に隣接する敵から順である（GDD 6.4）。

     もとは「隣り合う城だけ」を見て、そのうち最も守りの薄いものを選んでいた。
     二つの難があった。一つは、隣り合う敵城が一つも無ければ何もしなかったこと。
     方面の内側が固まると、旗頭は永久に動かない。もう一つは、遠近を問わず
     守りの薄さだけで選んでいたので、方面の反対側の城へ向かうことがあったこと。

     方面の領土に近い敵から順に当たる。同じ近さなら、守りの薄いほうから。
     境を接する敵を片づけてから次へ進むのが、方面を預かる者の務めである。 */
  const 見 = [];
  for (const 的 of s.castles) {
    if (的.faction === 旗.faction) continue;
    if (旗の下 && 旗の下(s, 旗.faction, 的.faction)) continue;
    let 近 = null, 拠 = null;
    for (const c of 己方) {
      const 道 = 道を引く ? 道を引く(s, 旗.faction, c.id, 的.id) : null;
      if (!道) continue;
      const 歩 = 道.length - 1;                            // 何歩先か（隣り合えば一）
      if (近 == null || 歩 < 近) { 近 = 歩; 拠 = c; }
    }
    if (近 == null || 近 > 4) continue;                    // 方面から遠すぎる城は預かりの外
    const 守 = 的.local + (s.generals || [])
      .filter((x) => x.at === 的.id && x.faction === 的.faction && !x.captive)
      .reduce((a, x) => a + x.retinue, 0);
    見.push({ 的, 拠, 守, 近 });
  }
  if (!見.length) return null;
  見.sort((a, b) => a.近 - b.近 || a.守 - b.守);
  return 見[0];
}

/* 旗頭に預ける高。方面の国々にある自領の城の実入りに、目盛りを掛ける。

   寄騎の有無ではなく方面で数える。方面を預けるとは、その国々の差配を預ける
   ことだからである（寄騎はそのうち、政務まで委ねた城のことである）。 */
export function 旗頭の預け高(s, 旗) {
  const f = (s.factions || {})[旗.faction] || {};
  const 方面 = Array.isArray(旗.方面) ? 旗.方面 : [];
  const 城ら = (s.castles || []).filter((c) => c.faction === 旗.faction && 方面.includes(c.kuni));
  const 実 = 城ら.reduce((a, c) => a + 城の実入り(c), 0);
  return { 城: 城ら, 実入り: 実, 預け: Math.round(実 * 預けの率(f)) };
}

/* 大名が自ら采配を執る戦か（GDD 6.4）。

   旗頭に方面を預けたのだから、その手勢が他家へ寄せる戦は旗頭が指図する。
   大名が出るのは攻めの許しを与えるところまでであって、いざ城下に着いた途端に
   盤面を取り上げるのでは、任せたことにならない。月報で顛末を聞けばよい。

   ただし的が自家の城であれば話は別で、これは我が身の守りである。旗頭の手勢が
   後詰に立つ形になるが、采配は大名が執る。 */
export const 自ら采配するか = (s, army, 的) => {
  if (!army || army.faction !== s.player) return false;
  if (!army.旗頭) return true;                       // 大名の直の手勢
  return !!的 && 的.faction === s.player;            // 預けた手勢でも、自家の守りなら出る
};
