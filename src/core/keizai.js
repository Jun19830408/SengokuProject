/* ==========================================================================
   金の出入り（GDD 6.2）

   遊ぶ側の申し出は「お金が溜まりすぎるので、もっと溜まりにくいほうがいい。
   ただ、最初があまりにも少なすぎたので、普通の状態にしたい」であった。

   一五八八年の記録では、織田家の蔵が一千三万貫に達していた。画面なしで走らせると、
   大きくなったAIの家も同じで、兵が軍役の器に満ち、開墾も済んでしまうと、金の
   使い道が尽きて蔵に積もる一方になる（三好家は十六年で七十万貫）。一方、遊びの
   初めは月の実入りが七百貫ほどで、蔵は二千六百貫――普請を四、五度すれば尽きた。

   直し方は四つ。
     一、初めの蔵 … 月の実入りのおよそ半年分を足す（家ごとに違う）
     二、年貢の率 … 石高の千分の三から千分の四へ。小さな家ほど効く
     三、大身の費え … 領国が広がると、奉行・代官・普請・寺社への寄進が嵩む。
                     五十万石を超えた分に応じて、上がりの最大四割を差し引く
     四、蔵の目減り … 上がりの半年分（少なくとも一万貫）を超えて積んだ金は、
                     進物・献金・普請に月に六分ずつ出ていく。蔵は上がりの一年分ほどで
                     頭打ちになる
   ========================================================================== */
import { clamp } from "./util.js";

export const 年貢の率 = 0.004;
export const 商いの率 = 4;

/* 城一つの月の上がり（扶持を引く前）。

   年貢の割は、郡を治める者の手腕で増減する（core/gun.js の 城の年貢の割）。
   郡代を置けば上がり、能のある郡代ほど上がる。商いは城の余禄なので割を掛けない。
   割を渡さねば一とする。 */
export const 城の上がり = (c, 年貢の割 = 1) => (c.comm || 0) * 商いの率 + (c.koku || 0) * 年貢の率 * 年貢の割;

// 大身の費え。家の石高に応じて、上がりから差し引く割。
export const 大身の始まり = 500000;
export const 大身の割 = (総石高) => clamp((総石高 - 大身の始まり) / 10000000, 0, 0.4);

// 蔵の目減り。上がりの半年分を超えた金が、月にこの割で出ていく。
// 小さな家の蔵は目減りさせない。初めの蔵（もとの蔵＋月の実入りの半年分）も、上がりの半年分を
// 超えないので減らない。
export const 蔵の留め月 = 6;
export const 蔵の留めの下限 = 10000;
export const 蔵の目減り率 = 0.06;
export function 蔵の目減り(gold, 月の上がり) {
  const 留 = Math.max(蔵の留めの下限, Math.max(0, 月の上がり) * 蔵の留め月);
  return gold > 留 ? Math.round((gold - 留) * 蔵の目減り率) : 0;
}

// 初めの蔵。月の実入り（扶持を引いたもの）のおよそ半年分を、もとの二千六百貫に足す。
export const 初めの金 = (元, 月の実入り) => Math.round((元 || 0) + Math.max(0, 月の実入り) * 6);
