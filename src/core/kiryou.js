/* ============================================================ 大名の器量（GDD 6.2 / 13.2）

   家がどう動くかは、その家を背負う者の器量で決まる。

     政治が高ければ　… 内政と外交に手を伸ばし、家に効く手を選ぶ
     知略が高ければ　… 調略を好む
     武勇が高ければ　… 戦を好む（ただし無駄な戦はしない）
     統率が高ければ　… その性質が家中に行き渡る

   統率だけは働きが違う。統率は「何をするか」ではなく「大名の色がどれだけ家に
   出るか」を決める。統率の低い大名は、いかに武勇があっても家中が付いてこず、
   家の動きは中庸に寄る。信長の苛烈も、家中を締められたからこそ家の動きになった。

   ここは純関数だけを置く。采配の側（govern/month.js・govern/aiDiplo.js）は、
   ここで出した気風に腰の重さや要る兵力を掛けるだけにする。そうしておけば、
   画面を通さずに測れる（tools/chihou.cjs が地方の絞りを測る）。 */
const clamp = (v, a, b) => Math.max(a, Math.min(b, v));

/* その家の当主。居なければ null。 */
export const 家の当主 = (s, fid) =>
  (s.generals || []).find((g) => g.faction === fid && g.lord && !g.captive) || null;

/* 浸透。統率が家中への通りを決める。
   統率五十で三割五分、七十で五割五分、九十で七割五分ほど。 */
export const 浸透 = (lead) => clamp(0.35 + (lead - 50) / 200, 0.25, 0.95);

/* 気風。−1 から +1 の目盛りで、中庸からの振れを表す。
   当主が居なければ、すべて零（中庸）。家は無難に動く。 */
export function 気風(s, fid) {
  const 主 = 家の当主(s, fid);
  if (!主) return { 攻め: 0, 調略: 0, 治め: 0, 浸透: 0.35, 主: null };
  const t = 浸透(主.lead || 55);
  const 振れ = (v) => clamp(((v == null ? 55 : v) - 60) / 35, -1, 1) * t;
  return {
    攻め: 振れ(主.valor),
    調略: 振れ(主.wit),
    治め: 振れ(主.gov),
    浸透: t,
    主,
  };
}

/* 腰の重さ（出陣に踏み切る目）。武勇が高いほど軽い。

   もとは家の名を数にした「気性」で決めていた（進取〇.六〇／堅実〇.三二）。
   同じ家はいつも同じ気性で、代替わりしても変わらなかった。器量で決めれば、
   当主が替われば家の動きも変わる。 */
export function 攻めの腰(s, fid) {
  const k = 気風(s, fid);
  return clamp(0.32 * (1 + k.攻め * 0.8), 0.08, 0.62);
}

/* 攻めに要る兵力の比。武勇が高いほど小さい差でも仕掛ける。

   ただし下限を置く。「無駄な戦はしない」というのはこれで、どれほど猛々しい
   大名でも、五分五分を割る戦には出ない。武田信玄が上洛を急がなかったのは
   臆したからではなく、勝てぬ戦をしなかったからである。 */
export function 要る兵力(s, fid, 基 = 1.35) {
  const k = 気風(s, fid);
  return clamp(基 * (1 - k.攻め * 0.22), 1.02, 基 * 1.35);
}

/* 一度に出せる軍の数。

   これまでは、どの家も「軍が一つでも出ていれば次は出さない」であった。
   十六城を持つ大身も、一城の小家も、同じ一軍しか動かせない。それでは
   大きい家が大きくならない――地方に大勢力が育たぬ元はここにある。

   七城につき一手を目安とし、統率の高い当主はもう一手を捌ける。

   はじめ四城につき一手・上限六手としたが、これは効きすぎた。十年で城を持つ家が
   百三十七から四十四に減り、三十年で八勢力しか残らない。狙いは「三十〜四十年で
   各地方に三家ほど」であって、十年でそこへ着いてはならない。 */
export function 出せる軍の数(s, fid) {
  const 城 = (s.castles || []).filter((c) => c.faction === fid).length;
  if (!城) return 0;
  const k = 気風(s, fid);
  const 基 = 1 + Math.floor(城 / 7);
  return clamp(基 + (k.浸透 >= 0.75 ? 1 : 0), 1, 4);
}

/* 調略に手を伸ばすか。知略が高いほど繁く仕掛ける。 */
export function 調略の腰(s, fid, 基 = 0.3) {
  const k = 気風(s, fid);
  return clamp(基 * (1 + k.調略 * 1.2), 0.05, 0.9);
}

/* 内政と外交に手を伸ばすか。政治が高いほど繁い。 */
export function 治めの腰(s, fid, 基 = 0.35) {
  const k = 気風(s, fid);
  return clamp(基 * (1 + k.治め * 1.0), 0.08, 0.9);
}

/* 弱きに付け入る目。

   強い家だけが伸びるのでは、盤は面白くない。弱い家も、隣に手薄な城があれば
   狙う。相手が半分の兵しか持たぬなら、腰の重い当主でも兵を出す。 */
export function 好機か(己の兵, 敵の兵) {
  return 己の兵 > Math.max(400, 敵の兵) * 2;
}
