import { clamp } from "./util.js";

/* ==========================================================================
   出征の物差し（GDD 6.4 / 7.3 / 9.1）――城を攻めるに要る兵を、どの家も同じ物差しで測る

   遊ぶ側の申し出は「そもそも、旗頭が出す軍が少な過ぎます。あえて1.6倍とか2倍の設定を
   するからだと思います。連戦することも考慮してできるだけ軍を集結させて挑むべきです。
   また、一つの軍だけでなく、攻められそうな城があれば複数の軍を立てることになっても
   攻めるべきで、そのときの考え方としては、最低3倍の兵が集められるのであれば積極的に
   出征すべきです。他方で、野戦によって相手の軍を削り、後続の本隊で一気にけりをつける
   ことも考えられます。武将の優秀さによっては3倍を下回る場合でも軍を出していいと思います。
   これは、旗頭だけでなく、AIとしての判断で共通させていいと思います。」であった。

     城攻めの比 … 城の兵（地の兵と、城にいる将の手勢）の三倍。城攻めの見込み（core/kakomi.js
                  強攻の見込み）で、三倍の寄せ手が一度の強攻で城を落とす見込みは六割である
     将の利     … 率いる将のうち器量（統率五分・武勇三分・知略二分。合戦の崩れ際と同じ量り）の
                  いちばん高い者が七十を超えれば、超えたぶんだけ兵が少なくて済む。九十五で
                  一.二五倍の働き（三倍が二.四倍で足りる）。七十までは三倍のまま
     野の比     … 城の外で当たる敵（来うる後詰と、城の近くに陣を張る軍）には、その一.三倍。
                  野戦は城の壁を挟まないので、城攻めほどの差は要らない。野で削っておけば、
                  城に残る兵の三倍で足りる
     連戦の余り … 集められるなら、要る兵の一.三倍まで寄せる。一つ落とせば、その兵で次の城へ
                  進む（在陣の始末）。ぎりぎりの兵で出ると、落としたあと何もできない
   ========================================================================== */
export const 城攻めの基の比 = 3;
export const 野の比 = 1.3;
export const 連戦の余り = 1.3;

/* 将の器量（統率五分・武勇三分・知略二分）。合戦の崩れ際・立ち直り（battle/engine.js）と同じ量り */
export const 将の器量 = (g) => ((g && g.lead) || 60) * 0.5 + ((g && g.valor) || 60) * 0.3 + ((g && g.wit) || 60) * 0.2;

/* 将の利（一から一.二五）。率いる将のうち器量のいちばん高い者で決まる */
export function 将の利(将ら = []) {
  const 器 = 将ら.length ? Math.max(...将ら.map(将の器量)) : 60;
  return 1 + clamp((器 - 70) / 100, 0, 0.25);
}

/* 城攻めに要る比（三倍から二.四倍）。七十までは三倍、八十で二.七三倍、九十で二.五倍 */
export const 城攻めの比 = (将ら = []) => 城攻めの基の比 / 将の利(将ら);

/* 野で当たるに要る比（一.三倍から一.〇四倍）。将の利は野でも同じく効く */
export const 野で当たる比 = (将ら = []) => 野の比 / 将の利(将ら);
