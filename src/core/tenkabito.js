/* ============================================================ 天下への道筋（GDD 13.2）

   家の大きさによって、目指すものが違う。

     弱い家　… 存続を目指す。膝を屈し、誼を通じ、隙あらば手薄な隣を取る。
     強い家　… 天下を目指す。ただし一足飛びには行かない。段を踏む。

   段はこうである（作者の見立て）。

     一　足場を固める　… まず己の地方を制する。背に敵を置いたまま遠征はできない。
     二　周りを鎮める　… 隣の地方の脅威を、外交か戦で除く。二正面は避ける。
     三　京を目指す　　… 二条御所を取る。天下人への道はここから開ける。
                         関東・奥羽の家は、まず関東を制してから西へ向かう
                         （頼朝も家康も、関東を固めてから天下を論じた）。
     四　五畿を制する　… 京を得たら畿内を固め、官位を得る。
     五　天下へ　　　　… 惣無事令を発し、号令で残る地方を平らげる。

   ここは純関数だけを置く。采配の側（govern/month.js）は、ここで出した「いまの段」
   と「その段での狙い」を的の値打ちに掛けるだけにする。そうしておけば、画面を
   通さずに測れる。 */
import { REGIONS, GOKINAI, KANTO_KEY } from "../data/provinces.js";
import { courtRank, 旗の下の城数, 天下人の直轄, 天下人の版図 } from "./province.js";

export const 京の城 = "nijo";                       // 二条御所

/* 志を抱くほどの家か。これに満たぬ家は、ただ生き延びることを考える。

   関門は天下人の六割五分。信長が上洛したのは尾張と美濃を押さえた時分で、
   天下人の身代にはほど遠かった。志は資格より先に立つ。 */
export const 志の直轄 = 天下人の直轄 * 0.65;         // 全国の約八分
export const 志の版図 = 天下人の版図 * 0.6;          // 全城の約一割八分
export const 足場の握り = 0.6;                      // 己の地方をこれだけ握れば、外へ出る

/* その家の本拠がある地方。無ければ、いちばん城を持つ地方。 */
export function 家の地方(s, fid) {
  const 我 = (s.castles || []).filter((c) => c.faction === fid);
  if (!我.length) return null;
  const 本 = 我.find((c) => c.id === ((s.factions || {})[fid] || {}).本拠) || 我[0];
  const 数 = new Map();
  for (const c of 我) {
    const r = REGIONS.find((x) => x.kuni.includes(c.kuni));
    if (r) 数.set(r.name, (数.get(r.name) || 0) + 1);
  }
  const 本の地方 = REGIONS.find((x) => x.kuni.includes(本.kuni));
  if (本の地方 && (数.get(本の地方.name) || 0) >= 数.size) return 本の地方;
  const 頭 = [...数.entries()].sort((a, b) => b[1] - a[1])[0];
  return 頭 ? REGIONS.find((x) => x.name === 頭[0]) : 本の地方;
}

/* その地方をどれだけ握っているか（旗の下を含む）。 */
export function 地方の握り(s, fid, 地方, 旗の下か) {
  if (!地方) return 0;
  const 城 = (s.castles || []).filter((c) => 地方.kuni.includes(c.kuni));
  if (!城.length) return 1;
  const 我 = 城.filter((c) => c.faction === fid
    || (旗の下か ? 旗の下か(s, fid, c.faction) : false)).length;
  return 我 / 城.length;
}

/* いまの段（GDD 13.2）。

   返すのは段の名と、その段で重く見るべきもの。采配はこれを的の値打ちに掛ける。 */
export const 段 = {
  存続: "存続", 足場: "足場を固める", 周り: "周りを鎮める",
  関東: "関東を制する", 上洛: "京を目指す", 五畿: "五畿を制する", 天下: "天下へ",
};

export function いまの段(s, fid, { 旗の下か } = {}) {
  const 我 = (s.castles || []).filter((c) => c.faction === fid);
  if (!我.length) return { 段: 段.存続, 志なし: true };
  const 全国石高 = s.castles.reduce((a, c) => a + c.koku, 0);
  const 直轄 = 我.reduce((a, c) => a + c.koku, 0);
  const 版図 = 旗の下の城数(s, fid);

  /* 志を抱くほどの身代が無ければ、ただ生き延びる。

     身代か版図か、どちらかが足りればよい（「かつ」ではない）。両方を要ると
     したところ、四十年で志を抱いた家は一家だけであった――北条は直轄一割二分四厘
     まで伸びながら、旗の下が一割五分で十八分に届かず、存続の段に留まっていた。
     国を切り従える家と、旗の下を広げる家と、道は一つではない。 */
  if (直轄 < 全国石高 * 志の直轄 && 版図 < s.castles.length * 志の版図) {
    return { 段: 段.存続, 志なし: true };
  }

  const 位 = courtRank(s, fid);
  if (位 && 位.号令) return { 段: 段.天下, 位 };        // 関白・将軍。あとは平らげるのみ
  if (位) return { 段: 段.五畿, 位, 狙う国: GOKINAI };  // 五畿を制した。版図を積む

  /* 京を持っているか。持っていれば次は五畿である。 */
  const 京 = (s.castles || []).find((c) => c.id === 京の城);
  const 京は我が手 = !!京 && (京.faction === fid || (旗の下か ? 旗の下か(s, fid, 京.faction) : false));
  if (京は我が手) return { 段: 段.五畿, 狙う国: GOKINAI };

  /* 足場。まず己の地方を制する。背に敵を置いたまま遠征はできない。 */
  const 地方 = 家の地方(s, fid);
  const 握 = 地方の握り(s, fid, 地方, 旗の下か);
  /* 六割としたのは測ったからである。七割では、九州を六割一分握った島津も、
     奥羽を六割三分握った南部も足場の段に留まり、十六年動かなかった。
     地方の隅々まで平らげてから出るのでは、いつまでも出られない。 */
  if (握 < 足場の握り) return { 段: 段.足場, 地方, 握, 狙う国: 地方 ? 地方.kuni : null };

  /* 関東・奥羽の家は、まず関東を固めてから西へ向かう。
     頼朝も家康も、関東を押さえてから天下を論じた。 */
  const 東の家 = 地方 && (地方.name === "関東" || 地方.name === "奥羽");
  if (東の家) {
    const 関東 = REGIONS.find((r) => r.name === "関東");
    const 関東の握 = 地方の握り(s, fid, 関東, 旗の下か);
    const 要 = KANTO_KEY.every((k) => (s.castles || []).filter((c) => c.kuni === k)
      .every((c) => c.faction === fid || (旗の下か ? 旗の下か(s, fid, c.faction) : false)));
    if (!要 || 関東の握 < 足場の握り) {
      return { 段: 段.関東, 地方: 関東, 握: 関東の握, 狙う国: 関東 ? 関東.kuni : null };
    }
  }

  /* 周りを鎮める。隣の地方に、己より大きい家がいるあいだは西へ向かわない。
     二正面は避けたい。 */
  const 石 = {};
  for (const c of s.castles) 石[c.faction] = (石[c.faction] || 0) + c.koku;
  const 隣の脅威 = Object.keys(石).filter((f) => {
    if (f === fid) return false;
    if (旗の下か && 旗の下か(s, fid, f)) return false;
    if (!s.castles.some((c) => c.faction === f)) return false;
    if (石[f] < 直轄 * 0.8) return false;                 // 己より小さい家は脅威ではない
    /* 隣り合っているか。地方が同じか、地方が隣り合うかで見る。 */
    const 彼の地方 = 家の地方(s, f);
    if (!彼の地方 || !地方) return false;
    return 彼の地方.name === 地方.name || 地方が隣り合うか(地方.name, 彼の地方.name);
  });
  if (隣の脅威.length) {
    return { 段: 段.周り, 地方, 脅威: 隣の脅威, 狙う国: 地方 ? 地方.kuni : null };
  }

  /* 京を目指す。 */
  return { 段: 段.上洛, 狙う城: 京の城, 狙う国: GOKINAI };
}

/* 地方どうしの隣り合わせ。盤の形は動かないので、表にして持つ。 */
const 地方の並び = {
  奥羽: ["関東"],
  関東: ["奥羽", "中部"],
  中部: ["関東", "畿内"],
  畿内: ["中部", "中国", "四国"],
  中国: ["畿内", "四国", "九州"],
  四国: ["畿内", "中国", "九州"],
  九州: ["中国", "四国"],
};
export const 地方が隣り合うか = (a, b) => !!(地方の並び[a] || []).includes(b);

/* その段における、的の値打ちの上乗せ（GDD 13.2）。

   采配は的を選ぶとき、この数を足す。段ごとに何を重く見るかが変わる。 */
export function 段の上乗せ(状, 的, { 旗の下か, 京までの歩 } = {}) {
  if (!状 || !的) return 0;
  let w = 0;
  const 国 = 状.狙う国;
  if (状.段 === 段.存続) return 0;                      // 弱い家は段を持たない
  if (状.狙う城 && 的.id === 状.狙う城) w += 140;       // 京そのもの
  if (国 && 国.includes(的.kuni)) {
    w += 状.段 === 段.足場 ? 70
      : 状.段 === 段.関東 ? 80
        : 状.段 === 段.上洛 ? 90
          : 状.段 === 段.五畿 ? 90
            : 状.段 === 段.周り ? 50 : 30;
  }
  /* 上洛の段では、京へ近い城ほど重く見る（GDD 13.2）。

     道々を切り従えながら進むのが上洛である。京だけを重く見ても、そこへ至る道が
     他家の領で塞がれていれば、二条御所は的の一覧にすら上らない――他家の領を
     素通りできないからである。実測では、斎藤が上洛の段に入って二十年、京を
     目指したまま一歩も進まなかった。信長も、まず近江を平らげてから京へ入った。

     京から一歩の城に六十、二歩で四十五、三歩で三十……と、近いほど重い。 */
  if (状.段 === 段.上洛 && typeof 京までの歩 === "function") {
    const 歩 = 京までの歩(的.id);
    if (歩 != null && 歩 <= 8) w += Math.round(75 * Math.pow(0.75, 歩 - 1));
  }
  if (状.段 === 段.上洛 && GOKINAI.includes(的.kuni)) w += 40;
  return w;
}
