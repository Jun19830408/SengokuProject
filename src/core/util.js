export function makeRng(seed) {
  let x = seed || 1;
  return () => { x ^= x << 13; x ^= x >>> 17; x ^= x << 5; x >>>= 0; return x / 4294967296; };
}

// 勢力色を暗く／明るくする。敵味方は色、直属・地域は明暗と縁で区別する（GDD 6.3）
export function shade(hex, k) {
  const n = parseInt(hex.slice(1), 16);
  const f = (v) => Math.max(0, Math.min(255, Math.round(k < 0 ? v * (1 + k) : v + (255 - v) * k)));
  return `rgb(${f((n >> 16) & 255)},${f((n >> 8) & 255)},${f(n & 255)})`;
}


/* ------------------------------------------------------- 籤（くじ）

   盤の出来事を決めるのに Math.random を回すと、同じ種から始めたはずの
   ほかの出来事――合戦の行方まで――が一斉にずれる。あとから仕組みを足すたび、
   古い試験が落ちるのはこのためである。

   卓の印と、家と、年から籤を起こせば、遊びごとには違い、同じ盤では必ず同じになる。
   月送りの采配（姫・外交・調略）はみなこれを使う。 */
export function 籤(...種) {
  let h = 2166136261;
  for (const t of 種.join("|")) h = Math.imul(h ^ t.charCodeAt(0), 16777619);
  return () => {
    h |= 0; h = (h + 0x6D2B79F5) | 0;
    let t = Math.imul(h ^ (h >>> 15), 1 | h);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
