/* ==========================================================================
   馬と鉄砲 ─ 城に蓄える二つの兵器（GDD 6.3）

   槍と弓は、村々の百姓が自前で携えて出る。改めて買い揃えるものではない。
   馬と鉄砲は違う。馬は牧で育てねばならず、鉄砲は買うか作るかせねばならない。
   だから、この二つだけを城の蓄えとして数える。

   天文十五年（1546）という年立てが効く。鉄砲が種子島へ伝わったのは天文十二年
   （1543）であり、まだ三年しか経っていない。堺・根来・国友で打ち始めたころで、
   天下の大半には一挺も無い。長篠の三千挺は三十年先の話である。
   ========================================================================== */

/* ------------------------------------------------------------------ 馬

   牧のある国に馬は多い。奥州の南部馬、甲斐・信濃の木曽馬、越後の馬。
   関東の牧も古くから知られる。西国は馬が乏しく、船と足で戦う。

   数は「一万石あたり何頭か」で置く。全国の地域家臣団は二十八万人ほどで、
   その二割を騎馬に仕立てるなら五万六千頭が要る。国ごとの差はそこへ寄せる。 */
export const 馬の産地 = {
  陸奥: 2.4, 出羽: 2.0,                       // 南部馬・奥州馬の産地
  甲斐: 2.2, 信濃: 2.0,                       // 木曽馬。武田の騎馬はここに拠る
  越後: 1.6, 上野: 1.5, 下野: 1.4, 常陸: 1.3, // 関東の牧
  相模: 1.2, 武蔵: 1.2, 安房: 1.1, 下総: 1.1,
  駿河: 1.1, 遠江: 1.1, 三河: 1.0, 尾張: 1.0,
  近江: 1.0, 美濃: 1.1, 飛騨: 1.2,
  // 西国は概ね乏しい（既定は 0.7）
  薩摩: 1.1, 大隅: 1.1, 日向: 1.2,            // 南九州にも牧があった
};
export const 馬の既定 = 0.7;

/* ------------------------------------------------------------------ 鉄砲

   天文十五年に鉄砲を持つ者は、ごく限られる。
     ・島津  … 種子島は島津の支配下。伝来の地であり、最も早く手にした
     ・雑賀  … 根来・雑賀の鉄砲衆。畿内で最も早く打ち始めた
     ・三好  … 堺を押さえる。南蛮の品も鉄砲もここに集まる
     ・六角  … 近江国友。将軍家の命で鉄砲を打ち始めた
     ・大友  … 豊後府内。南蛮船の来る湊を持つ
     ・大内  … 山口。明・南蛮との交わりが深い
     ・本願寺… 大坂。門徒の財と堺の商いで早くから揃えた
   ほかは零である。欲しければ商人から買うほかない。 */
export const 鉄砲の家 = {
  shimazu: 90,      // 種子島。伝来の地
  saika: 80,        // 雑賀衆・根来衆
  miyoshi: 60,      // 堺
  honganji: 50,     // 大坂
  rokkaku: 40,      // 国友
  otomo: 40,        // 豊後府内の南蛮船
  ouchi: 30,        // 山口
  ashikaga: 12,     // 将軍家。数は少ないが早くから知る
  azai: 8,          // 国友の隣
  negoro: 60,       // 根来（別の家として在れば）
};

/* 一万石あたりの馬の頭数。国の差はここに乗る。 */
export const 馬の基準 = 42;

/* その城が抱える馬。牧の在る国ほど多い。 */
export function 城の馬(c) {
  const k = 馬の産地[c.kuni] == null ? 馬の既定 : 馬の産地[c.kuni];
  return Math.round((c.koku / 10000) * 馬の基準 * k);
}

/* その城が抱える鉄砲。伝来まもないので、持つ家は限られる。
   同じ家でも、湊や城下の大きい城に集まる。 */
export function 城の鉄砲(c, 家の総石高) {
  const n = 鉄砲の家[c.faction];
  if (!n) return 0;
  const 割 = 家の総石高 > 0 ? c.koku / 家の総石高 : 1;
  return Math.max(1, Math.round(n * 割));
}

/* --------------------------------------------------- 兵科の割り当て（GDD 8.1）

   隊を仕立てるときの兵科の割り。一割きざみで選ぶ。
   槍と弓はいくらでも立てられる。馬と鉄砲は城の蓄えが限りとなる。 */
export const 既定の兵科 = { yari: 50, yumi: 20, teppo: 0, kiba: 30 };

/* 直属の供回りの兵科（GDD 6.3）。

   直属は武将が自前で養う手勢である。地域家臣団と違って、選んで仕立てるものではない。
   供回りには必ず馬が付く。騎馬の一騎もいない武将というものはいない。

   地域家臣団の割りをどう選ぼうと、直属のここは変わらない。
   馬は武将の身代から出るものとし、城の蓄えからは引かない。 */
export const 直属の兵科 = { yari: 55, yumi: 17, teppo: 3, kiba: 25 };
export const 直属の騎馬 = 直属の兵科.kiba / 100;
