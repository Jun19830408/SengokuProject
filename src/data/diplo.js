/* 外交（GDD 12.1）

   従属・臣従は「下の者が上の者に膝を屈する」ことである。上下があるのだから、
   どちらが上でどちらが下かを、盤に書き留めておかねばならない。

   これまでは書き留めず、そのときどきの石高を比べて上下を決めていた。
   一度は膝を屈した相手でも、こちらの石高がその家を追い越した途端、
   その家がこちらの臣下に化ける。逆もまた然りである。
   関係の向きが、戦の結果でひとりでに裏返っていた。

   また、命の名も向きを示していなかった。「従属」は相手を従える命、
   「臣従」は自らが膝を屈する命であって、向きが逆である。
   同じ並びに置かれていたので、どちらへ働く命なのか読み取れない。

   ここでは、
     ・命の名に向きを入れる（従属させる／従属する、臣従させる／臣従する）
     ・結んだときに、どちらが上かを盟約そのもの（r.master）へ書き留める
   の二つを定める。 */
export const SUBJECT = ["従属", "臣従"];             // 上下のある間柄

/* 上下のある間柄で、上に立っているのはどの家か。
   古い記録には書き留めがないので、そのときは石高で見当をつける。 */
export function masterOf(r, aId, bId, aKoku, bKoku) {
  if (!r || !SUBJECT.includes(r.state)) return null;
  if (r.master === aId || r.master === bId) return r.master;
  return aKoku >= bKoku ? aId : bId;                 // 古い記録の見当
}

