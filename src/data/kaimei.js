/* その年までに来ている、最も新しい名。無ければ null（元の名のまま）。 */
export function 改まった名(id, 年) {
  let 名 = null, 年印 = -1, 訳 = null;
  for (const x of 城の改名) {
    if (x.id !== id || x.y > 年 || x.y < 年印) continue;
    名 = x.名; 年印 = x.y; 訳 = x.訳;
  }
  return 名 ? { 名, y: 年印, 訳 } : null;
}
