export function 改まった名乗り(id, 年) {
  let 名 = null, 年印 = -1, 訳 = null;
  for (const x of 武将の改名) {
    if (x.id !== id || x.y > 年 || x.y < 年印) continue;
    名 = x.名; 年印 = x.y; 訳 = x.訳;
  }
  return 名 ? { 名, y: 年印, 訳 } : null;
}
