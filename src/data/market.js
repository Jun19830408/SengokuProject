/* ==========================================================================
   商人 ─ 兵糧・馬・鉄砲の売り買い（GDD 5.x）

   城下には市が立ち、廻船の商人が出入りする。金があれば買えるし、
   蓄えを吐き出して金に換えることもできる。

   値は月で動く。作物は取り入れのあとに安く、端境に高い。
   馬は秋に肥えて出回り、冬から春に痩せて値が張る。
   鉄砲は伝来まもなく、法外に高い。年を追うごとに打ち手が増えて下がっていく。
   ========================================================================== */

/* 買値の基準（貫）。売るときは口銭を引かれる。 */
export const 基準値 = {
  food: { 名: "兵糧", 単位: "石", 買: 0.024, 刻み: [1000, 5000, 20000] },
  horse: { 名: "馬", 単位: "頭", 買: 2.6, 刻み: [10, 50, 200] },
  gun: { 名: "鉄砲", 単位: "挺", 買: 24, 刻み: [5, 20, 50] },
};

// 商人の口銭。売値は買値のこれだけになる。
export const 口銭 = 0.62;

/* 月ごとの値動き。一を基準とする。

   兵糧 … 九月から十一月が取り入れ。出回って安い。
          春から夏は端境で、蔵が空き、値が張る。
   馬   … 秋に牧から出る。冬から春は飼葉が要り、痩せてもいるので高い。
   鉄砲 … 作るのに季節はない。ただし戦の多い夏に引き合いが強まる。 */
export const 月の値動き = {
  food: [1.28, 1.30, 1.26, 1.18, 1.10, 1.04, 1.00, 1.02, 0.82, 0.72, 0.78, 1.06],
  horse: [1.22, 1.24, 1.18, 1.10, 1.02, 0.98, 0.96, 0.94, 0.86, 0.84, 0.92, 1.12],
  gun: [1.00, 1.00, 1.02, 1.04, 1.08, 1.12, 1.14, 1.12, 1.06, 1.00, 0.98, 0.98],
};

/* 鉄砲は年を追って安くなる。
   天文十二年に種子島へ伝わり、堺・根来・国友で打ち始めた。
   打ち手が増えるにつれ値は下がるが、底はある。 */
export function 鉄砲の年値(year) {
  const 経た年 = Math.max(0, year - 1546);
  return Math.max(0.34, Math.pow(0.94, 経た年));
}

/* その城・その月の値。湊と市の栄えた城ほど安く買え、高く売れる。 */
export function 相場(s, c, kind) {
  const b = 基準値[kind];
  if (!b) return { buy: 0, sell: 0 };
  const 月 = 月の値動き[kind][Math.max(0, Math.min(11, (s.month || 1) - 1))];
  const 年 = kind === "gun" ? 鉄砲の年値(s.year || 1546) : 1;
  // 商いの栄えた城は、諸国の品が集まるので買値が安く、売値も立つ
  const 市 = 1 - Math.min(0.18, ((c && c.comm) || 40) / 100 * 0.22);
  const buy = b.買 * 月 * 年 * 市;
  return { buy, sell: buy * 口銭, 月, 年, 市 };
}

// 買うのに要る金（貫）。端数は切り上げ、商人は損をしない。
export const 買値 = (s, c, kind, n) => Math.ceil(相場(s, c, kind).buy * Math.max(0, n));
// 売って得る金（貫）。端数は切り捨て。
export const 売値 = (s, c, kind, n) => Math.floor(相場(s, c, kind).sell * Math.max(0, n));
