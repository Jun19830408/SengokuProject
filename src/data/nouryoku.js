/* ==========================================================================
   武将の能力の見直し（GDD 6.1）

   値の意味を定め直す。
     統率 … 軍をまとめ、思うように動かす力
     武勇 … 合戦の中で、どれほどの強さで相手に損害を与えられるか。
             腕っぷしの強さだけではない。合戦に強かった将は、軍略の人で
             あっても武勇を低くしない（遊ぶ側の申し出による）
     知略 … 謀り、見抜く力
     政務 … 国を治め、人と物を回す力

   武将帳の値は、武勇を「個の武芸」として付けていた節があった。剣術家が
   武勇の最上位に並び、竹中半兵衛（武勇三十二）や太原雪斎（三十四）のように
   合戦で名を上げた軍略家が下位に沈んでいた。また、柴田勝家（知略三十八・
   政務三十五）のように、方面軍と一国を任された将の知略・政務が低すぎた。

   直し方は二つ。
   一　決まり：統率が七十以上の将は、武勇を「統率−三十」より下げない。
       軍を巧みに動かす将の軍は、合戦でもそれなりの損害を与えるからである。
       はじめ「統率−十五」としたが、四十五人を一律に押し上げて上げすぎた
       （今川義元が五十三から八十一）。極端に離れた者だけを引き上げる。
   二　見直し：名のある将は、実績に照らして一人ずつ値を定める。ただし「下げすぎ」を
       戻す程度にとどめ、中ほどを大きく超えるほどには上げない。下の表の値が
       最後に当たる（決まりより強い）。訳には拠った事績を記す。値そのものは
       事績から見積もったものであって、史料に数があるわけではない。

   武将帳（generals.js・newcomers.js）の値は、この見直しを当てた後のもので
   ある。古い記録には core/state.js の 能力を見直す が一度だけ当てる。
   ========================================================================== */

