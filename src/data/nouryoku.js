/* 一人の値を見直す。表の値を当てる。何度当てても同じになる。 */
export function 能力を見直す(g) {
  if (!g) return g;
  const 改 = 能力の改め[g.id];
  if (改) for (const k of 欄) if (改[k] != null) g[k] = 改[k];
  return g;
}
