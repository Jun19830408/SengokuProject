const 欄 = ["lead", "valor", "wit", "gov"];

/* 一人の値を見直す。決まりを当ててから、表の値を当てる。何度当てても同じになる。 */
export function 能力を見直す(g) {
  if (!g) return g;
  if ((g.lead || 0) >= 武勇の下限_統率の境 && g.valor != null) {
    g.valor = Math.max(g.valor, g.lead - 武勇の下限_統率の差);
  }
  const 改 = 能力の改め[g.id];
  if (改) for (const k of 欄) if (改[k] != null) g[k] = 改[k];
  return g;
}
