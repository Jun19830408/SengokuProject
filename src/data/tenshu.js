export const 大きな家の石高 = 500000;
export const 天守の世 = 1576;

/* 表の欄のうち、その年に立っているもの。
   undefined … 表に無い城（二へ回す）／ null … その年は天守が無い（二へも回さない） */
function 表で引く(id, 年, 持ち主) {
  const ら = 天守の表.filter((x) => x.id === id);
  if (!ら.length) return undefined;
  const 今 = ら.find((x) => !x.無し && x.自 <= 年 && (x.至 == null || 年 < x.至));
  if (今) return 今;
  const 史の天守 = ら.some((x) => !x.無し);
  if (史の天守) return null;                               // 史実の天守が建つ前か、失われた後
  // 「無し」だけの城は、その家が持つあいだだけ止める
  return ら.some((x) => x.無し && x.家 === 持ち主) ? null : undefined;
}

/* その城に、いま天守が立っているか。立っていれば { 重, 史実, 名 } を返す */
export function 天守を見る(s, castle) {
  if (!castle) return null;
  const 年 = (s && s.year) || 1546;
  const 史 = 表で引く(castle.id, 年, castle.faction);
  if (史) return { 重: 史.重 || 3, 史実: true, 確: 史.確 || "", 典: 史.典 || "" };
  if (史 === null) return null;
  // 表に無い城。盤で大きな家の本拠になったときだけ
  if (年 < 天守の世 || !s || !castle.faction) return null;
  const 家 = (s.factions || {})[castle.faction];
  if (!家 || 家.本拠 !== castle.id) return null;
  const 石 = 家の石高(s, castle.faction);
  if (石 < 大きな家の石高) return null;
  return { 重: 石 >= 1500000 ? 5 : 石 >= 1000000 ? 4 : 3, 史実: false };
}
