/* ==========================================================================
   大軍の野（GDD 8.10）

   関ヶ原は史実の布陣図から一画素ずつ写した一枚である。ここに集めた六枚は、
   史実で大軍どうしが噛み合った戦場の地形を写したものである。布陣は写さない
   ――誰がどこに立つかは盤の上の成り行きで決まる。土地の名も画面には出さず、
   「二つの川が落ち合う平野」といった土地柄だけを見せる。

   一歩は 0.80m。盤はいずれも八千×五千六百歩（六.四km×四.五km）で、
   三十隊ずつ、合わせて六十隊が長い戦列で向き合える広さを確かめてある。

   ------------------------------------------------------------------- 攻守

   守勢は「拠る所」を与えられる――高み、川の向こう、城下。攻勢は開けた所から
   押す。関ヶ原で西軍が笹尾山と天満山の高みに拠り、東軍が桃配山から東の野に
   展いたのと同じ置き方である。ただし拠る所には必ず代償を付けた。背が川で
   塞がっていたり、退き口が橋ひとつだったりする。守れば強いが、崩れれば壊滅する。

   ------------------------------------------------------------- 地形の組み方

   山と丘は円を連ねて尾根にする。円を一つだけ置くと、麓が崖のように切り立ち、
   隊が山肌に貼りつく（関ヶ原でも西軍が一隊残らず平地に立つ、という逆さまな
   ことが起きた）。峰の円のまわりに低い裾の円を重ね、坂を段々に落とす。

   木立は野一面に撒かない。川べり、丘の裾、山の膝――実際に木が茂る所に寄せる。
   布陣の場からは外す。伏兵を生かす野（丘と森の川原）だけは、布陣の場の外側に
   わざと深い森を置く。
   ========================================================================== */

const 賽を巻く = (種) => () => {
  種 |= 0; 種 = (種 + 0x6D2B79F5) | 0;
  let t = Math.imul(種 ^ (種 >>> 15), 1 | 種);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};

/* 尾根を引く。節を結んで円を連ね、峰から裾へ高さを落とす。 */
function 尾根(節, { 高, r, 裾 = 0.55, 名 = "尾根", 札 = null, 間 = 0.62 } = {}) {
  const 出 = [];
  for (let i = 0; i < 節.length - 1; i++) {
    const [x1, y1, h1 = 高, r1 = r] = 節[i], [x2, y2, h2 = 高, r2 = r] = 節[i + 1];
    const 距 = Math.hypot(x2 - x1, y2 - y1);
    const 数 = Math.max(1, Math.round(距 / (Math.min(r1, r2) * 間)));
    for (let k = 0; k < 数; k++) {
      const t = k / 数;
      出.push({ 名, 高: Math.round(h1 + (h2 - h1) * t), x: Math.round(x1 + (x2 - x1) * t),
        y: Math.round(y1 + (y2 - y1) * t), r: Math.round(r1 + (r2 - r1) * t) });
    }
  }
  const [lx, ly, lh = 高, lr = r] = 節[節.length - 1];
  出.push({ 名, 高: lh, x: lx, y: ly, r: lr });
  if (札 != null && 出[札]) 出[札].札 = true;
  /* 裾。峰の円の外側に、低くて広い円を重ねて坂を段々にする。 */
  const 裾ら = 出.filter((_, i) => i % 2 === 0).map((o) => ({ 名, 高: Math.round(o.高 * 裾),
    x: o.x, y: o.y, r: Math.round(o.r * 1.28) }));
  return { 峰: 出, 裾: 裾ら };
}

/* 木立を散らす。寄せる帯（川べり・丘の裾）を渡し、布陣の場からは外す。 */
function 木を散らす(種, n, 幅, 高, { 寄 = null, 避 = [], r = [90, 150], 縁 = 240, 間 = 110 } = {}) {
  const 賽 = 賽を巻く(種);
  const 出 = [];
  for (let i = 0; i < n * 90 && 出.length < n; i++) {
    const x = 縁 + 賽() * (幅 - 縁 * 2), y = 縁 + 賽() * (高 - 縁 * 2);
    if (寄 && !寄(x, y, 賽)) continue;
    const rr = Math.round(r[0] + 賽() * (r[1] - r[0]));
    let 良 = true;
    for (const a of 避) if (Math.hypot(a.x - x, a.y - y) < (a.r || 0) + rr + (a.間 || 0)) { 良 = false; break; }
    if (!良) continue;
    for (const a of 出) if (Math.hypot(a.x - x, a.y - y) < a.r + rr + 間) { 良 = false; break; }
    if (良) 出.push({ x: Math.round(x), y: Math.round(y), r: rr });
  }
  return 出;
}

/* 折れ線の節を細かく割り、少し蛇行させる（真っ直ぐな川は嘘くさい）。 */
const 筋 = (pts, 割 = 4, 揺 = 0, 種 = 7) => {
  const 賽 = 賽を巻く(種), 出 = [];
  for (let i = 0; i < pts.length - 1; i++) {
    const [x1, y1] = pts[i], [x2, y2] = pts[i + 1];
    const dx = x2 - x1, dy = y2 - y1, 長 = Math.hypot(dx, dy) || 1;
    const nx = -dy / 長, ny = dx / 長;
    for (let k = 0; k < 割; k++) {
      const t = k / 割, w = 揺 ? (賽() - 0.5) * 2 * 揺 * Math.sin(Math.PI * t) : 0;
      出.push({ x: Math.round(x1 + dx * t + nx * w), y: Math.round(y1 + dy * t + ny * w) });
    }
  }
  const [lx, ly] = pts[pts.length - 1];
  出.push({ x: lx, y: ly });
  return 出;
};
const 節々 = (pts) => pts.map(([x, y]) => ({ x, y }));
/* 点から線（川筋）までの隔たり。木立を川べりへ寄せるのに使う。 */
const 筋までの距 = (筋ら, x, y) => {
  let 最 = Infinity;
  for (const p of 筋ら) { const d = Math.hypot(p.x - x, p.y - y); if (d < 最) 最 = d; }
  return 最;
};
/* 布陣の枠（陣）を、木立を避けるための円に直す。 */
/* 布陣の場（備の群れ）を、木立を避けるための円に直す。 */
const 陣の円 = (陣) => {
  const 備ら = 陣.備 || [];
  if (!備ら.length) return { x: 0, y: 0, r: 0, 間: 0 };
  const x = 備ら.reduce((a, b) => a + b.x, 0) / 備ら.length;
  const y = 備ら.reduce((a, b) => a + b.y, 0) / 備ら.length;
  let r = 0;
  for (const b of 備ら) r = Math.max(r, Math.hypot(b.x - x, b.y - y) + b.幅 / 2);
  return { x, y, r: r + 120, 間: 200 };
};


/* ==========================================================================
   陣立て（GDD 12.6）

   横一列にずらりと並べるのは、盤の上ではただの棒である。史実の大軍は備（そなえ）
   に分かれ、先手・二陣・左右の翼・本陣と役割を持って布かれた。野ごとに、その戦で
   実際に採られた形に倣って備を置く。

   備はこう書く：{ 名, x, y, 向, 幅, 数 }。中心 (x,y) から 向 に直交する向きへ
   幅いっぱいに 数 隊を並べる。前から順に埋め、余った隊は最後の備の後ろへ付ける。
   ========================================================================== */

/* 一つの備。 */
/* 一つの備。役は、盤の上での振る舞いを決める（GDD 12.6）。
     高み … 山や丘を押さえる。持ち場を離れない。取られれば要塞になる
     押さえ … 渡しや谷の口を塞ぐ。持ち場を離れない
     本隊 … 正面から当たる
     別働 … 大きく回って敵の後ろを狙う
     本陣 … 総大将。後ろに控える */
const 備 = (名, x, y, 向, 幅, 数, 役 = "本隊") => ({ 名, x, y, 向, 幅, 数, 役 });

/* 備の数の割り振り。総勢三十二隊を、割合で分ける。 */
const 割る = (総, 割ら) => {
  const 和 = 割ら.reduce((a, b) => a + b, 0);
  const 出 = 割ら.map((r) => Math.max(1, Math.round((総 * r) / 和)));
  let 差 = 総 - 出.reduce((a, b) => a + b, 0);
  for (let i = 0; 差 !== 0 && i < 出.length * 4; i++) {
    const k = i % 出.length;
    if (差 > 0) { 出[k]++; 差--; } else if (出[k] > 1) { 出[k]--; 差++; }
  }
  return 出;
};
/* 向きに直交する方へ d、向きの逆（後ろ）へ e ずらした点。 */
const 位 = (x, y, 向, d, e) => ({
  x: Math.round(x + d * Math.sin(向) - e * Math.cos(向)),
  y: Math.round(y - d * Math.cos(向) - e * Math.sin(向)),
});

/* 鶴翼。中軍を前に出し、両翼を後ろへ引いて包む。 */
function 鶴翼(x, y, 向, 幅, 深, 総 = 32) {
  const [中, 左, 右, 二, 本] = 割る(総, [0.26, 0.2, 0.2, 0.2, 0.14]);
  const p左 = 位(x, y, 向, -幅 * 0.36, 深 * 0.5), p右 = 位(x, y, 向, 幅 * 0.36, 深 * 0.5);
  const p二 = 位(x, y, 向, 0, 深 * 0.62), p本 = 位(x, y, 向, 0, 深 * 1.15);
  return [
    備("中軍", x, y, 向, 幅 * 0.36, 中),
    備("左翼", p左.x, p左.y, 向, 幅 * 0.3, 左),
    備("右翼", p右.x, p右.y, 向, 幅 * 0.3, 右),
    備("二陣", p二.x, p二.y, 向, 幅 * 0.3, 二),
    備("本陣", p本.x, p本.y, 向, 幅 * 0.16, 本),
  ];
}

/* 魚鱗。先鋒を細く、後ろへ行くほど広げる楔。 */
function 魚鱗(x, y, 向, 幅, 深, 総 = 32) {
  const 割ら = [0.1, 0.16, 0.22, 0.26, 0.26];
  const 数ら = 割る(総, 割ら);
  const 名ら = ["先鋒", "二陣", "三陣", "四陣", "本陣"];
  return 数ら.map((n, i) => {
    const d = (深 / (数ら.length - 1)) * i;
    const w = 幅 * (0.2 + 0.8 * (i / (数ら.length - 1)));
    const p = 位(x, y, 向, 0, d);
    return 備(名ら[i], p.x, p.y, 向, i === 数ら.length - 1 ? 幅 * 0.22 : w, n);
  });
}

/* 段構え。横に長い列を、間を空けて重ねる（設楽原の三段）。 */
function 段構え(x, y, 向, 幅, 深, 総 = 32, 段 = 3) {
  const 割ら = 段 === 3 ? [0.32, 0.26, 0.24, 0.18] : [0.28, 0.24, 0.2, 0.16, 0.12];
  const 数ら = 割る(総, 割ら);
  const 名ら = ["先手", "二列", "三列", "四列", "本陣"];
  return 数ら.map((n, i) => {
    const 末 = i === 数ら.length - 1;
    const d = 末 ? 深 * 1.25 : (深 / 段) * i;
    const p = 位(x, y, 向, 0, d);
    return 備(末 ? "本陣" : 名ら[i], p.x, p.y, 向, 末 ? 幅 * 0.16 : 幅 * (1 - i * 0.06), n);
  });
}

/* 縦列。街道や谷を進む隊を縦に連ねる（車懸り・峠越え）。 */
function 縦列(x, y, 向, 幅, 深, 総 = 32, 筋 = 4) {
  const 本 = Math.max(2, Math.round(総 * 0.12));
  const 残 = 総 - 本;
  const 段 = Math.max(2, Math.round(残 / 筋 / 2));      // 一筋あたりの段数（一段に二隊）
  const 出 = [];
  for (let k = 0; k < 筋; k++) {
    const u = 筋 > 1 ? (k - (筋 - 1) / 2) * (幅 / (筋 - 1)) : 0;
    for (let i = 0; i < 段; i++) {
      const p = 位(x, y, 向, u, (深 / 段) * i);
      出.push(備(`${k + 1}の手`, p.x, p.y, 向, 200, 2));
    }
  }
  const p本 = 位(x, y, 向, 0, 深 * 1.2);
  出.push(備("本陣", p本.x, p本.y, 向, 幅 * 0.16, 本));
  return 出;
}

/* 横列。まっすぐな列を前後に重ねる。 */
function 横列(x, y, 向, 幅, 深, 総 = 32, 段 = 2) {
  const 割ら = 段 === 2 ? [0.42, 0.34, 0.24] : [0.3, 0.26, 0.24, 0.2];
  const 数ら = 割る(総, 割ら);
  const 名ら = ["先手", "二陣", "三陣", "本陣"];
  return 数ら.map((n, i) => {
    const 末 = i === 数ら.length - 1;
    const d = 末 ? 深 * 1.3 : (深 / 段) * i;
    const p = 位(x, y, 向, 0, d);
    return 備(末 ? "本陣" : 名ら[i], p.x, p.y, 向, 末 ? 幅 * 0.16 : 幅 * (1 - i * 0.07), n);
  });
}

/* 陣立てに沿って n 隊ぶんの立ち位置を並べる。

   備の幅に収まらない数を横一列に押し込むと、隊が重なって団子になる。
   隊の正面はおよそ百十歩、間合いを含めて二百二十歩は要る――収まらなければ
   段に折る。後ろの段は二百歩下がる。前の備から順に埋め、余った隊は最後の備の
   後ろへ付ける。 */
export const 隊の間合い = 230;

function 備を敷く(b, 数) {
  const co = Math.cos(b.向), si = Math.sin(b.向);
  const 一段 = Math.max(1, Math.min(数, Math.floor(b.幅 / 隊の間合い) + 1));
  const 段数 = Math.ceil(数 / 一段);
  const 出 = [];
  for (let r = 0; r < 段数; r++) {
    const n = Math.min(一段, 数 - r * 一段);
    for (let i = 0; i < n; i++) {
      const u = n > 1 ? (i - (n - 1) / 2) * (b.幅 / (n - 1)) : 0;
      const e = r * 200;
      出.push({ x: Math.round(b.x + u * si - e * co), y: Math.round(b.y - u * co - e * si),
        向: b.向, 名: b.名, 役: b.役 || "本隊" });
    }
  }
  return 出;
}

/* 備どうしが重なることもある（山裾の一手と本隊など）。
   立ち位置を出したあと、近すぎる組を押し分ける。数回まわせば落ち着く。 */
function 押し分ける(場, 間 = 隊の間合い) {
  for (let 度 = 0; 度 < 6; 度++) {
    let 動 = 0;
    for (let i = 0; i < 場.length; i++) {
      for (let j = i + 1; j < 場.length; j++) {
        const dx = 場[j].x - 場[i].x, dy = 場[j].y - 場[i].y;
        const d = Math.hypot(dx, dy);
        if (d >= 間 || d === 0) continue;
        const 押 = (間 - d) / 2;
        const ux = dx / d, uy = dy / d;
        場[i].x -= ux * 押; 場[i].y -= uy * 押;
        場[j].x += ux * 押; 場[j].y += uy * 押;
        動++;
      }
    }
    if (!動) break;
  }
  for (const p of 場) { p.x = Math.round(p.x); p.y = Math.round(p.y); }
  return 場;
}

export function 陣立てを敷く(陣立て, n) {
  /* 本陣の枠は先に取っておく（GDD 12.6）。

     前の備から順に埋めるだけだと、隊が少ない軍では最後の本陣まで届かず、
     総大将の座る枠が無くなる――実測では二十隊の軍で本陣が一つも立たず、
     当主が先手に出ていた。旗本は、小勢でも必ず立てる。 */
  const 本陣ら = 陣立て.filter((b) => b.役 === "本陣");
  const 前ら = 陣立て.filter((b) => b.役 !== "本陣");
  const 本陣の数 = 本陣ら.length ? Math.max(1, Math.min(n <= 8 ? 1 : 2, n)) : 0;
  const 前の数 = Math.max(0, n - 本陣の数);
  const 出 = [];
  for (const b of 前ら) {
    if (出.length >= 前の数) break;
    出.push(...備を敷く(b, Math.min(b.数, 前の数 - 出.length)));
  }
  for (const b of 本陣ら) {
    if (出.length >= n) break;
    出.push(...備を敷く(b, Math.min(b.数, n - 出.length)));
  }
  let 段 = 1;
  while (出.length < n && 前ら.length) {
    const b = 前ら[前ら.length - 1];
    const co = Math.cos(b.向), si = Math.sin(b.向);
    const 後 = 備を敷く({ ...b, 名: "後備", x: b.x - co * 240 * 段, y: b.y - si * 240 * 段 },
      Math.min(6, n - 出.length));
    出.push(...後);
    段++;
    if (段 > 8) break;
  }
  return 押し分ける(出.slice(0, n));
}

