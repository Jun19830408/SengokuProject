/* ==========================================================================
   大軍の野（GDD 8.10）

   関ヶ原は史実の布陣図から一画素ずつ写した一枚である。ここに集めた六枚は、
   史実で大軍どうしが噛み合った戦場の地形を写したものである。布陣は写さない
   ――誰がどこに立つかは盤の上の成り行きで決まる。土地の名も画面には出さず、
   「二つの川が落ち合う平野」といった土地柄だけを見せる。

   一歩は 0.80m。盤はいずれも八千×五千六百歩（六.四km×四.五km）で、
   三十隊ずつ、合わせて六十隊が長い戦列で向き合える広さを確かめてある。

   ------------------------------------------------------------------- 攻守

   守勢は「拠る所」を与えられる――高み、川の向こう、城下。攻勢は開けた所から
   押す。関ヶ原で西軍が笹尾山と天満山の高みに拠り、東軍が桃配山から東の野に
   展いたのと同じ置き方である。ただし拠る所には必ず代償を付けた。背が川で
   塞がっていたり、退き口が橋ひとつだったりする。守れば強いが、崩れれば壊滅する。

   ------------------------------------------------------------- 地形の組み方

   山と丘は円を連ねて尾根にする。円を一つだけ置くと、麓が崖のように切り立ち、
   隊が山肌に貼りつく（関ヶ原でも西軍が一隊残らず平地に立つ、という逆さまな
   ことが起きた）。峰の円のまわりに低い裾の円を重ね、坂を段々に落とす。

   木立は野一面に撒かない。川べり、丘の裾、山の膝――実際に木が茂る所に寄せる。
   布陣の場からは外す。伏兵を生かす野（丘と森の川原）だけは、布陣の場の外側に
   わざと深い森を置く。
   ========================================================================== */

const 賽を巻く = (種) => () => {
  種 |= 0; 種 = (種 + 0x6D2B79F5) | 0;
  let t = Math.imul(種 ^ (種 >>> 15), 1 | 種);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};

/* 尾根を引く。節を結んで円を連ね、峰から裾へ高さを落とす。 */
function 尾根(節, { 高, r, 裾 = 0.55, 名 = "尾根", 札 = null, 間 = 0.62 } = {}) {
  const 出 = [];
  for (let i = 0; i < 節.length - 1; i++) {
    const [x1, y1, h1 = 高, r1 = r] = 節[i], [x2, y2, h2 = 高, r2 = r] = 節[i + 1];
    const 距 = Math.hypot(x2 - x1, y2 - y1);
    const 数 = Math.max(1, Math.round(距 / (Math.min(r1, r2) * 間)));
    for (let k = 0; k < 数; k++) {
      const t = k / 数;
      出.push({ 名, 高: Math.round(h1 + (h2 - h1) * t), x: Math.round(x1 + (x2 - x1) * t),
        y: Math.round(y1 + (y2 - y1) * t), r: Math.round(r1 + (r2 - r1) * t) });
    }
  }
  const [lx, ly, lh = 高, lr = r] = 節[節.length - 1];
  出.push({ 名, 高: lh, x: lx, y: ly, r: lr });
  if (札 != null && 出[札]) 出[札].札 = true;
  /* 裾。峰の円の外側に、低くて広い円を重ねて坂を段々にする。 */
  const 裾ら = 出.filter((_, i) => i % 2 === 0).map((o) => ({ 名, 高: Math.round(o.高 * 裾),
    x: o.x, y: o.y, r: Math.round(o.r * 1.28) }));
  return { 峰: 出, 裾: 裾ら };
}

/* 木立を散らす。寄せる帯（川べり・丘の裾）を渡し、布陣の場からは外す。 */
function 木を散らす(種, n, 幅, 高, { 寄 = null, 避 = [], r = [90, 150], 縁 = 240, 間 = 110 } = {}) {
  const 賽 = 賽を巻く(種);
  const 出 = [];
  for (let i = 0; i < n * 90 && 出.length < n; i++) {
    const x = 縁 + 賽() * (幅 - 縁 * 2), y = 縁 + 賽() * (高 - 縁 * 2);
    if (寄 && !寄(x, y, 賽)) continue;
    const rr = Math.round(r[0] + 賽() * (r[1] - r[0]));
    let 良 = true;
    for (const a of 避) if (Math.hypot(a.x - x, a.y - y) < (a.r || 0) + rr + (a.間 || 0)) { 良 = false; break; }
    if (!良) continue;
    for (const a of 出) if (Math.hypot(a.x - x, a.y - y) < a.r + rr + 間) { 良 = false; break; }
    if (良) 出.push({ x: Math.round(x), y: Math.round(y), r: rr });
  }
  return 出;
}

/* 折れ線の節を細かく割り、少し蛇行させる（真っ直ぐな川は嘘くさい）。 */
const 筋 = (pts, 割 = 4, 揺 = 0, 種 = 7) => {
  const 賽 = 賽を巻く(種), 出 = [];
  for (let i = 0; i < pts.length - 1; i++) {
    const [x1, y1] = pts[i], [x2, y2] = pts[i + 1];
    const dx = x2 - x1, dy = y2 - y1, 長 = Math.hypot(dx, dy) || 1;
    const nx = -dy / 長, ny = dx / 長;
    for (let k = 0; k < 割; k++) {
      const t = k / 割, w = 揺 ? (賽() - 0.5) * 2 * 揺 * Math.sin(Math.PI * t) : 0;
      出.push({ x: Math.round(x1 + dx * t + nx * w), y: Math.round(y1 + dy * t + ny * w) });
    }
  }
  const [lx, ly] = pts[pts.length - 1];
  出.push({ x: lx, y: ly });
  return 出;
};
const 節々 = (pts) => pts.map(([x, y]) => ({ x, y }));
/* 点から線（川筋）までの隔たり。木立を川べりへ寄せるのに使う。 */
const 筋までの距 = (筋ら, x, y) => {
  let 最 = Infinity;
  for (const p of 筋ら) { const d = Math.hypot(p.x - x, p.y - y); if (d < 最) 最 = d; }
  return 最;
};
