/* ==========================================================================
   天下分け目の采配（GDD 12.6）

   遊ぶ側だけが挑めるのでは、盤が片肺になる。AI の大身も、肩を並べる家へ
   一戦を挑む。ただし無闇には挑まない――兵で劣っていれば、まず国を肥やす。

   遊ぶ側の関わらない一戦は、盤を開かずにここで裁く。六十四隊を日暮れまで
   回せば一戦で数秒かかり、月送りが止まる。数と器量と野の利で勝敗を決め、
   跡の始末だけを本式に行う。遊ぶ側の一戦は画面で戦う。
   ========================================================================== */
import { clamp } from "../core/util.js";
import { 家の当主 } from "../core/kiryou.js";
import { 分け目の野, 野を探す } from "../data/wakemeba.js";
import {
  器量くらべ, 天下分け目を挑めるか, 天下分け目を起こす, 分け目の兵, 分け目の沙汰,
  取る城を見立てる, 野を選ぶ側, 野の見立て, 石高の順,
} from "../core/wakeme.js";

export const 挑む腰 = 0.10;                  // 条件が揃った月に挑む目

/* 挑むかどうか。兵で大きく劣るなら見送る。 */
export function 挑むか(s, 主, 的) {
  const 我 = 分け目の兵(s, 主), 彼 = 分け目の兵(s, 的);
  if (我 <= 0 || 彼 <= 0) return false;
  const 比 = 我 / 彼;
  const 当 = 家の当主(s, 主);
  /* 器量のある当主は、五分でも挑む。凡庸な当主は、倍でなければ動かない。 */
  const 腰 = 当 ? clamp(1.35 - (当.valor + 当.wit) / 300, 0.9, 1.35) : 1.2;
  return 比 >= 腰;
}

/* AI の大身が一戦を挑む。月に一件まで。

   家の総当たりで条件を調べると、月ごとに「家数の二乗 × 城数」を数えることになる
   （五十家・二百七十一城で百万回を超え、三十年の走りが目に見えて遅くなった）。
   挑めるのは石高の並びで隣り合う家だけなのだから、まず並びを一度だけ作り、
   上位の隣り合う組にかぎって調べる。 */
export const 見る組の数 = 8;                 // 並びの上から何組まで見るか

export function 天下分け目の采配(s, { 告げる } = {}) {
  if (s.分け目) return null;
  const 順 = 石高の順(s);
  const 組ら = [];
  for (let i = 0; i < Math.min(見る組の数, 順.length - 1); i++) {
    組ら.push([順[i].f, 順[i + 1].f], [順[i + 1].f, 順[i].f]);
  }
  for (const [主, 的] of 組ら) {
    if (主 === s.player) continue;                 // 遊ぶ側は自分で挑む
    if (!天下分け目を挑めるか(s, 主, 的).ok) continue;
    if (!挑むか(s, 主, 的)) continue;
    if (Math.random() > 挑む腰) continue;
    const 選 = 野を選ぶ側(s, 主, 的);
    const 野 = 選 ? 野の見立て(s, 選, 選 === 主 ? 的 : 主) : null;
    const w = 天下分け目を起こす(s, 主, 的, { 野 });
    if (!w) continue;
    if (告げる) {
      告げる(`${(s.factions[主] || {}).name}が${(s.factions[的] || {}).name}へ天下分け目を挑んだ。`
        + `兵は${w.待ち}ヶ月のうちに本拠へ集まる。`);
    }
    return w;
  }
  return null;
}

/* 野を選べる側の見立ては盤の側（core/wakeme.js）に置いてある。
   遊ぶ側が挑んだときも、相手はこれで選ぶ。 */
export const AIの選ぶ野 = (s, 選ぶ側, 相手) => 野の見立て(s, 選ぶ側, 相手);

/* 遊ぶ側の関わらない一戦を、盤を開かずに裁く。 */
export function 盤を開かずに裁く(s, w, { 告げる } = {}) {
  const 力 = (fid) => {
    const 兵 = 分け目の兵(s, fid);
    const 器 = 器量くらべ(s, fid);
    return 兵 * (0.8 + 器 / 1000);
  };
  const 野 = 野を探す(w.野);
  const a = 力(w.挑), b = 力(w.受);
  /* 野を選んだ側には、地の利がいくらか乗る。 */
  const 利 = (fid) => (w.選んだ側 === fid ? 1.08 : 1);
  const A = a * 利(w.挑) * (0.85 + Math.random() * 0.3);
  const B = b * 利(w.受) * (0.85 + Math.random() * 0.3);
  const 勝 = A >= B ? w.挑 : w.受;
  const 負 = 勝 === w.挑 ? w.受 : w.挑;
  /* 敗走の度合いは、力の開きから見積もる。 */
  const 開 = Math.max(A, B) / Math.max(1, Math.min(A, B));
  const 敗走比 = clamp(0.25 + (開 - 1) * 1.2, 0.2, 1);
  const 出した兵 = 分け目の兵(s, 負);
  const 城ら = 取る城を見立てる(s, 勝, 負);
  const 出た将ら = (s.generals || []).filter((g) => g.faction === 負 && !g.captive).map((g) => g.id);
  const 跡 = 分け目の沙汰(s, { 勝, 負, 城ら, 敗走兵: Math.round(出した兵 * 敗走比), 出した兵,
    出た将ら, 告げる });
  if (告げる) {
    告げる(`${野 ? 野.詞 : "野"}に兵十万余。${(s.factions[勝] || {}).name}が${(s.factions[負] || {}).name}を破り、天下分け目は決した。`);
  }
  return { 勝, 負, 跡 };
}
