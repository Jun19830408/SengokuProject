/* ==========================================================================
   風雲：武将の帳に載らない家中の者（架空の上役と同じ組の者）

   遊ぶ人の申し出：「その大名家の組織ツリーを作りたいです。…上司の名前も武将でないものも架空で載せたいです」。
   主人公の筋の上役のうち、物頭から五人長までは武将の帳（s.generals）に載らない。組織の木（hitori/soshiki.js）と仕官の
   物語（hitori/fuun.js 風雲を始める）に、その者たちの名を出す。
     名 … 家と風雲を始めた年月から決まる乱数で選ぶ（記録に置かずとも、いつ開いても同じ名になる。主人公が取り立てられて
           上役の身分に就けば、その上役は筋から外れる）
     物頭は姓と名。それより下（三百人長から五人長）と同じ組の足軽は名だけ（主人公も物頭に取り立てられるまで名だけ：
           hitori/fuun.js 名乗り）
   名は見本の組み合わせで、実在の人物ではない。武将の帳の者と同じ名になれば選び直す。値はみな仮。
   ========================================================================== */
import { 名の見本, 鳴らす, 字の鍵 } from "./tezei_meibo.js";

/* 物頭の姓の見本と、上役（物頭から五人長）の名の見本 */
const 姓の見本 = ["大野木", "竹腰", "堀尾", "野々村", "岡部", "長谷川", "山田", "伊藤", "今枝", "林田", "沢井", "中川",
  "松井", "大島", "富田", "吉田", "安藤", "村井", "坪内", "石黒"];
const 上役の名の見本 = ["弥五郎", "権兵衛", "甚左衛門", "与三郎", "半兵衛", "太郎左衛門", "新右衛門", "惣兵衛", "彦右衛門",
  "孫三郎", "清兵衛", "市之丞", "藤十郎", "源左衛門", "伝右衛門", "八郎兵衛", "作右衛門", "久左衛門", "助之進", "七郎次"];
/* 上役の身分（上から）。主人公の身分より上の者だけを筋に出す（hitori/soshiki.js） */
export const 架空の上役の身分 = ["物頭", "三百人長", "百人長", "五十人長", "十人長", "五人長"];
export const 同じ組の数 = 4;                     // 足軽のとき、同じ五人組にいるほかの足軽（五人長の組は五人。主人公を入れて）

/* 架空の上役と同じ組の者。s … 盤（s.風雲 がある）。返すのは { 物頭, 三百人長, 百人長, 五十人長, 十人長, 五人長, 同輩: [名…] } */
export function 架空の上役(s) {
  const f = s && s.風雲;
  const 始 = (f && f.始め) || { 年: s && s.year, 月: s && s.month };
  const r = 鳴らす(字の鍵(`${s && s.player}|${始.年}|${始.月}|上役`));
  const 武将の名 = new Set(((s && s.generals) || []).map((x) => x.name));
  const 使った = new Set([f && f.名, f && f.通称].filter(Boolean));
  const 選ぶ = (見本, 前 = "") => {
    for (let k = 0; k < 40; k++) {
      const n = 前 + 見本[Math.floor(r() * 見本.length)];
      if (!使った.has(n) && !武将の名.has(n) && ![...使った].some((u) => u.endsWith(n.slice(前.length)))) { 使った.add(n); return n; }
    }
    const n = 前 + 見本[Math.floor(r() * 見本.length)]; 使った.add(n); return n;
  };
  const 出 = {};
  const 姓 = 姓の見本[Math.floor(r() * 姓の見本.length)];
  出.物頭 = 選ぶ(上役の名の見本, 姓);
  for (const 身 of 架空の上役の身分.slice(1)) 出[身] = 選ぶ(身 === "十人長" || 身 === "五人長" ? 名の見本 : 上役の名の見本);
  出.同輩 = Array.from({ length: 同じ組の数 }, () => 選ぶ(名の見本));
  return 出;
}
