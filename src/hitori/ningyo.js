export const 人形の近さ = (zc) => clamp((zc - 1.6) / 1.4, 0, 1);

/* 人形の段（〇 粒・一 粗・二 中・三 細）。s … 画の上の背丈（px）、d … 写しからの奥行き（m）。与平（我）は数の限り
   （環.細の奥・中の奥）に入れず、見かけの大きさだけで決める（下の 人形を描く の説明） */
export function 人形の段(s, d, 環, 我 = false) {
  const 中奥 = 我 ? Infinity : (環 && 環.中の奥) ?? Infinity, 細奥 = 我 ? Infinity : (環 && 環.細の奥) ?? Infinity;
  return s < 7 ? 0 : s < 16 || d > 中奥 ? 1 : s < 36 || d > 細奥 ? 2 : 3;
}

/* ---------- 一人を描く ---------- */
