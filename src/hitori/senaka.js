/* 方向キー（輪または鍵盤）を押しているか */
const 方向キーを押しているか = (入) => !!入 && (Math.hypot(入.jx || 0, 入.jy || 0) > 0.12 || (!!入.keys && ["u", "d", "l", "r"].some((k) => 入.keys.has(k))));
