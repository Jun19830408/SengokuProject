      const rx = 我.x - p.x, rz = 我.z - p.z, d2 = Math.hypot(rx, rz) || 1; 我.退x = rx / d2 * 2.2; 我.退z = rz / d2 * 2.2;
      if (我.hp <= 0) { 我.倒 = t; 我.倒向 = -1; 我.撃 = null; 態.終 = { t: t + 1.6, 種: "討死" }; }
