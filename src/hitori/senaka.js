  if (!s && 作る) { s = { cd: 0, 突始: -9, 突向: null, x: p.x, z: p.z, 見刻: 態.t, 拍: -1 }; m.set(p.番, s); }
  if (s) { s.x = p.x; s.z = p.z; }
