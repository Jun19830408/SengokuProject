    + "|" + (m.fac || []).map((f) => (f.hp > 0 ? 1 : 0)).join("") + "|" + (m.付城 || []).length + "|" + (m.出城 ? m.出城.gates.map((g) => (g.broken ? 1 : 0)).join("") : "");
