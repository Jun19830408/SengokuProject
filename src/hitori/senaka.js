    if (近) { tx = 近.x - 我.x; tz = 近.z - 我.z; } else if (有 && sp > 0.05) { tx = vx; tz = vz; }
    const L = Math.hypot(tx, tz); if (L > 1e-4) { 我.fx = tx / L; 我.fz = tz / L; }
