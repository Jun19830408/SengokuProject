      for (let k = 0; k <= 20; k++) { const a = (k / 20) * Math.PI * 2, [qx, qy, qz] = P(x + Math.cos(a) * r, 水面 + 0.01, z + Math.sin(a) * r); if (qz < 0.4) { ctx.beginPath(); break; } k ? ctx.lineTo(qx, qy) : ctx.moveTo(qx, qy); }
