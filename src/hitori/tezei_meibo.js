/* ---- 伸び方（案の③）。遊ぶ人の申し出：「戦の経験値によってプレイヤーの統率力もあがっていく」「部隊のポテンシャルと
   経験値によって統率力が成長する」。
     練れ … 合戦に出た名簿の者（この戦で討たれて欠員になった枠は除く）の練れが、練れの上（一）へ近づく。
            近づく割は 練れの伸び.基、槍を合わせた（手勢が討ち取るか討たれた）戦なら 練れの伸び.戦 を足す
     与平の統率 … 手勢を率いた合戦ごとに 統率の伸び.基、槍を合わせた戦なら 統率の伸び.戦、名簿の素質の均しが
            統率の伸び.素質の目安 より高ければ 統率の伸び.素質 を足す（素質の高い隊を率いると伸びが速い）。統率が
            統率の伸び.鈍る より上なら半ば（切り上げ）。上限は九十（ほかの能力と同じ）
     戦の種の倍 … 遊ぶ人の申し出（「威力偵察の伸びは通常の合戦よりも少なく、山賊退治での伸びは威力偵察よりもさらに
            少ない伸びにする」）により、練れの伸びと統率の伸びに 戦の伸びの倍 を掛ける。統率の端（一に満たない伸び）は
            f.統率の端 に持ち越し、一に届けば上げる（下の 統率に足す）
   値はみな仮 ---- */
export const 練れの伸び = { 基: 0.1, 戦: 0.08 };
export const 統率の伸び = { 基: 1, 戦: 1, 素質: 1, 素質の目安: 55, 鈍る: 70, 上: 90 };
export const 戦の伸びの倍 = { 合戦: 1, 威力偵察: 0.6, 山賊退治: 0.3 };
export const 伸びの倍を見る = (種) => (種 && 戦の伸びの倍[種] != null ? 戦の伸びの倍[種] : 1);
/* 名簿の練れを伸ばす（欠員と、この戦で欠けた枠 欠けた を除く）。倍 … 戦の種の倍。返すのは伸ばした枠の数 */
export function 練れを伸ばす(f, 戦った, 欠けた = new Set(), 倍 = 1) {
  const 手 = f && f.手勢; if (!手) return 0;
  const k = (練れの伸び.基 + (戦った ? 練れの伸び.戦 : 0)) * 倍;
  let n = 0;
  手.名簿 = 手.名簿.map((m) => { if (m.欠 || !(m.人 > 0) || 欠けた.has(m.id)) return m; n++; return { ...m, 練れ: Math.round(Math.min(練れの上, m.練れ + (練れの上 - m.練れ) * k) * 100) / 100 }; });
  return n;
}
/* 与平の統率の伸び（この戦で上がる数。倍が一に満たなければ端が出る） */
export function 統率の伸びを量る(今, 戦った, 素質, 倍 = 1) {
  const 伸 = 統率の伸び.基 + (戦った ? 統率の伸び.戦 : 0) + (素質 > 統率の伸び.素質の目安 ? 統率の伸び.素質 : 0);
  const 鈍 = (今 >= 統率の伸び.鈍る ? Math.ceil(伸 / 2) : 伸) * 倍;
  return Math.max(0, Math.min(統率の伸び.上, 今 + 鈍) - 今);
}
/* 統率に伸びを足す（端は f.統率の端 に持ち越す）。返すのは上がった数（整数） */
export function 統率に足す(f, 伸) {
  const 和 = (f.統率の端 || 0) + Math.max(0, 伸 || 0), 整 = Math.floor(和 + 1e-9);
  const 前 = f.統率;
  f.統率 = Math.min(統率の伸び.上, 前 + 整);
  f.統率の端 = f.統率 >= 統率の伸び.上 ? 0 : Math.round((和 - 整) * 100) / 100;
  return f.統率 - 前;
}
