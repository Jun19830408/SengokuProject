/* 新参（空きを埋める者）。素質三十・練れ五割五分・武勇三十・扶持は一人あたり一 */
export const 新参の値 = { 素質: 30, 練れ: 0.55, 武勇: 30, 扶持: 1 };
/* 練れの幅（〇.五から一。今の統率＝素質×練れ） */
export const 練れの下 = 0.5, 練れの上 = 1;

/* 名は月と身分から決まる乱数で選ぶ（同じ月に開き直しても同じ候補が出る）。名は百姓の名の見本で、実在の人物ではない */
const 名の見本 = ["与作", "弥助", "権六", "太郎兵衛", "次郎作", "小助", "彦八", "甚六", "源太", "六蔵", "喜平", "伝八",
  "庄助", "茂作", "新六", "孫七", "吉蔵", "八郎", "市蔵", "長吉", "仁助", "徳次", "留吉", "亀蔵", "松五郎", "竹次", "梅吉",
  "佐吉", "清六", "嘉平", "惣七", "久蔵", "辰五郎", "寅吉", "卯助", "巳之助", "平作", "又八", "善六", "文吉"];
const 鳴らす = (n) => { let h = n | 0; return () => { h = (h + 0x6D2B79F5) | 0; let t = Math.imul(h ^ (h >>> 15), 1 | h); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; };
const 字の鍵 = (s) => { let h = 2166136261; for (const ch of String(s)) { h ^= ch.codePointAt(0); h = Math.imul(h, 16777619); } return h | 0; };
const 限る = (v, a, b) => Math.min(b, Math.max(a, v));

export const 名簿の形を見る = (身分) => 名簿の形[身分] || null;
/* 今の統率（素質×練れ） */
export const 今の統率 = (m) => Math.round(m.素質 * m.練れ);
/* 一人あたりの扶持（素質と練れと武勇から。一から八） */
export const 一人の扶持 = (素質, 練れ, 武勇) => 限る(Math.round(1 + (素質 * 練れ - 20) / 12 + (武勇 - 30) / 25), 1, 8);

/* 名簿の一つの枠。人 … 今の人数。定 … 定めの人数（足軽は一、十人隊は十、五十人隊は五十）。単 … 一人あたりの扶持。
   扶持 … 今の人数ぶんの扶持（単×人）。欠 … 欠員の枠（人は〇） */
const 隊の名 = (人) => (人 === 10 ? "十" : "五十");
/* 新参の枠を作る */
export function 新参を作る(形, 番) {
  const 人 = 形.人;
  return { id: `新参${番}`, 種: 形.種, 人, 定: 人, 名: 人 > 1 ? `新参の${隊の名(人)}人` : "新参", 頭: null,
    素質: 新参の値.素質, 練れ: 新参の値.練れ, 武勇: 新参の値.武勇, 単: 新参の値.扶持, 扶持: 新参の値.扶持 * 人, 新参: true };
}
/* 欠員の枠を作る */
export function 欠員を作る(形, 番) {
  return { id: `欠${番}`, 種: 形.種, 人: 0, 定: 形.人, 名: "欠員", 頭: null, 素質: 0, 練れ: 0, 武勇: 0, 単: 0, 扶持: 0, 欠: true };
}
/* 古い記録の枠（定・単が無い）を正す */
const 枠を正す = (m, 形) => ({ ...m, 定: m.定 ?? 形.人, 単: m.単 ?? (m.人 > 0 ? m.扶持 / m.人 : 0) });
/* 欠けた人数（定めの人数と今の人数の差） */
export const 欠けの数 = (m) => Math.max(0, (m.定 ?? m.人) - m.人);
/* 候補を作る（月と身分と主人公の名から決まる乱数で。同じ月なら同じ候補） */
export function 候補を作る(身分, 年, 月, 名 = "") {
  const 形 = 名簿の形を見る(身分); if (!形) return [];
  const r = 鳴らす(字の鍵(`${名}|${身分}|${年}|${月}`));
  const 鐘 = () => (r() + r() + r()) / 3;
  const 使った = new Set(), 名を選ぶ = () => { for (let k = 0; k < 20; k++) { const n = 名の見本[Math.floor(r() * 名の見本.length)]; if (!使った.has(n)) { 使った.add(n); return n; } } return 名の見本[Math.floor(r() * 名の見本.length)]; };
  const 出 = [];
  for (let i = 0; i < 形.候補; i++) {
    const 素質 = Math.round(20 + 65 * 鐘()), 練れ = Math.round((0.55 + 0.4 * r()) * 100) / 100, 武勇 = Math.round(25 + 55 * 鐘());
    const 頭 = 名を選ぶ();
    const 単 = 一人の扶持(素質, 練れ, 武勇);
    出.push({ id: `候${年}-${月}-${i}`, 種: 形.種, 人: 形.人, 定: 形.人, 名: 形.人 > 1 ? `${頭}の${隊の名(形.人)}人` : 頭, 頭: 形.人 > 1 ? 頭 : null,
      素質, 練れ, 武勇, 単, 扶持: 単 * 形.人 });
  }
  return 出;
}

/* 名簿の扶持の和・手勢の統率（今の統率を人数で均す。名簿が無ければ null） */
export const 名簿の扶持 = (名簿) => (名簿 || []).reduce((a, m) => a + (m.扶持 || 0), 0);
export function 手勢の統率を量る(名簿) {
  const 人 = (名簿 || []).reduce((a, m) => a + m.人, 0);
  return 人 > 0 ? Math.round((名簿 || []).reduce((a, m) => a + 今の統率(m) * m.人, 0) / 人) : null;
}
/* 名簿の均し（素質・練れ・武勇。人数で均す） */
const 均す = (名簿, 鍵) => { const 人 = 名簿.reduce((a, m) => a + m.人, 0); return 人 ? 名簿.reduce((a, m) => a + m[鍵] * m.人, 0) / 人 : 0; };

/* 名簿を今の身分の形に整える（無ければ新参で作る。取り立てなら引き継ぐ）。候補は月が改まれば作り直す。f を改めて返す */
export function 手勢の名簿を整える(f, 年, 月) {
  const 形 = f && 名簿の形を見る(f.身分);
  if (!形) return f;
  const 手 = f.手勢 || (f.手勢 = { 身分: null, 名簿: [], 候補: [], 候補の月: null, 雇った: [], 番: 0 });
  if (手.身分 !== f.身分) {
    let 古 = (手.名簿 || []).filter((m) => m.人 > 0);
    /* 取り立て：前の名簿を、新しい形の枠にまとめて引き継ぐ（足軽十人 → 十人隊一つ。十人隊五つ → 五十人隊一つ）。
       欠員があれば、まとめた隊は欠けたまま（定めの人数に足りない） */
    if (古.length && (古[0].定 ?? 古[0].人) < 形.人) {
      const 人 = Math.min(形.人, 古.reduce((a, m) => a + m.人, 0));
      古 = 人 > 0 ? [{
        id: `継${年}-${月}`, 種: 形.種, 人, 定: 形.人, 名: `${f.名}の${隊の名(形.人)}人（もとの手勢）`, 頭: f.名,
        素質: Math.round(均す(古, "素質")), 練れ: Math.round(均す(古, "練れ") * 100) / 100, 武勇: Math.round(均す(古, "武勇")),
        単: 名簿の扶持(古) / Math.max(1, 古.reduce((a, m) => a + m.人, 0)), 扶持: 0, 継ぎ: true }] : [];
      for (const m of 古) m.扶持 = Math.round(m.単 * m.人);
    }
    const 名簿 = 古.slice(0, 形.数).map((m) => 枠を正す(m, 形));
    for (let k = 名簿.length; k < 形.数; k++) 名簿.push(新参を作る(形, 手.番 = (手.番 || 0) + 1));
    手.名簿 = 名簿; 手.身分 = f.身分; 手.候補の月 = null;
  } else 手.名簿 = 手.名簿.map((m) => 枠を正す(m, 形));
  const 鍵 = `${年}-${月}`;
  if (手.候補の月 !== 鍵) { 手.候補 = 候補を作る(f.身分, 年, 月, f.名); 手.候補の月 = 鍵; 手.雇った = []; }
  return f;
}

/* 雇い入れる枠（替える者の枠。無ければ、欠員の枠、それも無ければ新参の枠） */
const 雇う枠 = (手, 替える) => (替える ? 手.名簿.findIndex((m) => m.id === 替える)
  : 手.名簿.findIndex((m) => m.欠) >= 0 ? 手.名簿.findIndex((m) => m.欠) : 手.名簿.findIndex((m) => m.新参));
/* 雇えるか（訳を返す。雇えれば null） */
export function 雇えるか(f, 候補id, 替える = null) {
  const 手 = f && f.手勢, 形 = f && 名簿の形を見る(f.身分);
  if (!手 || !形) return "手勢を率いる身分ではない";
  const 候 = (手.候補 || []).find((x) => x.id === 候補id);
  if (!候 || (手.雇った || []).includes(候補id)) return "もう雇った候補";
  const 番 = 雇う枠(手, 替える);
  if (番 < 0) return "空き（欠員か新参の枠）が無い。先に暇を出す";
  if (名簿の扶持(手.名簿) - 手.名簿[番].扶持 + 候.扶持 > 形.枠) return `扶持の枠（${形.枠}）を超える`;
  return null;
}
/* 雇う（欠員か新参の枠、または替える者の枠に入れる）。f を改めて返す（雇えなければ そのまま） */
export function 手勢を雇う(f, 候補id, 替える = null) {
  if (雇えるか(f, 候補id, 替える)) return f;
  const 手 = f.手勢, 候 = 手.候補.find((x) => x.id === 候補id);
  手.名簿[雇う枠(手, 替える)] = { ...候, id: `雇${候.id}` };
  手.雇った = [...(手.雇った || []), 候補id];
  return f;
}
/* 暇を出す（その枠は欠員になる。扶持もそのぶん下がる）。欠員には暇を出せない */
export function 暇を出す(f, 名簿id) {
  const 手 = f && f.手勢, 形 = f && 名簿の形を見る(f.身分);
  if (!手 || !形) return f;
  const 番 = 手.名簿.findIndex((m) => m.id === 名簿id && !m.欠);
  if (番 < 0) return f;
  手.名簿[番] = 欠員を作る(形, 手.番 = (手.番 || 0) + 1);
  return f;
}
/* 補充（新参で埋める）。欠員の枠は新参の枠に、欠けた隊は欠けた人数ぶんの新参を入れる（隊の素質・練れ・武勇は新参の
   ぶんだけ下がり、一人あたりの扶持も均される）。補充の扶持（新参一人に一）が枠を超えるなら埋めない。返すのは訳（埋めれば null） */
export function 補充できるか(f, 名簿id) {
  const 手 = f && f.手勢, 形 = f && 名簿の形を見る(f.身分);
  if (!手 || !形) return "手勢を率いる身分ではない";
  const m = 手.名簿.find((x) => x.id === 名簿id);
  if (!m || !欠けの数(m)) return "欠けていない";
  if (名簿の扶持(手.名簿) + 欠けの数(m) * 新参の値.扶持 > 形.枠) return `扶持の枠（${形.枠}）を超える`;
  return null;
}
export function 補充する(f, 名簿id) {
  if (補充できるか(f, 名簿id)) return f;
  const 手 = f.手勢, 形 = 名簿の形を見る(f.身分), 番 = 手.名簿.findIndex((x) => x.id === 名簿id), m = 手.名簿[番];
  if (m.欠) { 手.名簿[番] = 新参を作る(形, 手.番 = (手.番 || 0) + 1); return f; }
  const 足 = 欠けの数(m), 新 = 新参の値, 人 = m.人 + 足;
  const 均 = (鍵) => (m[鍵] * m.人 + 新[鍵] * 足) / 人;
  手.名簿[番] = { ...m, 人, 素質: Math.round(均("素質")), 練れ: Math.round(均("練れ") * 100) / 100, 武勇: Math.round(均("武勇")),
    単: (m.単 * m.人 + 新.扶持 * 足) / 人, 扶持: Math.round(m.単 * m.人 + 新.扶持 * 足) };
  return f;
}
/* 欠けたところを、みな新参で埋める（扶持の枠に収まるぶんだけ。前の枠から順に） */
export function みな補充する(f) {
  const 手 = f && f.手勢; if (!手) return f;
  for (const m of [...手.名簿]) if (欠けの数(m) && !補充できるか(f, m.id)) 補充する(f, m.id);
  return f;
}
/* 名簿の欠けた人数の和 */
export const 欠けの和 = (名簿) => (名簿 || []).reduce((a, m) => a + 欠けの数(m), 0);

/* 合戦の損を名簿に移す。残 … 生き残った手勢の兵の数（盤の手勢の組の人数の和）。乱 … 乱数（〇〜一）。
   遊ぶ人の申し出（「部隊が少なくなったらその分扶持も下がり、その分補充するという流れにしたい」）により、討たれた兵の
   ぶんは欠員にする（新参では埋めない。埋めるのは屋敷の 補充する か 手勢を雇う）。
   一人ずつの名簿（十人長）は、討たれた数だけ、武勇の低い者ほど討たれやすく選んで欠員の枠にする（扶持も払わない）。
   隊の名簿は、討たれたぶんを隊ごとに人数の割で振り、その隊の人数を減らす（生き残りの素質・練れ・武勇はそのまま。
   扶持は一人あたりの扶持×残った人数に下がる。皆討たれた隊は欠員の枠になる）。
   返すのは { 減（討たれた数）, 欠けた（欠員になった枠の id） } */
export function 戦の損を名簿に移す(f, 残, 乱 = Math.random) {
  const 手 = f && f.手勢, 形 = f && 名簿の形を見る(f.身分), 欠けた = new Set();
  if (!手 || !形 || !Number.isFinite(残)) return { 減: 0, 欠けた };
  const 全 = 手.名簿.reduce((a, m) => a + m.人, 0), 減 = 限る(Math.round(全 - 残), 0, 全);
  if (!減) return { 減: 0, 欠けた };
  if (形.人 === 1) {
    const 候 = 手.名簿.map((m, i) => ({ i, m })).filter((o) => o.m.人 > 0).map((o) => ({ i: o.i, w: 1.6 - o.m.武勇 / 100 }));
    for (let k = 0; k < 減 && 候.length; k++) {
      const 和 = 候.reduce((a, o) => a + o.w, 0); let x = 乱() * 和, j = 0;
      for (; j < 候.length - 1; j++) { x -= 候[j].w; if (x <= 0) break; }
      const { i } = 候.splice(j, 1)[0];
      手.名簿[i] = 欠員を作る(形, 手.番 = (手.番 || 0) + 1); 欠けた.add(手.名簿[i].id);
    }
    return { 減, 欠けた };
  }
  /* 隊：減りを人数の割で振る（割り切れない端は、端の大きい隊から一人ずつ。隊の人数を超えては振らない） */
  const 分 = 手.名簿.map((m) => Math.floor(減 * m.人 / 全));
  let 端 = 減 - 分.reduce((a, v) => a + v, 0);
  const 順 = 手.名簿.map((m, i) => ({ i, r: 減 * m.人 / 全 - 分[i] })).sort((a, z) => z.r - a.r || a.i - z.i);
  for (let 巡 = 0; 端 > 0 && 巡 < 4; 巡++) for (const { i } of 順) { if (端 <= 0) break; if (分[i] < 手.名簿[i].人) { 分[i] += 1; 端 -= 1; } }
  手.名簿 = 手.名簿.map((m, i) => {
    if (!分[i]) return m;
    const 人 = m.人 - 分[i];
    if (人 <= 0) { const 欠 = 欠員を作る(形, 手.番 = (手.番 || 0) + 1); 欠けた.add(欠.id); return 欠; }
    return { ...m, 人, 扶持: Math.round(m.単 * 人) };
  });
  return { 減, 欠けた };
}

/* 盤へ渡す手勢の数（名簿の人数。名簿が無ければ身分の数） */
