/* ==========================================================================
   手勢の名簿（風雲モード・十人長から三百人長。案の②：雇い入れ）

   遊ぶ人の申し出：「部隊のメンバーですが、自分で雇えるようにしたいですね。10人長のときはメンバー10人を選べる。
   で、30人長と50人長になったら10人隊を選べる、100人以上だと50人隊を選べるようにしたいです。選べる人や部隊に
   ついては、統率力が示されており、これによってプレイヤーの部隊の統率力も決まるような感じでしょうか」。
   案に対する遊ぶ人の答え：縛りは「扶持の枠と候補の数の両方」、統率は「数字」で見せる、「与平の統率が低いと良い兵を
   活かしきれない作りで（よい）」、作る順は「①統率で操作のしやすさ ②雇い入れの画面 ③伸び方」。

     選ぶもの … 十人長は足軽を一人ずつ十人、三十人長・五十人長は十人隊を三つ・五つ、百人長・三百人長は五十人隊を
                二つ・六つ（下の 名簿の形）
     札       … 名・統率（今の統率＝素質×練れ。素質と練れも出す）・武勇・扶持
     縛り     … 扶持の枠（身分で決まる。名簿の扶持の和がこれを超えて雇えない）と、候補の数（月ごとに入れ替わる）
     新参     … 取り立てで新たにできた枠は、新参（素質も練れも低いが、扶持は安い）で埋める
     合戦の損 … 遊ぶ人の申し出（「部隊が少なくなったらその分扶持も下がり、その分補充するという流れにしたい」）により、
                討たれた兵のぶんは欠員になる（手勢の人数が減り、その者の扶持も払わない。十人長なら討たれた者の枠が
                欠員に、隊なら隊の人数が減る。下の 戦の損を名簿に移す）。暇を出しても、その枠は欠員になる
     補充     … 欠員は屋敷で埋める。候補を雇って入れるか、新参で埋める（隊の欠けは新参で埋め、そのぶん隊の素質・練れ・
                武勇が下がる。下の 補充する）。埋めなければ、手勢はその人数のまま合戦に出る
     取り立て … 十人長から三十人長に上がれば、いまの十人を一つの十人隊にまとめて引き継ぎ、残りを選び足す
                （百人長に上がれば、五つの十人隊を一つの五十人隊にまとめる）
   手勢の統率（盤の手勢の統率。hitori/tezei.js 実効の統率）は、名簿の今の統率を人数で均したもの。
   値はみな仮。
   ========================================================================== */
