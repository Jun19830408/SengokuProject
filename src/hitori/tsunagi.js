/* ==========================================================================
   一人働き（武将一人プレイ）のつなぎ

   合戦は三つの寄りで見える。
     駒        … 組の人数を十で割って切り上げた数の駒（battle/draw.js）
     一人ずつ  … 組を五十人にほどいた足軽（battle/shinga.js。絵だけで、理には触れない）
     一人視点  … 与平の背中越し（これから作る）

   駒と一人ずつは、理（組の人数）から絵への一方向でつながっている。どちらも
   組の人数を四捨五入した数（五十まで）から描くので、人数が変われば二つが揃って変わる。
   一人視点では与平が兵を討つので、逆向き（絵の側の一人 → 理の人数）のつなぎが要る。
   それがここである。

   兵を討つ(b, q, 番, 討ち手)
     一、理：組 q の人数を、ちょうど一人減らす。帳簿（損・隊列の乱れ・士気の削れ・
         組を潰したときの武功）は battle/engine.js の applyDamage がふだんの損害と
         同じに付ける（正味：挟撃の割増しと筋書きの手加減は掛けない）。
     二、絵：一人ずつの兵の 番 番目を「指名」する。次に絵の状態を進めるとき
         （shinga.js 新絵状態を進める）、倒れる順の頭にその者が立つ。
   こうして、駒の数・一人ずつの兵・一人視点の三つが、同じ一人の死を見る。

   番 … 一人ずつの兵の持ち場の番（〇〜四十九）。持ち場の番は、前の者が倒れて後ろの
        者が詰めると別の者を指すので、討つその時に引き当てる（組の兵を数える を使う）。
   ========================================================================== */
import { applyDamage } from "../battle/engine.js";
import { 組の見た目 } from "../battle/shinga.js";

/* 組 q を抱える隊 */
export function 組の隊(b, q) {
  for (const c of (b && b.corps) || []) if ((c.squads || []).includes(q)) return c;
  return null;
}

/* 組 q の、いま立っている兵の持ち場の番と居所（絵の上の所。盤の座標） */
export function 組の兵を数える(q) {
  const s = 組の見た目(q);
  if (!s || !s.初) return [];
  const out = [];
  for (let n = 0; n < 50; n++) if (s.生[n]) out.push({ 番: n, x: s.sx[n], y: s.sy[n] });
  return out;
}

/* 与平（討ち手）が、組 q の 番 番目の兵を討つ。討てれば true。
   討ち手 … { 隊, 組, 武勇 }。組を潰したときの武功は、討ち手の組（の組頭）に付く。
   番 を省けば、理の人数だけを一人減らす（誰が倒れるかは絵の側の選びに任せる）。 */
export function 兵を討つ(b, q, 番, 討ち手 = {}) {
  if (!b || !q || !(q.men > 0)) return false;
  const 隊 = 組の隊(b, q);
  if (!隊) return false;
  if (番 != null) {
    const s = 組の見た目(q);
    if (!s || !s.初 || !(番 >= 0 && 番 < 50) || !s.生[番]) return false;
    (s.指名 || (s.指名 = [])).push(番);
  }
  applyDamage(b, 隊, q, 1, 1, 討ち手.武勇, 討ち手.隊 || null, 討ち手.組 || null, true);
  const 記 = b.一人働き || (b.一人働き = { 討ち取り: 0 });
  記.討ち取り += 1;
  return true;
}

/* 撮る道具・試しが覗く口（遊びの側からは呼ばない。battle/shinga.js の window.__組の兵の所 と同じ扱い） */
if (typeof window !== "undefined") window.__一人働き = { 兵を討つ, 組の兵を数える, 組の隊 };
