/* ============================================================
   風雲モード：宿老の段（国主・旗頭）の試験（hitori/fuun.js 宿老の段、core/rank.js 国主に任じる・旗頭に任じる）

   案「宿老で国主・旗頭」と、遊ぶ人の答え「（主人公の城が当主と同じ国にあって国主になれないときは）国主になれる時が来るまで、
   城主のまま待つ」。旗頭はキャンペーンと同じく四国につき一人。
     一、主人公の城が当主のいる国にあれば、宿老になっても国主にならず、城主のまま待つ
     二、当主のいない国に城があれば、宿老に届いたとき国主に任じる。すでに国主がいれば交代し、元の国主の忠誠を下げる。
         その国の城主を寄騎に取る
     三、待っていた主人公も、のちの月の初めに国主になれる形になれば任じる
     四、家が四か国を持ち旗頭の枠が空いていれば、国主の主人公を旗頭に任じる。枠が無ければ国主のまま
     五、上司：国主なら、その国を受け持つ旗頭（いなければ当主）。旗頭なら当主
   値はみな仮。
   ============================================================ */
const path = require('path');
const H = require(path.join(__dirname, '..', 'build', 'harness.cjs'));
const { initState } = H;
const 咎 = [];
const 確 = (名, 可, 添 = '') => { console.log(`  ${可 ? '○' : '★'} ${名}${添 ? '　' + 添 : ''}`); if (!可) 咎.push(名); };
let 種 = 0x5C21;
Math.random = () => { 種 |= 0; 種 = (種 + 0x6D2B79F5) | 0; let t = Math.imul(種 ^ (種 >>> 15), 1 | 種); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
/* 家老まで上げた風雲 */
const 家老の風雲 = () => {
  const s = initState('oda'); H.風雲を始める(s, '与平');
  const f = s.風雲; f.身分 = '三百人長'; f.勲功 = 270; H.取り立てを見る(s); H.名乗りを定める(s, '木下', '藤吉郎');
  const 境 = H.身分の境(s, H.主人公の仮の武将(s));
  f.知行 = 境.侍大将; H.禄高の身分を見る(s); f.知行 = 境.家老; H.禄高の身分を見る(s);
  return { s, 境 };
};
/* 主人公は十三で仕え始め、宿老は二十から（core/rank.js 身分に就ける齢）。仕えて七年たった形にしてから宿老の境に届かせる */
const 宿老にする = (s, 境) => { s.風雲.始め = { ...s.風雲.始め, 年: s.風雲.始め.年 - 7 }; s.風雲.知行 = 境.宿老 + 10; H.禄高の身分を見る(s); };
/* 他家の城を家に移す（そこにいた他家の将は、その家の別の城へ移す） */
const 城を移す = (s, id) => {
  const c = s.castles.find((x) => x.id === id), 旧 = c.faction;
  const 退く = s.castles.find((x) => x.faction === 旧 && x.id !== id);
  for (const g of s.generals.filter((x) => x.at === id && x.faction === 旧)) { g.at = 退く ? 退く.id : null; if (g.本領 === id) g.本領 = 退く ? 退く.id : null; }
  c.faction = s.player; c.lordId = null; c.城代 = false;
  return c;
};
/* 主人公を、家の別の城へ城主として移す */
const 主人公を移す = (s, c) => {
  const g = H.主人公の武将(s), 元 = H.主人公の城(s);
  if (元) 元.lordId = null;
  c.lordId = g.id; g.at = c.id; g.本領 = c.id; s.風雲.城 = c.id;
};

(() => {
  console.log('── 一　主人公の城が当主のいる国（尾張）にあれば、宿老になっても城主のまま待つ');
  {
    const { s, 境 } = 家老の風雲(), f = s.風雲, g = H.主人公の武将(s), 城 = H.主人公の城(s);
    宿老にする(s, 境);
    確('宿老に届いた', f.身分 === '宿老' && H.宿老か(f.身分));
    確('当主のいる国（尾張）では国主にならない', g.役 !== '国主' && g.役 !== '旗頭' && 城.kuni === '尾張', `${城.name}（${城.kuni}）`);
    確('城主のまま', H.主人公の城(s) === 城 && 城.lordId === g.id);
  }

  console.log('\n── 二　当主のいない国に城があれば、宿老に届いたとき国主に任じる（国主がいれば交代）');
  {
    const { s, 境 } = 家老の風雲(), f = s.風雲, g = H.主人公の武将(s);
    const 刈谷 = 城を移す(s, 'kariya'), 岡崎 = 城を移す(s, 'okazaki');
    主人公を移す(s, 刈谷);
    /* 岡崎城に、三河の国主を置いておく */
    const 先 = s.generals.find((x) => x.faction === s.player && !x.lord && !x.風雲の主 && x.at === 'narumi' && x.id !== g.id)
      || s.generals.find((x) => x.faction === s.player && !x.lord && !x.風雲の主);
    先.at = 岡崎.id; 先.本領 = 岡崎.id; 岡崎.lordId = 先.id; 先.fief = Math.max(先.fief || 0, 境.家老 + 100);
    const 先の任 = H.国主に任じる(s, s.player, '三河', 先.id);
    確('（支度）三河に国主を置く', 先の任.ok && 先.役 === '国主', 先の任.why || 先.name);
    const 前の忠誠 = 先.loyal;
    宿老にする(s, 境);
    確('宿老に届いたとき、三河の国主に任じる', g.役 === '国主' && g.役国 === '三河');
    確(`元の国主は役を解かれ、忠誠が${H.城主を外された忠誠の減り}下がる`, 先.役 !== '国主' && 先.loyal === Math.max(0, 前の忠誠 - H.城主を外された忠誠の減り), `${先.name} ${前の忠誠}→${先.loyal}`);
    確('三河の城主（岡崎城の元の国主）を寄騎に取る', 先.寄親 === g.id);
    確('記と知らせに残す', (f.記 || []).some((x) => /宿老として三河の国主に任じられた/.test(x.文)) && (f.知らせ || []).some((x) => /三河の国主に任じられた/.test(x)));
    const 当主 = s.generals.find((x) => x.faction === s.player && x.lord);
    確('国主の上司は、三河を受け持つ旗頭がいなければ当主', f.上司 === 当主.id);
  }

  console.log('\n── 三　待っていた主人公も、のちの月の初めに国主になれる形になれば任じる');
  {
    const { s, 境 } = 家老の風雲(), f = s.風雲, g = H.主人公の武将(s);
    宿老にする(s, 境);
    確('（尾張では）まだ国主でない', g.役 !== '国主');
    const 刈谷 = 城を移す(s, 'kariya'); 主人公を移す(s, 刈谷);
    H.風雲の月の初め(s);
    確('月の初めに、三河の国主に任じる', g.役 === '国主' && g.役国 === '三河');
  }

  console.log('\n── 四　家が四か国を持ち旗頭の枠が空いていれば、国主の主人公を旗頭に任じる');
  {
    const { s, 境 } = 家老の風雲(), f = s.風雲, g = H.主人公の武将(s);
    const 刈谷 = 城を移す(s, 'kariya'); 主人公を移す(s, 刈谷);
    城を移す(s, 'iwamura');                                  // 美濃
    確('（三か国では）旗頭の枠が無い', H.旗頭の枠(s, s.player) === 0);
    宿老にする(s, 境);
    確('三か国なら国主のまま', g.役 === '国主');
    城を移す(s, 'kuwana');                                   // 伊勢。これで尾張・三河・美濃・伊勢の四か国
    確('（四か国で）旗頭の枠が一つ', H.旗頭の枠(s, s.player) === 1);
    H.風雲の月の初め(s);
    確('四か国になれば、月の初めに旗頭に任じる', g.役 === '旗頭' && g.役国 === '三河');
    const 当主 = s.generals.find((x) => x.faction === s.player && x.lord);
    確('旗頭の上司は当主', f.上司 === 当主.id);
    確('記に残す', (f.記 || []).some((x) => /旗頭に任じられた/.test(x.文)));
  }

  console.log('\n── 五　国主の上司は、その国を受け持つ旗頭');
  {
    const { s, 境 } = 家老の風雲(), f = s.風雲, g = H.主人公の武将(s);
    const 刈谷 = 城を移す(s, 'kariya'); 主人公を移す(s, 刈谷);
    宿老にする(s, 境);
    const 旗 = s.generals.find((x) => x.faction === s.player && !x.lord && !x.風雲の主 && x.役 !== '国主');
    旗.役 = '旗頭'; g.寄親 = 旗.id;                          // 主人公（三河の国主）を寄騎にした旗頭
    H.上司を見直す(s);
    確('国主の上司は、その国を受け持つ旗頭', f.上司 === 旗.id, 旗.name);
  }

  console.log(咎.length ? `\n★ ${咎.length}件の咎：${咎.join('／')}` : '\n確かめ：みな通った');
  console.log('エラー: なし');
  process.exit(咎.length ? 1 : 0);
})();
