/* 差配を預ける――寄騎を与えると、その城の政務は寄親が行う（GDD 6.4）。

   もとは寄騎に効き目が一つしかなかった。出陣のとき寄親に従う、それだけである。
   何のために付けるのかが定まっていなかった。

   預けたものは「毎月の政務」である。大名がいちいち下知せずとも、寄親の差配で
   開墾・治水・徴募・訓練が進む。城が二十を超えれば毎月の内政は作業になるので、
   委任はそこに効く。これが大名（遊ぶ側）にとっての利である。

   使ってよい額は「預け高」で縛る。委ねた城が生んだ実入りに、家全体で一つの
   目盛り（少なめ〇.六／並一.〇／多め一.四）を掛けたものである。金そのものは
   動かさない――財布は家に一つのままで、予算とは承認であって口座を分けることでは
   ない。会社の支社が自らの収支で回すのと同じ考えである。 */
const path = require('path');
const H = require(path.join(__dirname, '..', 'build', 'harness.cjs'));
const { initState, advanceMonth, 城の寄親, 差配を預けた城, 大名が直に見る城,
  預け高, 預けの段, 城の実入り, 国主に任じる, 寄騎に取る, 寄騎を解く, castellanOf, stipendOf } = H;

const 咎 = [];
const 確 = (名, 可, 添 = '') => {
  console.log(`  ${可 ? '○' : '★'} ${名}${添 ? '　' + 添 : ''}`);
  if (!可) 咎.push(名);
};

let 種 = 0x9a1;
Math.random = function () { 種 |= 0; 種 = (種 + 0x6D2B79F5) | 0;
  let t = Math.imul(種 ^ (種 >>> 15), 1 | 種);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };

/* 尾張に国主を一人立て、別の城の城主をその寄騎にする */
const 場 = () => {
  const s = initState('oda');
  const 自城 = s.castles.filter((c) => c.faction === 'oda' && c.kuni === '尾張');
  // 国主となれるのは家老（八千石）以上。若年は禄に頭打ちがあるので大人から選ぶ
  const 親 = s.generals.find((g) => g.faction === 'oda' && !g.lord && !g.役 && (g.age || 0) >= 25
    && 自城.some((c) => c.id === (g.本領 || g.at)));
  /* 忠誠を篤くしておく。薄いと謀反の筋（tests/muhon.cjs）に乗って走ってしまい、
     差配そのものが消えて測りが濁る。ここで見たいのは委任のほうである。 */
  親.fief = 14000; 親.age = Math.max(親.age || 30, 32); 親.loyal = 85;
  const 親城 = 自城.find((c) => c.id === (親.本領 || 親.at));
  国主に任じる(s, 'oda', '尾張', 親.id);
  /* 別の城の「城主」を寄騎に取る。差配が預けられるのは城主の寄親であって、
     城にいるだけの者ではない。 */
  const 別城 = 自城.find((c) => c.id !== 親城.id);
  const 子 = castellanOf(s, 別城);
  if (子) { 子.fief = Math.max(子.fief || 0, 3000); 子.age = Math.max(子.age || 30, 28); 子.本領 = 別城.id; 子.loyal = 85; }
  return { s, 親, 子, 親城, 別城 };
};

console.log('── 一　寄騎を与えれば、その城の差配が預けられる');
{
  const { s, 親, 子, 親城, 別城 } = 場();
  確('はじめは、どの城も大名が直に見る', 差配を預けた城(s, 'oda').length === 0,
    `預けた ${差配を預けた城(s, 'oda').length}城／直に見る ${大名が直に見る城(s, 'oda').length}城`);
  const r = 寄騎に取る(s, 親.id, 子.id);
  確('同じ国の城主を寄騎に取れる', r.ok, r.why || `${親.name} ← ${子.name}`);
  const 預 = 差配を預けた城(s, 'oda');
  確('寄騎の城は、寄親の差配下に入る',
    預.some((c) => c.id === 別城.id), 預.map((c) => c.name).join('・') || 'なし');
  確('その城の寄親が知れる', (城の寄親(s, 別城) || {}).id === 親.id,
    (城の寄親(s, 別城) || {}).name || 'なし');
  確('寄親自身の城は、大名が直に見る（寄親が誰かの寄騎でないかぎり）',
    !城の寄親(s, 親城), 親城.name);
  寄騎を解く(s, 子.id);
  確('解けば、また大名が直に見る', 差配を預けた城(s, 'oda').length === 0);
}

console.log('\n── 二　預け高は、委ねた城の実入りに目盛りを掛けたもの');
{
  const { s, 親, 子, 別城 } = 場();
  寄騎に取る(s, 親.id, 子.id);
  const 実 = 城の実入り(別城);
  for (const [段, 名] of [[0, '少なめ'], [1, '並'], [2, '多め']]) {
    s.factions.oda.預け = 段;
    const 帳 = 預け高(s, 'oda');
    const v = 帳.find((x) => x.親.id === 親.id);
    確(`${名}なら実入りの${預けの段[段].率}倍`,
      !!v && Math.abs(v.預け - 実 * 預けの段[段].率) < 1.5,
      `実入り ${Math.round(実)}貫 → 預け ${v ? v.預け : 0}貫`);
  }
}

console.log('\n── 三　委ねれば、大名が下知せずとも政務が進む');
{
  /* 委ねた城と、委ねぬ城とを同じ月数だけ送って引き比べる。
     遊ぶ側の城は、これまで采配が手を出さなかった（自ら下知するものだから）。 */
  const 走る = (委ねる) => {
    const { s, 親, 子, 別城 } = 場();
    if (委ねる) 寄騎に取る(s, 親.id, 子.id);
    s.factions.oda.gold = 30000;
    // 他家に奪われると数字が濁るので、守りを厚くしておく
    for (const c of s.castles.filter((x) => x.faction === 'oda')) { c.local = 9000; c.food = 90000; c.def = 95; }
    let u = s;
    const 前石 = 別城.koku, 前兵 = 別城.local;
    /* 政務は毎月かならず動くわけではない（采配は籤で動く）。
       月報はその月ぶんしか残らないので、月ごとに拾い集める。 */
    const 報 = [];
    for (let i = 0; i < 6; i++) {
      u = advanceMonth(u);
      報.push(...(u.monthEvents || []).filter((t) => /差配/.test(t)));
    }
    const c = u.castles.find((x) => x.id === 別城.id);
    return { 石: c.koku - 前石, 兵: c.local - 前兵, 主: c.faction, 報, u };
  };
  const 無 = 走る(false), 有 = 走る(true);
  確('六か月のあいだ城は自家のまま（測りが濁らない）', 無.主 === 'oda' && 有.主 === 'oda',
    `委ねぬ ${無.主}／委ねた ${有.主}`);
  /* 石高は放っておいても毎月わずかに増える（民が自ら田を開く。限りの〇.一五分）。
     ゆえに「伸びるか」ではなく「委ねぬときより大きく伸びるか」で測る。 */
  確('委ねた城は石高が伸びる', 有.石 > 0, `+${Math.round(有.石)}石`);
  確('委ねた城のほうが、委ねぬ城より大きく伸びる', 有.石 > 無.石 * 3,
    `委ねた +${Math.round(有.石)}石／委ねぬ +${Math.round(無.石)}石（自然増のみ）`);
  確('月報に、預けた者の収支と成果が出る', 有.報.length > 0,
    有.報[0] || '六か月のあいだ一度も差配の報せが出なかった');
  確('委ねぬ城では、差配の報せは出ない', 無.報.length === 0, `${無.報.length}件`);
}

console.log('\n── 四　預け高を超えては使わない');
{
  const { s, 親, 子 } = 場();
  寄騎に取る(s, 親.id, 子.id);
  s.factions.oda.預け = 0;                       // 少なめ
  s.factions.oda.gold = 30000;
  let u = s;
  for (let i = 0; i < 6; i++) u = advanceMonth(u);
  const 報 = (u.monthEvents || []).filter((t) => /差配/.test(t));
  // 月報の文から「預けNのうちM貫を用い」を読む
  const 読 = 報.map((t) => (t.match(/預け([\d,]+)貫のうち([\d,]+)貫/) || []).slice(1)
    .map((x) => Number(x.replace(/,/g, '')))).filter((x) => x.length === 2);
  確('使った額は、預けた額を超えない', 読.every(([預, 使]) => 使 <= 預),
    読.map(([預, 使]) => `${使}／${預}貫`).join('・') || '（この月は動きなし）');
}

console.log(`\n════ 差配を預ける：咎 ${咎.length} 件`);
console.log('エラー:', 咎.length ? 咎.join(' | ') : 'なし');
process.exit(咎.length ? 1 : 0);
