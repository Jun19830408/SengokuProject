/* 寿命（GDD 6.1）。

   人の齢は八十を常の限りとする。史実でそれを超えて生きた者だけが、その齢まで
   生きる――これが決めであった。ところが毎年の病没の目が重すぎて、決めと中身が
   食い違っていた。

     もとの目　四十八〜一.五分／五十四〜三.五分／六十〜七.五分
               七十〜十六分／（限りの四年前）〜三十四分

   これだと四十八の者が八十まで生きる見込みは二分三厘しかない。六十から七十まで
   生きる見込みでさえ四割六分――六十代で半数が病に倒れる。遊ぶ側の申し出は
   「柴田勝家が六十（一五八一年）で死去した。原則は八十まで生きるもので、
   長生きする者はそれより長く、というものだったはず」であった。

   直したあとは、病を得るのは六十を越えてからとし、目も軽くする。
   史実で没年の定まっている者（FATED）は、これまでどおりその年に没する。
   早く没してほしい者がいれば、賽を重くするのではなく FATED に名指しで書く。 */
const path = require('path');
const H = require(path.join(__dirname, '..', 'build', 'harness.cjs'));

const 咎 = [];
const 確 = (名, 可, 添 = '') => {
  console.log(`  ${可 ? '○' : '★'} ${名}${添 ? '　' + 添 : ''}`);
  if (!可) 咎.push(名);
};

/* 月送りの寿命の段と同じ目。ここを直したら、こちらも直す。 */
const 病の目 = (a) => (a >= 75 ? 0.05 : a >= 70 ? 0.028 : a >= 65 ? 0.015 : a >= 60 ? 0.008 : 0);
const 生き延びる = (から, まで) => {
  let 生 = 1;
  for (let a = から; a < まで; a++) 生 *= 1 - 病の目(a);
  return 生;
};

console.log('── 一　決めのとおり、八十が常の限りである');
{
  確('限りは八十', H.LIFE_CAP === 80, `${H.LIFE_CAP}歳`);
  /* LONG_LIVED は「史実の没年齢」の控えである。八十より長い者が大半だが、
     七十代で没した者（柳生石舟斎は七十八）も入っている。名のある者には
     史実の齢を当て、それ以外は常の限りに従わせる、という作りである。 */
  const 齢ら = Object.values(H.LONG_LIVED || {});
  確('史実の齢が定まっている者がいる', 齢ら.length > 0, `${齢ら.length}名`);
  確('その多くは八十より長い', 齢ら.filter((v) => v > H.LIFE_CAP).length > 齢ら.length / 2,
    `八十超 ${齢ら.filter((v) => v > H.LIFE_CAP).length}名・最長 ${Math.max(...齢ら)}歳`);
  const g = { id: 'f_gyuichi' };
  確('長命の者には、その齢が返る', H.lifeSpan(g) > H.LIFE_CAP, `${H.lifeSpan(g)}歳`);
  確('常の者には八十が返る', H.lifeSpan({ id: 'nobody' }) === 80);
}

console.log('\n── 二　六十より手前では、病で没しない');
{
  確('五十代に病の目は立たない', 病の目(50) === 0 && 病の目(59) === 0);
  確('六十を越えれば目が立つ', 病の目(60) > 0, `${(病の目(60) * 100).toFixed(1)}分`);
  確('老いるほど重くなる',
    病の目(60) < 病の目(65) && 病の目(65) < 病の目(70) && 病の目(70) < 病の目(75),
    [60, 65, 70, 75].map((a) => `${a}歳 ${(病の目(a) * 100).toFixed(1)}分`).join('／'));
}

console.log('\n── 三　八十まで生きるのが常である');
{
  const 六十から = 生き延びる(60, 80);
  確('六十の者の半ばは八十に届く', 六十から > 0.5, `${(六十から * 100).toFixed(0)}%`);
  const 六十代 = 生き延びる(60, 70);
  確('六十代を越える者が大半', 六十代 > 0.8, `${(六十代 * 100).toFixed(0)}%`);
  /* 直す前の目で同じ計算をすると、どれほど食い違っていたかが分かる。 */
  const 旧 = (a) => (a >= 76 ? 0.34 : a >= 70 ? 0.16 : a >= 60 ? 0.075 : a >= 54 ? 0.035 : 0.015);
  let 旧生 = 1; for (let a = 60; a < 80; a++) 旧生 *= 1 - 旧(a);
  確('直す前よりはっきり長く生きる', 六十から > 旧生 * 3,
    `いま ${(六十から * 100).toFixed(0)}% ／ 前 ${(旧生 * 100).toFixed(1)}%`);
}

console.log('\n── 四　月を送っても、六十代が病で消えてゆかない');
{
  let _s = 0x9191 >>> 0;
  Math.random = function () { _s = (_s + 0x6D2B79F5) | 0; let t = Math.imul(_s ^ (_s >>> 15), 1 | _s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
  const s = H.initState('oda');
  /* 五十五歳の者を並べ、十五年送る。討死や出奔が混じらぬよう、戦の無い家に置く。 */
  const 衆 = s.generals.filter((g) => !g.lord && !g.captive).slice(0, 60);
  for (const g of 衆) { g.age = 55; }
  const 名 = new Set(衆.map((g) => g.id));
  for (let i = 0; i < 15 * 12; i++) H.advanceMonth(s);
  const 残 = s.generals.filter((g) => 名.has(g.id) && !g.captive).length;
  確('十五年ののち（七十歳）、大半が生きている', 残 >= 衆.length * 0.6,
    `${残}／${衆.length}名`);
}

console.log(`\nエラー: ${咎.length ? 咎.join(' / ') : 'なし'}`);
process.exit(咎.length ? 1 : 0);
