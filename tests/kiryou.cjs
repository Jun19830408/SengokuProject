/* 大名の器量が家の動きを決める（GDD 6.2 / 13.2）。

   狙いは作者の言による。

     政治が高ければ　… 内政と外交に手を伸ばす
     知略が高ければ　… 調略を好む
     武勇が高ければ　… 戦を好む（ただし無駄な戦はしない）
     統率が高ければ　… その性質が家中に行き渡る

   統率だけは働きが違う。統率は「何をするか」ではなく「大名の色がどれだけ家に
   出るか」を決める。統率の低い大名は、いかに武勇があっても家中が付いてこず、
   家の動きは中庸に寄る。ここではその筋が数の上で立っているかを見る。

   地方がどれだけ絞られるかは tools/chihou.cjs で測る（走らせるのに十数分かかる
   ので試験には入れない）。 */
const path = require('path');
const H = require(path.join(__dirname, '..', 'build', 'harness.cjs'));
const { initState, 気風, 浸透, 家の当主, 攻めの腰, 要る兵力, 出せる軍の数, 調略の腰, 治めの腰, 好機か } = H;

const 咎 = [];
const 確 = (名, 可, 添 = '') => {
  console.log(`  ${可 ? '○' : '★'} ${名}${添 ? '　' + 添 : ''}`);
  if (!可) 咎.push(名);
};

/* 当主の値を差し替えて測る。器量以外は同じ盤である。 */
const 据える = (値) => {
  const s = initState('oda');
  const 主 = s.generals.find((g) => g.faction === 'oda' && g.lord);
  Object.assign(主, 値);
  return { s, 主 };
};
const 並 = { lead: 60, valor: 60, wit: 60, gov: 60 };

console.log('── 一　器量が気風に出る');
{
  const 猛 = 据える({ ...並, valor: 95, lead: 90 });
  const 温 = 据える({ ...並, valor: 35, lead: 90 });
  /* 閾値をあてずっぽうに置いても意味がない（初め −0.5 と書いて背いた。
     武勇の目盛りは四十から百に寄っているので、三十五はすでに端である）。
     見るべきは「向きが逆で、振れの大きさが釣り合っていること」である。 */
  const 猛気 = 気風(猛.s, 'oda').攻め, 温気 = 気風(温.s, 'oda').攻め;
  確('武勇が高ければ攻め気が立つ', 猛気 > 0.5, 猛気.toFixed(2));
  確('武勇が低ければ攻め気が引く', 温気 < 0 && Math.abs(温気) > 猛気 * 0.5,
    `猛 ${猛気.toFixed(2)}／温 ${温気.toFixed(2)}`);
  const 智 = 据える({ ...並, wit: 95, lead: 90 });
  確('知略が高ければ調略に傾く', 気風(智.s, 'oda').調略 > 0.5, 気風(智.s, 'oda').調略.toFixed(2));
  const 政 = 据える({ ...並, gov: 95, lead: 90 });
  確('政治が高ければ治めに傾く', 気風(政.s, 'oda').治め > 0.5, 気風(政.s, 'oda').治め.toFixed(2));
}

console.log('\n── 二　統率は「浸透」であって、好みそのものではない');
{
  const 強 = 据える({ ...並, valor: 95, lead: 95 });
  const 弱 = 据える({ ...並, valor: 95, lead: 40 });
  const a = 気風(強.s, 'oda').攻め, b = 気風(弱.s, 'oda').攻め;
  確('同じ武勇でも、統率が低ければ家に出にくい', b < a * 0.75,
    `統率95 → ${a.toFixed(2)}／統率40 → ${b.toFixed(2)}`);
  確('統率が低くても向きは変わらない（好みは同じ）', a > 0 && b > 0);
  確('浸透は統率とともに増える', 浸透(95) > 浸透(60) && 浸透(60) > 浸透(40),
    `40:${浸透(40).toFixed(2)} 60:${浸透(60).toFixed(2)} 95:${浸透(95).toFixed(2)}`);
}

console.log('\n── 三　攻めの腰と、要る兵力');
{
  const 猛 = 据える({ ...並, valor: 95, lead: 90 });
  const 温 = 据える({ ...並, valor: 35, lead: 90 });
  確('猛き大名は腰が軽い', 攻めの腰(猛.s, 'oda') > 攻めの腰(温.s, 'oda'),
    `${攻めの腰(猛.s, 'oda').toFixed(2)} ＞ ${攻めの腰(温.s, 'oda').toFixed(2)}`);
  確('猛き大名は小さい差でも仕掛ける', 要る兵力(猛.s, 'oda') < 要る兵力(温.s, 'oda'),
    `${要る兵力(猛.s, 'oda').toFixed(2)} ＜ ${要る兵力(温.s, 'oda').toFixed(2)}`);
  /* 無駄な戦はしない。どれほど猛々しくとも、五分を割る戦には出ない。 */
  確('どれほど猛くとも、五分を割る戦には出ない', 要る兵力(猛.s, 'oda') >= 1.02,
    要る兵力(猛.s, 'oda').toFixed(2));
  確('弱きに付け入る目は、腰の重さに関わらず立つ', 好機か(2000, 800) && !好機か(1000, 800),
    '倍の兵があれば狙う');
}

console.log('\n── 四　一度に出せる軍の数は家の大きさで決まる');
{
  const { s } = 据える({ ...並, lead: 60 });
  const 小 = 出せる軍の数(s, 'oda');
  for (const k of ['尾張', '美濃', '三河', '伊勢']) {
    for (const c of s.castles.filter((x) => x.kuni === k)) c.faction = 'oda';
  }
  const 大 = 出せる軍の数(s, 'oda');
  確('大身は幾手も動かせる', 大 > 小, `${s.castles.filter((c) => c.faction === 'oda').length}城で ${小} → ${大}手`);
  確('小家でも一手は出せる', 小 >= 1, `${小}手`);
  確('際限なくは増えない', 大 <= 6, `${大}手`);
}

console.log('\n── 五　調略と治めの腰');
{
  const 智 = 据える({ ...並, wit: 95, lead: 90 });
  const 武 = 据える({ ...並, wit: 35, lead: 90 });
  確('知略の高い家はよく仕掛ける', 調略の腰(智.s, 'oda') > 調略の腰(武.s, 'oda') * 1.5,
    `${調略の腰(智.s, 'oda').toFixed(2)} ／ ${調略の腰(武.s, 'oda').toFixed(2)}`);
  const 政 = 据える({ ...並, gov: 95, lead: 90 });
  const 疎 = 据える({ ...並, gov: 35, lead: 90 });
  確('政治の高い家はよく手を打つ', 治めの腰(政.s, 'oda') > 治めの腰(疎.s, 'oda') * 1.5,
    `${治めの腰(政.s, 'oda').toFixed(2)} ／ ${治めの腰(疎.s, 'oda').toFixed(2)}`);
}

console.log('\n── 六　当主を欠いた家は中庸に動く');
{
  const s = initState('oda');
  for (const g of s.generals.filter((x) => x.faction === 'oda' && x.lord)) g.lord = false;
  確('当主が居なければ気風は零', 気風(s, 'oda').攻め === 0 && 気風(s, 'oda').調略 === 0);
  確('それでも軍は出せる（盤が止まらない）', 出せる軍の数(s, 'oda') >= 1);
  確('当主を欠いても腰は中庸', 攻めの腰(s, 'oda') > 0.3 && 攻めの腰(s, 'oda') < 0.6,
    攻めの腰(s, 'oda').toFixed(2));
}

console.log('');
if (咎.length) { console.log('★背いた事:'); for (const x of 咎) console.log('   ' + x); }
console.log('エラー:', 咎.length ? `${咎.length}件` : 'なし');
process.exit(咎.length ? 1 : 0);
