/* 音（GDD 15.4）。

   盤に調べを添えた。政務は位で替わり（守護代の頃・関白・征夷大将軍）、戦は野と城で
   分かれ、天下分け目だけは別に立てる。録音は持ち込まず、その場で合成する。

   音の出ない所（試験・古い端末）でも盤が壊れてはならないので、鳴らす口は差し替え
   られるようにしてある。ここでは「鳴らした事だけを控える口」を据えて、次を検める。

     一、曲が揃い、音階の外れた音を鳴らさない
     二、場面で曲が替わる（位による政務の三つを含む）
     三、遊ぶ側が触れるまで鳴らさない（携帯の決まり）
     四、切れば止まり、入れれば戻る。入切と音量は棚に残る
     五、音の座が無くとも、盤は倒れない */
const path = require('path');
const H = require(path.join(__dirname, '..', 'build', 'harness.cjs'));

const 咎 = [];
const 確 = (名, 可, 添 = '') => {
  console.log(`  ${可 ? '○' : '★'} ${名}${添 ? '　' + 添 : ''}`);
  if (!可) 咎.push(名);
};

/* 棚（localStorage）の代わり。 */
const 棚 = (() => {
  const m = new Map();
  return { getItem: (k) => (m.has(k) ? m.get(k) : null), setItem: (k, v) => m.set(k, String(v)), removeItem: (k) => m.delete(k) };
})();
global.localStorage = 棚;

console.log('■ 一、六つの曲が揃っている');
{
  const 名ら = Object.keys(H.曲);
  確('政務三つと、野戦・城攻め・天下分け目', 名ら.length === 6
    && ['政務', '関白', '将軍', '野戦', '城攻め', '分け目'].every((k) => 名ら.includes(k)), 名ら.join('・'));
  let 外れ = [], 音符数 = {};
  for (const [名, k] of Object.entries(H.曲)) {
    let n = 0;
    for (let i = 0; i < k.小節; i++) {
      for (const q of k.音符(i)) {
        n++;
        if (!H.楽器[q.楽器]) 外れ.push(`${名}：${q.楽器}という楽器は無い`);
        if (!(q.音 >= 24 && q.音 <= 96)) 外れ.push(`${名}：音の高さ ${q.音} は鳴らせぬ`);
        if (!(q.長 > 0) || !(q.強 > 0)) 外れ.push(`${名}：長さか強さが無い`);
        // 太鼓と鉦のほかは、その曲の音階の上にあること
        if (!['太鼓', '鉦'].includes(q.楽器)) {
          const 階 = k.音階.map((x) => ((x % 12) + 12) % 12);
          if (!階.includes(((q.音 % 12) + 12) % 12)) 外れ.push(`${名}：${q.音} は音階の外`);
        }
      }
    }
    音符数[名] = n;
  }
  確('音階も楽器も外れがない', 外れ.length === 0, 外れ.slice(0, 3).join('／') || Object.entries(音符数).map(([k, v]) => `${k}${v}`).join('・'));
  const 一巡 = Object.entries(H.曲).map(([名, k]) => `${名}${(k.小節 * k.拍子 * 60 / k.拍).toFixed(0)}秒`);
  確('どの曲も一巡が七秒から四十秒に収まる',
    Object.values(H.曲).every((k) => { const s = k.小節 * k.拍子 * 60 / k.拍; return s >= 6 && s <= 40; }), 一巡.join('・'));
}

console.log('■ 二、場面で曲が替わる');
{
  確('政務は位で三つに分かれる',
    H.場面の曲('政務', {}) === '政務'
    && H.場面の曲('政務', { 位: '関白' }) === '関白'
    && H.場面の曲('政務', { 位: '征夷大将軍' }) === '将軍');
  確('戦は野・城・天下分け目に分かれる',
    H.場面の曲('野戦') === '野戦' && H.場面の曲('城攻め') === '城攻め' && H.場面の曲('分け目') === '分け目');
  確('盤の姿からも場面が決まる',
    H.盤の場面({ 画面: 'map', 位: '関白' }).場面 === '政務'
    && H.盤の場面({ 合戦: { mode: 'castle' } }).場面 === '城攻め'
    && H.盤の場面({ 合戦: { 分け目: true } }).場面 === '分け目');
}

console.log('■ 三、触れるまでは鳴らさない');
{
  const 口 = H.覚える口(0);
  H.口を据える(口);
  H.入切(true);
  H.掛ける('政務');
  H.刻む();
  確('解錠の前は一音も出さない', 口.控え.length === 0, `${口.控え.length}音`);
  H.解錠する(() => { throw new Error('座は作らせない'); });   // 口があるので座は要らない
  H.掛ける('政務');
  const 積 = H.刻む();
  確('解錠のあとは先読みのぶんが積まれる', 口.控え.length > 0, `${口.控え.length}音（${H.先読み}秒ぶん）`);
  確('積んだ音は、いまより先の時刻に置かれる', 口.控え.every((x) => x.時 >= 0));
  const 使った = [...new Set(口.控え.map((x) => x.楽器))];
  確('政務の調べは琴と尺八で鳴る', 使った.includes('琴'), 使った.join('・'));
}

console.log('■ 四、場面を替えれば曲が替わる');
{
  const 口 = H.覚える口(100);
  H.口を据える(口);
  H.場面を選ぶ('野戦');
  口.進める(1); H.刻む();
  const 野 = [...new Set(口.控え.map((x) => x.楽器))];
  確('野戦には太鼓が入る', 野.includes('太鼓'), 野.join('・'));
  確('いま掛かっている曲が控えられる', H.音の設定().曲 === '野戦', H.音の設定().曲 || 'なし');
  H.場面を選ぶ('政務', { 位: '征夷大将軍' });
  確('政務（将軍）へ替わる', H.音の設定().曲 === '将軍', H.音の設定().曲 || 'なし');
  H.場面を選ぶ('分け目');
  確('天下分け目へ替わる', H.音の設定().曲 === '分け目', H.音の設定().曲 || 'なし');
}

console.log('■ 五、切れば止まり、棚に残る');
{
  const 口 = H.覚える口(200);
  H.口を据える(口);
  H.場面を選ぶ('城攻め');
  口.進める(1); H.刻む();
  const 前 = 口.控え.length;
  確('城攻めの調べが鳴る', 前 > 0, `${前}音`);
  H.入切(false);
  口.進める(2); H.刻む();
  確('切れば、それ以上は積まれない', 口.控え.length === 前, `${口.控え.length}音`);
  確('切ったことが棚に残る', /"入":false/.test(棚.getItem(H.音の棚の鍵) || ''), 棚.getItem(H.音の棚の鍵) || 'なし');
  H.音量(0.3);
  確('音量も棚に残る', /0\.3/.test(棚.getItem(H.音の棚の鍵) || ''), 棚.getItem(H.音の棚の鍵) || 'なし');
  H.入切(true);
  口.進める(1); H.刻む();
  確('入れ直せば、また鳴る', 口.控え.length > 前, `${口.控え.length}音`);
}

console.log('■ 六、音の座が無くとも盤は倒れない');
{
  H.口を据える(null);
  let 倒れず = true;
  try {
    H.解錠する(null);          // 作り手が無い（古い端末・試験）
    H.場面を選ぶ('野戦');
    H.刻む();
    H.入切(false); H.入切(true);
  } catch (e) { 倒れず = false; }
  確('座を作れずとも、例外を投げない', 倒れず);
}

console.log('');
if (咎.length) { console.log('★背いた事:'); for (const x of 咎) console.log('   ' + x); }
console.log('エラー:', 咎.length ? `${咎.length}件` : 'なし');
process.exit(咎.length ? 1 : 0);
