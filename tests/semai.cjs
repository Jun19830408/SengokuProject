/* 狭い縦画面で、合戦の道具立てが盤に収まって押せるか（GDD 8.1）。

   ここだけは本物の Chrome で測る。ほかの試験は jsdom で走らせているが、
   jsdom には配置（layout）が無い。釦が盤からはみ出しているかどうかは、
   実際に並べてみなければ分からない。tests/shimau.cjs が「しまう仕掛けが
   動くか」を確かめても、「そもそも釦が見えて押せるか」を見逃したのは
   このためである。

   また Chrome の --window-size は幅を五百より狭くできない。四三〇と書いても
   開くのは五百である。よって遊びを iframe に入れ、iframe の幅を狭める。
   差し金（media query）は iframe の幅で決まるので、これで実機の狭さになる。

   測る組（実測、直す前 → 直したあと）

     幅×丈      盤の丈        「広く」の下端    収まり
     393×852   484 → 536     425 → 116        ○ → ○
     393×580   280 → 283     425 → 116        ★はみ出す → ○

   直す前は釦を縦に五つ積んでいたので、列の丈が三〇五要った。盤がそれより
   低いと下の「広く」が外へ出る。外へ出た釦は盤の枠（overflow:hidden）に
   切られ、押しても届かない。しまう釦が切れるので、しまうこともできない。

   狭いときは横に寝かせた。列の丈は四二で足りるので、盤の丈に縛られない。 */
const path = require('path');
const { 検分する } = require(path.join(__dirname, '..', 'tools', 'semai.cjs'));

const 咎 = [];
const 確 = (名, 可, 添 = '') => {
  console.log(`  ${可 ? '○' : '★'} ${名}${添 ? '　' + 添 : ''}`);
  if (!可) 咎.push(名);
};

/* 852 は iPhone の縦、580 は帯や欄が伸びて盤が痩せたとき。
   後者が、直す前に釦の切れた丈である。 */
const 組ら = [{ 幅: 393, 高: 852 }, { 幅: 393, 高: 580 }];
const 結ら = 検分する(組ら);

for (const r of 結ら) {
  const 頭 = `${r.幅}×${r.高}`;
  確(`${頭}　盤（canvas）が出ている`, !!r.盤, r.盤 ? `丈 ${r.盤の丈}` : '');
  確(`${頭}　道具立ての釦が五つとも有る`, r.釦.length === 5 && r.釦.every((b) => b.有));
  const はみ = r.釦.filter((b) => b.有 && !b.収).map((b) => b.名);
  確(`${頭}　どの釦も盤からはみ出さない`, はみ.length === 0, はみ.length ? `はみ出す：${はみ.join('・')}` : '');
  const 届かぬ = r.釦.filter((b) => b.有 && !b.届).map((b) => b.名);
  確(`${頭}　どの釦も押せば届く`, 届かぬ.length === 0, 届かぬ.length ? `届かぬ：${届かぬ.join('・')}` : '');
  確(`${頭}　「広く」でしまえる`, r.しまえた === true);
  確(`${頭}　しまったあと取っ手で戻せる`, r.取っ手 === true && r.戻せた === true);
  確(`${頭}　盤が画面の四割より広い`, !!r.盤 && r.盤の丈 >= r.高 * 0.42, r.盤 ? `${r.盤の丈}／${r.高}` : '');
}

// 帯は二行までに収める（三行に折り返すと盤を圧す）
for (const r of 結ら) {
  確(`${r.幅}×${r.高}　上の帯が二行に収まる`, r.帯の丈 > 0 && r.帯の丈 <= 70, `丈 ${r.帯の丈}`);
}

console.log(`\n════ 狭い縦画面：咎 ${咎.length} 件`);
console.log('エラー:', 咎.length ? 咎.join(' | ') : 'なし');
process.exit(咎.length ? 1 : 0);
