/* 横に持った携帯で、遊べる範囲が残っているか（GDD 15.1）。

   差し金（media query）を幅だけで書いていたので、横持ちでは道具立てが縦に
   積まれたままであった。幅は八百あっても丈は四百を切るので、列が盤からはみ出し、
   下の釦は押せない。政務の地図では右の列が九つあり、日本全土の小図とも重なる。

   測る組（実測、直す前 → 直した後）

     844×390　はみ出す・押せぬ・重なる釦　6 → 0
     844×330　　　　　　　　　　　　　　　8 → 0

   丈が足りないときは、政務の地図も合戦の盤も道具立てを横に寝かせ、小図は
   左下へ移した（右の列とぶつかっていた）。 */
const path = require('path');
const { 測る: 地図を測る } = require(path.join(__dirname, '..', 'tools', 'kasanari.cjs'));
const { 測る: 城攻めを測る } = require(path.join(__dirname, '..', 'tools', 'shiro-semai.cjs'));

const 咎 = [];
const 確 = (名, 可, 添 = '') => {
  console.log(`  ${可 ? '○' : '★'} ${名}${添 ? '　' + 添 : ''}`);
  if (!可) 咎.push(名);
};

console.log('── 一　政務の地図（横持ち・タブありの丈）');
for (const [幅, 高] of [[844, 390], [844, 330], [393, 852]]) {
  const r = 地図を測る(幅, 高);
  const 頭 = `${幅}×${高}`;
  確(`${頭}　釦が揃っている`, (r.釦 || []).length >= 10, `${(r.釦 || []).length}個`);
  const はみ = (r.釦 || []).filter((b) => !b.収).map((b) => b.名);
  確(`${頭}　盤からはみ出す釦がない`, はみ.length === 0, はみ.join('・') || 'なし');
  const 届かぬ = (r.釦 || []).filter((b) => !b.届).map((b) => b.名);
  確(`${頭}　押せぬ釦がない`, 届かぬ.length === 0, 届かぬ.join('・') || 'なし');
  const 重 = (r.釦 || []).filter((b) => b.小図と重なる).map((b) => b.名);
  確(`${頭}　日本全土の小図と重なる釦がない`, 重.length === 0, 重.join('・') || 'なし');
  確(`${頭}　盤が画面の四割五分は残る`, r.盤の丈 >= r.高 * 0.45,
    `盤の丈 ${r.盤の丈}／画面 ${r.高}`);
}

console.log('\n── 二　城攻めの盤（横持ち・タブありの丈）');
for (const [幅, 高] of [[844, 390], [844, 330]]) {
  const r = 城攻めを測る(幅, 高);
  const 頭 = `${幅}×${高}`;
  const 広 = (r.釦 || []).find((b) => b.名 === '広く');
  確(`${頭}　「広く」がある`, !!広 && 広.有);
  確(`${頭}　「広く」が盤に収まる`, !広 || 広.収, 広 ? `下 ${広.下}` : '');
  確(`${頭}　「広く」が押せる`, !広 || 広.届);
  確(`${頭}　押せば道具立てがしまわれる`, !!r.しまえた);
  確(`${頭}　取っ手で戻せる`, !!r.戻せた);
}

console.log('');
if (咎.length) { console.log('★背いた事:'); for (const x of 咎) console.log('   ' + x); }
console.log('エラー:', 咎.length ? `${咎.length}件` : 'なし');
process.exit(咎.length ? 1 : 0);
